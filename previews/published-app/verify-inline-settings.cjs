/* eslint-disable @typescript-eslint/no-require-imports -- Node browser verification. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      page.setDefaultTimeout(12000)
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.goto('http://127.0.0.1:3199/odeon-demo/school-setup?experience=configured&section=school')
      const main = page.locator('main'), nav = page.getByRole('navigation', { name: 'School setup sections' })
      const save = main.getByRole('button', { name: 'Save changes', exact: true })
      await main.getByLabel('School name', { exact: true }).waitFor()
      assert.equal(await save.count(), 0)
      await main.getByLabel('School name', { exact: true }).fill('Independent Academy')
      await save.click()
      assert.equal(await save.count(), 0)
      await nav.getByRole('button', { name: 'Curriculum', exact: true }).click()
      const level = main.getByLabel('Level 1 name', { exact: true })
      await level.fill('Foundation')
      await save.click()
      assert.equal(await save.count(), 0)
      await main.getByRole('button', { name: 'Add material', exact: true }).click()
      await main.getByRole('button', { name: 'Cancel material', exact: true }).click()
      assert.equal(await level.inputValue(), 'Foundation')
      const checkbox = main.getByRole('checkbox', { name: 'Level 3', exact: true })
      await checkbox.uncheck()
      await checkbox.check()
      assert.equal(await save.count(), 0, 'Reverting a setting clears unsaved state')
      await nav.getByRole('button', { name: 'Plans & prices', exact: true }).click()
      const combination = main.getByLabel('When multiple discounts qualify', { exact: true })
      await combination.selectOption('combine')
      await main.getByLabel('Apply discounts in this order', { exact: true }).selectOption('fixed-first')
      await save.click()
      assert.equal(await save.count(), 0)
      await nav.getByRole('button', { name: 'School details', exact: true }).click()
      assert.equal(await main.getByLabel('School name', { exact: true }).inputValue(), 'Independent Academy')
      await nav.getByRole('button', { name: 'Curriculum', exact: true }).click()
      assert.equal(await level.inputValue(), 'Foundation')
      await level.fill('Unsaved name')
      page.once('dialog', dialog => dialog.dismiss())
      await nav.getByRole('button', { name: 'School details', exact: true }).click()
      assert.equal(await level.inputValue(), 'Unsaved name', 'Declining discard retains the draft')
      page.once('dialog', dialog => dialog.accept())
      await nav.getByRole('button', { name: 'Plans & prices', exact: true }).click()
      assert.equal(await combination.inputValue(), 'combine')
      assert.equal(await main.getByLabel('Apply discounts in this order', { exact: true }).inputValue(), 'fixed-first')
      await nav.getByRole('button', { name: 'Curriculum', exact: true }).click()
      assert.equal(await level.inputValue(), 'Foundation')
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: directly editable school, progression and discount settings; save, revert, material access and discard protection`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })