/* eslint-disable @typescript-eslint/no-require-imports -- Node browser verification script. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      const errors = []; page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(12000)
      await page.goto('http://127.0.0.1:3199/odeon-demo/school-setup?experience=configured&section=plans')
      const main = page.locator('main'), nav = page.getByRole('navigation', { name: 'School setup sections' })
      await main.getByRole('button', { name: /Edit Monthly subscription/ }).first().click()
      assert.equal(await main.getByRole('button', { name: 'Add lesson length', exact: true }).count(), 0)
      await main.getByRole('heading', { name: 'Lesson prices (USD)', exact: true }).waitFor()
      await main.getByLabel('Price for 45 minutes (USD)', { exact: true }).fill('55')
      await main.getByLabel('Price for 60 minutes (USD)', { exact: true }).fill('75')
      await main.getByRole('button', { name: 'Save changes', exact: true }).click()
      await main.getByRole('heading', { name: /60 min · \$75.00/ }).waitFor()
      await main.getByRole('button', { name: 'Add discount', exact: true }).click()
      const qualify = await main.getByLabel('Qualify when', { exact: true }).boundingBox()
      const condition = await main.getByRole('heading', { name: 'Condition 1', exact: true }).boundingBox()
      assert.ok(condition.y - qualify.y - qualify.height >= 18, 'Discount conditions remain clearly separated')
      await page.screenshot({ path: `/tmp/odeon-discount-spacing-${width}.png`, fullPage: true })
      await main.getByRole('button', { name: 'Cancel discount', exact: true }).click()
      await nav.getByRole('button', { name: 'Teachers', exact: true }).click()
      await main.getByRole('button', { name: 'Edit Maya Chen', exact: true }).click()
      for (const title of ['Contact details', 'Teaching assignments', 'Schedule']) await main.getByRole('heading', { name: title, exact: true }).waitFor()
      const assignmentRow = main.locator('[data-teaching-assignment]').filter({ has: page.getByRole('checkbox', { name: 'Guitar', exact: true }) })
      const before = await assignmentRow.boundingBox()
      await assignmentRow.getByRole('checkbox').check()
      const after = await assignmentRow.boundingBox()
      assert.equal(after.height, before.height, 'Assignment row height stays fixed when checked')
      await assignmentRow.getByRole('checkbox').uncheck()
      await main.getByLabel('Teacher phone', { exact: true }).fill('2025550123')
      await main.getByRole('slider', { name: 'Piano maximum level' }).fill('2')
      await main.getByRole('button', { name: 'Teacher locations', exact: true }).click()
      await main.getByRole('option', { name: 'Headliner Music Academy', exact: true }).waitFor()
      await page.keyboard.press('Escape')
      assert.equal(await main.getByLabel(/^Availability \d+ starts$/).count(), 0)
      assert.equal(await main.getByRole('combobox', { name: 'Preview access' }).count(), 0)
      await main.getByRole('region', { name: 'Weekly availability', exact: true }).waitFor()
      if (width === 1440) {
        const sunday = main.getByLabel('Sunday availability grid', { exact: true })
        await sunday.evaluate(element => element.scrollIntoView({ block: 'start', inline: 'end' }))
        const bounds = await sunday.boundingBox()
        const x = bounds.x + bounds.width / 2
        const y = bounds.y + 120
        const drag = async (from, to) => {
          await page.mouse.move(x, from); await page.mouse.down()
          await page.mouse.move(x, to, { steps: 8 }); await page.mouse.up()
        }
        await drag(y, y + 120)
        await main.getByRole('button', { name: 'Edit Sunday availability 07:00–08:00', exact: true }).waitFor()
        await drag(y + 65, y + 125)
        await main.getByRole('button', { name: 'Edit Sunday availability 07:30–08:30', exact: true }).waitFor()
        await drag(y + 177, y + 237)
        await main.getByRole('button', { name: 'Edit Sunday availability 07:30–09:00', exact: true }).click()
        await page.getByRole('dialog', { name: 'Edit availability' }).getByRole('button', { name: 'Remove availability', exact: true }).click()
      }
      await main.getByRole('button', { name: 'Add availability', exact: true }).click()
      const availability = page.getByRole('dialog', { name: 'Edit availability' })
      const dateValue = await availability.getByLabel('Date', { exact: true }).inputValue()
      const sundayDate = new Date(`${dateValue}T12:00:00Z`); sundayDate.setUTCDate(sundayDate.getUTCDate() + 6)
      await availability.getByLabel('Date', { exact: true }).fill(sundayDate.toISOString().slice(0, 10))
      await availability.getByRole('button', { name: 'Save availability', exact: true }).click()
      await main.getByRole('button', { name: 'Edit Sunday availability 12:00–13:00', exact: true }).waitFor()
      await main.getByRole('button', { name: 'Next week', exact: true }).click()
      assert.equal(await main.getByRole('button', { name: 'Edit Sunday availability 12:00–13:00', exact: true }).count(), 1, 'Weekly availability carries forward')
      await main.getByRole('button', { name: 'Previous week', exact: true }).click()
      await main.getByRole('button', { name: 'Edit Sunday availability 12:00–13:00', exact: true }).waitFor()
      await main.getByLabel('Preferred rest break', { exact: true }).selectOption('30')
      await main.getByLabel('Preferred meal break', { exact: true }).selectOption('45')
      await main.getByRole('button', { name: 'Add Time Off', exact: true }).click()
      const off = page.getByRole('dialog', { name: 'Add time off', exact: true })
      assert.equal(await off.getByLabel('Time-off name', { exact: true }).count(), 0)
      await off.getByLabel('Sick leave', { exact: true }).check()
      const firstDate = await off.getByLabel('From date', { exact: true }).inputValue()
      const lastDate = new Date(`${firstDate}T12:00:00Z`); lastDate.setUTCDate(lastDate.getUTCDate() + 8)
      await off.getByLabel('Through date', { exact: true }).fill(lastDate.toISOString().slice(0, 10))
      await off.getByRole('button', { name: 'Save time off', exact: true }).click()
      assert.equal(await main.getByRole('button', { name: /^Edit time off Sick leave/ }).count(), 7)
      assert.equal(await main.getByRole('button', { name: /^Edit Monday availability/ }).count(), 0)
      await main.getByRole('button', { name: 'Next week', exact: true }).click()
      assert.equal(await main.getByRole('button', { name: /^Edit time off Sick leave/ }).count(), 2)
      await main.getByRole('button', { name: /^Edit time off Sick leave/ }).first().click()
      assert.equal(await page.getByRole('dialog', { name: 'Edit time off', exact: true }).getByLabel('Sick leave', { exact: true }).isChecked(), true)
      await page.getByRole('dialog', { name: 'Edit time off', exact: true }).getByRole('button', { name: 'Remove time off', exact: true }).click()
      await main.getByRole('button', { name: 'Previous week', exact: true }).click()
      assert.equal(await main.getByLabel('Calendar changes apply to', { exact: true }).count(), 0)
      await main.getByRole('button', { name: 'Next week', exact: true }).click()
      await main.getByRole('button', { name: 'Edit Sunday availability 12:00–13:00', exact: true }).click()
      await page.getByRole('dialog', { name: 'Edit availability' }).getByRole('button', { name: 'Remove availability', exact: true }).click()
      await main.getByRole('button', { name: 'Previous week', exact: true }).click()
      assert.equal(await main.getByRole('button', { name: 'Edit Sunday availability 12:00–13:00', exact: true }).count(), 1)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      await page.screenshot({ path: `/tmp/odeon-teacher-onboarding-${width}.png`, fullPage: true })
      await main.getByRole('button', { name: 'Save changes', exact: true }).click()
      await main.getByRole('button', { name: 'Edit Maya Chen', exact: true }).waitFor()
      await main.getByRole('button', { name: 'Edit Maya Chen', exact: true }).click()
      await main.getByRole('button', { name: 'Edit Sunday availability 12:00–13:00', exact: true }).waitFor()
      await main.getByRole('button', { name: 'Next week', exact: true }).click()
      assert.equal(await main.getByRole('button', { name: 'Edit Sunday availability 12:00–13:00', exact: true }).count(), 0)
      assert.equal(await main.getByLabel('Preferred rest break', { exact: true }).inputValue(), '30')
      assert.equal(await main.getByLabel('Preferred meal break', { exact: true }).inputValue(), '45')
      await main.getByRole('button', { name: 'Cancel', exact: true }).click()
      await nav.getByRole('button', { name: 'Calendar', exact: true }).click()
      await main.getByRole('button', { name: 'Add holiday', exact: true }).click()
      await main.getByLabel('Closure 1 name', { exact: true }).waitFor()
      assert.equal(await main.getByLabel(/lesson treatment/i).count(), 0)
      const nameBox = await main.getByLabel('Closure 1 name', { exact: true }).boundingBox()
      const dateBox = await main.getByLabel('Closure 1 from', { exact: true }).boundingBox()
      assert.ok(dateBox.y - nameBox.y - nameBox.height >= 18, 'Closure rows remain separated in the compact layout')
      assert.equal(await main.getByRole('button', { name: 'Review closure impact', exact: true }).count(), 0)
      assert.doesNotMatch(await page.locator('body').innerText(), /prototype|mock|preview experience|changes remain local|access-level/i)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      await page.screenshot({ path: `/tmp/odeon-closure-editor-${width}.png`, fullPage: true })
      await main.getByRole('button', { name: 'Save changes', exact: true }).click()
      assert.equal(await main.getByRole('button', { name: 'Save changes', exact: true }).count(), 0)
      await page.screenshot({ path: `/tmp/odeon-closures-${width}.png`, fullPage: true })
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: duration rates, teacher contact/levels/availability and holiday closures save; no implementation copy or page overflow`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })