  assert.equal(otherTeacher.students.find(item => item.id === 'preview:sophie').enrollments.find(item => item.id === lesson.enrollmentId).teacher, 'Nina Patel')
  const past = otherTeacher.lessons.find(item => item.enrollmentId === lesson.enrollmentId && item.date === '2026-11-03')
  assert.equal(past.teacher, 'Jordan Vale')
  assert.throws(() => reschedulePreviewSubscription(data, state, 'preview:kim', state.items.find(item => item.booking).id, { date: '2026-11-13', time: '14:00', teacher: 'Nina Patel', program: 'Piano' }), /active weekly subscription/)
