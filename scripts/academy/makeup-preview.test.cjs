  assert.equal(JSON.stringify(data), before)
  assert.equal(JSON.stringify(state), stateBefore)
  const past = data.lessons.find(item => item.enrollmentId === lesson.enrollmentId && item.date === '2026-11-03')
  assert.equal(result.lessons.find(item => item.id === past.id).time, past.time)
  const expanded = expandPreviewCalendar(result, '2028-05-05')
  const future = expanded.lessons.filter(item => item.enrollmentId === lesson.enrollmentId && (item.originalDate || item.date) >= '2026-11-10')
  assert.ok(future.every(item => new Date(`${item.date}T12:00:00Z`).getUTCDay() === 4 && item.time === '14:00'))
  assert.equal(new Set(future.map(item => item.originalDate || item.date)).size, future.length)
  assert.equal(expandPreviewCalendar(expanded, '2028-05-05').lessons.length, expanded.lessons.length)
