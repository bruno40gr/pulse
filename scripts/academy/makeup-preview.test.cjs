  const expanded = expandPreviewCalendar(next.data, '2027-05-05')
  assert.ok(!expanded.lessons.some(item => item.enrollmentId === lesson.enrollmentId && item.date === '2026-11-10'))
  assert.throws(() => movePreviewLesson(data, state, 'preview:alex-account', lesson.id, slot))
  assert.throws(() => movePreviewLesson(data, state, 'preview:kim', lesson.id, { ...slot, program: 'Guitar' }))
