test('invoice builder issues future months across subscriptions with optional payer and independent recipient', () => {
  const { buildSubscriptionInvoice, invoiceMonthCoverage, issueMonthlyInvoice } = load('academy-family-preview')
  const { invoiceDocument, invoicePdf } = load('academy-invoice-document')
  const data = createFamilyPreview(), before = JSON.stringify(data)
  const action = { kind: 'build-invoice', accountId: kim, id: 'FUTURE', studentId: 'preview:sophie', enrollmentIds: ['preview:sophie-piano', 'preview:sophie-voice'], periods: ['2027-01', '2027-02', '2027-03'], billTo: 'Arts Foundation', billingDetails: 'Funding reference 42', date: '2026-11-08', due: '2026-12-08' }
  const draft = buildSubscriptionInvoice(data, action)
  assert.equal(JSON.stringify(data), before)
  assert.equal(draft.lines.length, 6)
  assert.equal(invoiceTotal(draft), 132000)
  assert.equal(draft.payerId, '')
  assert.equal(draft.billTo, 'Arts Foundation')
  const next = applyFamilyAction(data, action)
  assert.equal(next.invoices.find(invoice => invoice.id === 'FUTURE').status, 'Open')
  assert.deepEqual(next.students, data.students)
  for (const enrollmentId of action.enrollmentIds) for (const period of action.periods) {
    assert.equal(invoiceMonthCoverage(next, enrollmentId, period).length, 1)
    assert.throws(() => issueMonthlyInvoice(next, { id: 'AUTO', accountId: kim, enrollmentId, periods: [period], quantity: 4, date: action.date, due: action.due }), /already invoiced/)
  }
  assert.match(invoiceDocument(draft), /Arts Foundation/)
  assert.match(invoicePdf(draft), /Funding reference 42/)
  const assigned = buildSubscriptionInvoice(data, { ...action, payerId: sam })
  assert.equal(assigned.payerId, sam)
  assert.equal(assigned.billTo, 'Arts Foundation')
  const paid = applyFamilyAction(next, { kind: 'pay-invoice', accountId: kim, invoiceId: 'FUTURE', payerId: sam, cardId: 'preview:visa' })
  assert.equal(paid.invoices.find(invoice => invoice.id === 'FUTURE').paidById, sam)
  assert.equal(paid.invoices.find(invoice => invoice.id === 'FUTURE').billTo, 'Arts Foundation')
  assert.throws(() => applyFamilyAction(paid, { ...action, id: 'DUPLICATE' }), /already paid/)
  const refunded = applyFamilyAction(paid, { kind: 'refund-invoice', accountId: kim, invoiceId: 'FUTURE', reason: 'Correction' })
  assert.throws(() => applyFamilyAction(refunded, { ...action, id: 'DUPLICATE' }), /refunded/)
  assert.throws(() => applyFamilyAction(data, action, { role: 'parent' }), /Only staff/)
  for (const patch of [{ enrollmentIds: [] }, { periods: [] }, { periods: ['2027-01', '2027-01'] }, { enrollmentIds: ['preview:ethan-guitar'] }, { payerId: 'outside' }, { due: '2026-02-30' }, { due: '2026-01-01' }]) assert.throws(() => applyFamilyAction(data, { ...action, ...patch }))
})
