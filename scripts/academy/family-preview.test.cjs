test('invoice PDF has valid object offsets, escaped text, pagination and total', () => {
  const { invoicePdf, invoiceStatus } = load('academy-invoice-document')
  const { studentFamilyProjection } = load('academy-family-preview')
  const data = createFamilyPreview()
  const invoice = studentFamilyProjection(data, data.accounts[0], 'preview:sophie').invoices[0]
  const pdf = invoicePdf({ ...invoice, payerName: 'Sam (Kim) \\ Family' })
  assert.ok(pdf.startsWith('%PDF-1.4'))
  assert.match(pdf, /Total: \$200\.00/)
  assert.ok(pdf.includes('Sam \\(Kim\\) \\\\ Family'))
  assert.ok(!pdf.includes('Ethan'))
  const xref = Number(pdf.match(/startxref\n(\d+)/)[1])
  assert.equal(pdf.slice(xref, xref + 4), 'xref')
  const entries = pdf.slice(xref).split('\n')
  const count = Number(entries[1].split(' ')[1])
  for (let id = 1; id < count; id++) assert.ok(pdf.slice(Number(entries[id + 2].slice(0, 10))).startsWith(`${id} 0 obj`))
  const long = invoicePdf({ ...invoice, lines: Array.from({ length: 100 }, () => invoice.lines[0]) })
  assert.ok(Number(long.match(/\/Count (\d+)/)[1]) > 1)
  assert.equal(invoiceStatus({ ...invoice, status: 'Open', due: '2026-11-01' }), 'Overdue')
  assert.equal(invoiceStatus({ ...invoice, status: 'Paid' }), 'Paid')
  assert.equal(invoiceStatus({ ...invoice, status: 'Open', due: '2026-11-10' }), 'Open')
})
