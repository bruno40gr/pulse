/* eslint-disable @typescript-eslint/no-require-imports -- Pure editor validation tests. */
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const domain = {}
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.resolve(__dirname, '../../app/content-studio-prototype/school-setup/policy-content.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: domain })
test('new academy policy draft does not inherit Headliner defaults', () => {
 const values = domain.policyEditorValues({ name: 'School defaults' })
 assert.equal(values.timelyAction, '')
 assert.equal(values.plannedClosure, undefined)
 assert.equal(values.notice, undefined)
 assert.equal(domain.validatePolicyDraft(values), null)
})
test('legacy cancellation choices survive migration without inventing expiry days', () => {
 const values = domain.policyEditorValues({ timely: 'Issue a makeup', late: 'No makeup', expiry: '6' })
 assert.equal(values.timelyAction, 'Issue a makeup')
 assert.equal(values.lateAction, 'Forfeit lesson')
 assert.equal(values.makeupExpiryDays, undefined)
 assert.equal(domain.policyEditorValues({ timely: 'Issue a makeup', timelyAction: 'Reschedule' }).timelyAction, 'Reschedule')
})
test('only enabled conditional fields are required', () => {
 assert.ok(domain.validatePolicyDraft({ makeupExpiry: 'After a number of days' }))
 assert.equal(domain.validatePolicyDraft({ makeupExpiry: 'After a number of days', makeupExpiryDays: '90' }), null)
 assert.equal(domain.validatePolicyDraft({ makeupExpiry: 'No expiry', makeupExpiryDays: '-1' }), null)
 assert.ok(domain.validatePolicyDraft({ makeupLimit: '2' }))
 assert.equal(domain.validatePolicyDraft({ makeupLimit: '2', makeupPeriod: 'Month' }), null)
 assert.ok(domain.validatePolicyDraft({ freezeFee: 'Charge a fee', freezeFeeAmount: '0', freezeFeeBasis: 'Once per pause' }))
 assert.ok(domain.validatePolicyDraft({ freezeFee: 'Charge a fee', freezeFeeAmount: '15.123', freezeFeeBasis: 'Once per pause' }))
 assert.equal(domain.validatePolicyDraft({ freezeFee: 'Charge a fee', freezeFeeAmount: '15', freezeFeeBasis: 'Once per pause' }), null)
 assert.ok(domain.validatePolicyDraft({ withdrawal: 'After a notice period', withdrawalDays: '0' }))
 assert.equal(domain.validatePolicyDraft({ withdrawal: 'After a notice period', withdrawalDays: '30' }), null)
 assert.equal(domain.validatePolicyDraft({ withdrawal: 'Immediately', withdrawalDays: '0' }), null)
})