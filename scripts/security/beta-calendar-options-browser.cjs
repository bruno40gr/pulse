/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional browser regression. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      page.setDefaultTimeout(30000)
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.goto('http://127.0.0.1:3231/odeon-demo?screen=calendar')
      await page.getByRole('button', { name: 'Add booking', exact: true }).click()
      const modal = page.getByRole('dialog')
      assert.equal(await modal.getByLabel('Student', { exact: true }).count(), 0)
      assert.equal(await modal.getByRole('button', { name: 'Cancel', exact: true }).count(), 0)
      await page.waitForTimeout(250)
      await page.screenshot({ path: `/tmp/odeon-booking-paths-${width}.png` })
      await modal.getByRole('button', { name: 'Choose Lesson', exact: true }).click()
      assert.equal(await modal.locator('[aria-invalid=true]').count(), 0)
      assert.equal(await modal.getByText('Choose a room.', { exact: true }).count(), 0)
      await modal.getByRole('button', { name: 'Continue enrollment', exact: true }).click()
      assert.ok(await modal.locator('[aria-invalid=true]').count() >= 2)
      assert.equal(await modal.getByLabel('Lesson service', { exact: true }).getAttribute('aria-invalid'), 'true')
      await page.screenshot({ path: `/tmp/odeon-calendar-validation-${width}.png` })
      await modal.getByRole('button', { name: 'Back', exact: true }).click()
      await modal.getByRole('button', { name: 'Choose Studio booking', exact: true }).click()
      await modal.getByLabel('Booking date').fill('2026-11-10')
      await modal.getByLabel('Start time').selectOption('09:00')
      assert.equal(await modal.getByLabel('Service', { exact: true }).count(), 0)
      assert.equal(await modal.getByLabel('Teacher', { exact: true }).count(), 0)
      const room = modal.getByLabel('Room', { exact: true })
      assert.notEqual(await room.inputValue(), '')
      assert.equal(await room.inputValue(), await room.locator('option').nth(1).getAttribute('value'))
      for (const kind of ['Band rehearsal', 'Event', 'Block / unavailable']) {
        await modal.getByRole('button', { name: 'Back', exact: true }).click()
        await modal.getByRole('button', { name: `Choose ${kind}`, exact: true }).click()
        assert.equal(await modal.getByLabel('Service', { exact: true }).count(), 0)
        assert.equal(await modal.getByLabel('Only exclude from public self-booking').count(), 0)
      }
      await modal.getByRole('button', { name: 'Back', exact: true }).click()
      await modal.getByRole('button', { name: 'Choose Single lesson / Free trial', exact: true }).click()
      await modal.getByLabel('Booking date').fill('2026-11-10')
      await modal.getByLabel('Start time').selectOption('17:00')
      await modal.getByLabel('Lesson service', { exact: true }).selectOption('piano')
      assert.notEqual(await modal.getByLabel('Room', { exact: true }).inputValue(), '')
      const teacherOptions = await modal.getByLabel('Teacher', { exact: true }).locator('option').evaluateAll(items => items.map(item => item.textContent))
      console.log(width, 'Piano teachers:', teacherOptions.join(', '))
      assert.ok(teacherOptions.length > 1)
      await modal.getByLabel('Student', { exact: true }).selectOption('demo:student-1-1')
      const before = await modal.getByLabel('Lesson service', { exact: true }).inputValue()
      await modal.getByRole('button', { name: 'Back', exact: true }).click()
      assert.equal(await modal.getByLabel('Student', { exact: true }).count(), 0)
      await modal.getByRole('button', { name: 'Choose Lesson', exact: true }).click()
      assert.equal(await modal.getByLabel('Student', { exact: true }).inputValue(), 'demo:student-1-1')
      assert.equal(await modal.getByLabel('Lesson service', { exact: true }).inputValue(), before)
      await modal.getByRole('button', { name: 'Back', exact: true }).click()
      await modal.getByRole('button', { name: 'Choose Studio booking', exact: true }).click()
      await modal.getByRole('button', { name: 'Back', exact: true }).click()
      await modal.getByRole('button', { name: 'Choose Lesson', exact: true }).click()
      assert.equal(await modal.getByLabel('Student', { exact: true }).inputValue(), 'demo:student-1-1')
      assert.equal(await modal.getByLabel('Lesson service', { exact: true }).inputValue(), before)
      assert.equal(await modal.getByRole('button', { name: 'Cancel', exact: true }).count(), 0)
      assert.equal(await modal.getByRole('button', { name: /Choose / }).count(), 0)
      assert.equal(await modal.locator('[aria-invalid=true]').count(), 0)
      assert.equal(await modal.getByText(/Continue in the existing enrollment workspace/).count(), 0)
      await page.screenshot({ path: `/tmp/odeon-calendar-options-${width}.png` })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: shared entry cards, submit-only field validation, no redundant selectors/copy, filtered resources and automatic room`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
