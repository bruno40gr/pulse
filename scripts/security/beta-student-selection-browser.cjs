/* eslint-disable @typescript-eslint/no-require-imports -- Isolated fictional browser regression. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:3231'
assert.match(base, /^http:\/\/127\.0\.0\.1:/)
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      page.setDefaultTimeout(8000)
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.goto(`${base}/odeon-demo?screen=book`)
      await page.getByRole('button', { name: 'Enroll', exact: true }).click()
      await page.getByRole('button', { name: 'Choose Private lessons', exact: true }).click()
      const existing = page.getByRole('radio', { name: 'Existing contact', exact: true })
      const fresh = page.getByRole('radio', { name: 'New contact', exact: true })
      const self = page.getByRole('switch', { name: 'Classes are for this person', exact: true })
      assert.equal(await existing.isChecked(), true)
      assert.equal(await self.count(), 0)
      assert.equal(await page.getByRole('combobox', { name: 'Find a person' }).count(), 1)
      assert.equal(await page.getByLabel('First name', { exact: true }).count(), 0)
      assert.equal(await page.getByRole('heading', { name: 'Student 1', exact: true }).count(), 0)
      assert.equal(await page.getByRole('button', { name: 'Add another student' }).count(), 0)
      await page.locator('label').filter({ hasText: /^Search for a contact$/ }).waitFor()
      assert.equal(await page.getByText('Contact selection', { exact: true }).count(), 0)
      const search = page.getByRole('combobox', { name: 'Find a person' })
      assert.equal(await search.getAttribute('aria-expanded'), 'false')
      assert.equal(await page.getByRole('listbox').count(), 0)
      const vertical = await page.getByRole('radio').evaluateAll(elements => elements.map(element => element.getBoundingClientRect().y))
      assert.ok(vertical[1] > vertical[0] + 20, 'Contact choices are vertical')
      await search.click()
      await page.getByRole('listbox').waitFor()
      await page.keyboard.press('Escape')
      assert.equal(await search.getAttribute('aria-expanded'), 'false')
      await search.click()
      await page.getByRole('button', { name: 'Close options', exact: true }).click()
      assert.equal(await search.getAttribute('aria-expanded'), 'false')
      await search.click()
      await page.getByRole('heading', { name: 'Add a contact', exact: true }).click()
      assert.equal(await search.getAttribute('aria-expanded'), 'false')
      await fresh.check()
      assert.equal(await self.count(), 0)
      await page.getByRole('heading', { name: 'Contact details', exact: true }).waitFor()
      assert.equal(await page.getByRole('combobox', { name: 'Find a person' }).count(), 0)
      await page.getByLabel('First name', { exact: true }).fill('Robin')
      await page.getByLabel('Last name', { exact: true }).fill('Test')
      assert.equal(await self.count(), 0, 'Incomplete manual contact does not reveal switch')
      await page.getByLabel('Email', { exact: true }).fill('robin@example.invalid')
      assert.equal(await self.isChecked(), true)
      await existing.check()
      assert.equal(await self.count(), 0)
      await fresh.check()
      assert.equal(await page.getByLabel('First name', { exact: true }).inputValue(), 'Robin')
      assert.equal(await page.getByLabel('Email', { exact: true }).inputValue(), 'robin@example.invalid')
      await self.uncheck()
      await page.getByRole('heading', { name: 'Student 1', exact: true }).waitFor()
      const student = page.getByRole('heading', { name: 'Student 1', exact: true }).locator('../..')
      assert.equal(await student.getByRole('radio').count(), 0)
      await student.getByLabel('First name', { exact: true }).fill('Casey')
      await student.getByLabel('Last name', { exact: true }).fill('Test')
      await page.getByRole('button', { name: 'Add another student' }).click()
      await page.getByRole('heading', { name: 'Student 2', exact: true }).waitFor()
      await self.check()
      assert.equal(await page.getByRole('heading', { name: /^Student [12]$/ }).count(), 0)
      await self.uncheck()
      await page.getByRole('heading', { name: 'Student 2', exact: true }).waitFor()
      await student.getByRole('button', { name: 'Edit', exact: true }).click()
      assert.equal(await student.getByLabel('First name', { exact: true }).inputValue(), 'Casey')
      await self.check()
      const delta = await self.evaluate(element => {
        const row = element.closest('label')
        const text = row.querySelector('span').getBoundingClientRect()
        const input = element.getBoundingClientRect()
        return Math.abs(text.y + text.height / 2 - input.y - input.height / 2)
      })
      assert.ok(delta < 2, 'Switch label and control share a horizontal centerline')
      assert.ok(await self.evaluate(element => element.getBoundingClientRect().left - element.closest('label').querySelector('span').getBoundingClientRect().right) < 20, 'Switch sits beside its label')
      const radios = await page.getByRole('radio').evaluateAll(elements => elements.map(element => {
        const label = element.closest('label').getBoundingClientRect()
        const input = element.getBoundingClientRect()
        return Math.abs(input.y + input.height / 2 - label.y - label.height / 2)
      }))
      assert.ok(radios.every(delta => delta < 3), 'Radio controls align with labels')
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await page.getByRole('heading', { name: 'Set up lessons', exact: true }).waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      await page.goto(`${base}/odeon-demo?screen=book`)
      await page.getByRole('button', { name: 'Enroll', exact: true }).click()
      await page.getByRole('button', { name: 'Choose Private lessons', exact: true }).click()
      await page.getByRole('combobox', { name: 'Find a person' }).fill('Alex Adams')
      await page.getByRole('option', { name: /Alex Adams/ }).click()
      assert.equal(await self.isChecked(), false, 'Account holder is not the learner by default')
      await page.getByRole('heading', { name: 'Student 1', exact: true }).waitFor()
      assert.ok(await page.getByText('Emma Adams', { exact: true }).count(), 'Account holder children are populated')
      assert.equal(await page.getByRole('radio').count(), 2, 'Only the main contact has radio choices')
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: default search, new details, retained mode/student drafts, conditional students, aligned controls and Continue`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })