/* eslint-disable @typescript-eslint/no-require-imports -- Fictional lab; all mutations blocked. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      page.setDefaultTimeout(8000)
      const writes = [], errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => {
        const request = route.request(), pathname = new URL(request.url()).pathname
        if (request.method() === 'GET') return route.continue()
        if (pathname === '/api/inbox/reconcile') return route.fulfill({ json: { skipped: true } })
        if (pathname === '/api/contact-insights') return route.fulfill({ json: { insights: [] } })
        writes.push(pathname)
        return route.abort()
      })
      await page.goto('http://127.0.0.1:3218/dashboard/contacts')
      const table = page.getByRole('table', { name: 'Contacts', exact: true })
      await table.getByRole('button', { name: 'Sophie Kim', exact: true }).click()
      await page.getByRole('button', { name: 'Edit contact', exact: true }).click()
      const editor = page.getByRole('dialog', { name: 'Edit contact prototype', exact: true })
      await editor.getByLabel('First name', { exact: true }).fill('Sofia')
      await editor.getByLabel('Family', { exact: true }).selectOption('fixture-smith')
      await editor.getByLabel('Relationship for holder 1', { exact: true }).fill('sibling')
      await editor.getByRole('button', { name: 'Save preview', exact: true }).click()
      await page.getByRole('heading', { name: 'Sofia Kim', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      const family = table.getByRole('rowgroup').filter({ has: page.getByRole('button', { name: 'Jane Smith', exact: true }) })
      assert.ok((await family.innerText()).includes('Sofia Kim'))
      await table.getByRole('button', { name: 'Sofia Kim', exact: true }).click()
      await page.getByRole('button', { name: 'Edit contact', exact: true }).click()
      await editor.getByLabel('Relationship for holder 1', { exact: true }).waitFor()
      assert.equal(await editor.getByLabel('Relationship for holder 1', { exact: true }).inputValue(), 'sibling')
      await editor.getByRole('button', { name: 'Add holder', exact: true }).click()
      await editor.getByLabel('Holder 2', { exact: true }).selectOption('mock-jamie')
      await editor.getByLabel('Relationship for holder 2', { exact: true }).fill('aunt')
      await editor.getByRole('button', { name: 'Save preview', exact: true }).click()
      await page.getByRole('button', { name: 'Edit contact', exact: true }).click()
      assert.equal(await editor.getByLabel('Holder 2', { exact: true }).inputValue(), 'mock-jamie')
      assert.equal(await editor.getByLabel('Relationship for holder 2', { exact: true }).inputValue(), 'aunt')
      await editor.getByRole('button', { name: 'Remove holder 2', exact: true }).click()
      assert.equal(await editor.getByLabel('Holder 2', { exact: true }).count(), 0)
      await page.screenshot({ path: `/tmp/pulse-contact-editor-${width}.png`, fullPage: true })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      await editor.getByLabel('Family', { exact: true }).selectOption('')
      await editor.getByRole('button', { name: 'Save preview', exact: true }).click()
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      const standalone = table.getByRole('rowgroup').filter({ has: page.getByRole('button', { name: 'Sofia Kim', exact: true }) })
      assert.equal(await standalone.getByRole('button', { name: 'Jane Smith', exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Reset preview changes', exact: true }).click()
      await table.getByRole('button', { name: 'Sophie Kim', exact: true }).waitFor()
      assert.equal(await table.getByRole('button', { name: 'Sofia Kim', exact: true }).count(), 0)
      await table.getByRole('button', { name: 'Sophie Kim', exact: true }).click()
      await page.getByRole('button', { name: 'Edit contact', exact: true }).click()
      await editor.getByLabel('Account manager', { exact: true }).selectOption('mock-jamie')
      await editor.getByRole('button', { name: 'Save preview', exact: true }).click()
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      const kim = table.getByRole('rowgroup').filter({ has: page.getByRole('button', { name: 'Sophie Kim', exact: true }) })
      assert.equal(await kim.getByRole('row').first().getByRole('button', { name: 'Jamie Kim', exact: true }).count(), 1)
      await table.getByRole('button', { name: 'Sophie Kim', exact: true }).click()
      await page.getByRole('button', { name: 'Edit contact', exact: true }).click()
      await editor.getByLabel('First name', { exact: true }).fill('Unsaved')
      await editor.getByRole('button', { name: 'Cancel editing', exact: true }).click()
      await page.getByRole('heading', { name: 'Sophie Kim', exact: true }).waitFor()
      await page.reload()
      await table.getByRole('button', { name: 'Sophie Kim', exact: true }).waitFor()
      const restored = table.getByRole('rowgroup').filter({ has: page.getByRole('button', { name: 'Sophie Kim', exact: true }) })
      assert.equal(await restored.getByRole('row').first().getByRole('button', { name: 'Sam Kim', exact: true }).count(), 1)
      assert.deepEqual(writes, [])
      assert.deepEqual(errors, [])
      await page.screenshot({ path: `/tmp/pulse-editing-prototype-${width}.png`, fullPage: true })
      console.log(`PASS ${width}px: rename, move family, holders/relationships, detach, manager change, cancel, reload/reset; zero mutation requests`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })