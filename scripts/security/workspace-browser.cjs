/* eslint-disable @typescript-eslint/no-require-imports -- Optional browser regression runner; no new dependency. */
// Requires the standalone context harness described in docs/conversations-prototype.md.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const reviewUrl = process.env.WORKSPACE_REVIEW_URL || 'http://127.0.0.1:3101'
    const external = []
    page.on('request', request => {
      if (!request.url().startsWith(new URL(reviewUrl).origin) && !request.url().startsWith('data:')) external.push(request.url())
    })
    await page.goto(reviewUrl)
    const nav = page.getByRole('complementary', { name: 'Odeon preview navigation', exact: true })
    const contacts = page.getByRole('complementary', { name: 'Contacts', exact: true })
    const composer = page.getByRole('region', { name: 'Email composer', exact: true })
    const reader = page.getByRole('region', { name: 'Email reader', exact: true })
    const inbox = page.getByRole('complementary', { name: 'Email conversations', exact: true })
    const action = name => page.getByRole('button', { name, exact: true })
    await nav.waitFor()
    assert.equal(await contacts.locator('svg,input').count(), 0)
    assert.equal(await action('Quick view').count(), 0)
    const contactBounds = await contacts.boundingBox()
    const mainBounds = await page.locator('main').boundingBox()
    assert.equal(contactBounds.x - mainBounds.x, 29) // 28px page gutter + 1px SurfacePanel border
    await page.screenshot({ path: '/tmp/pulse-desktop-contacts.png', fullPage: true })

    await action('Open conversation with Alex Chen').click()
    await page.getByRole('heading', { name: 'Alex Chen', exact: true }).waitFor()
    assert.equal(await contacts.count(), 0)
    assert.equal(await page.getByRole('dialog').count(), 0)
    assert.equal(await page.evaluate(() => !!document.querySelector('main').closest('[inert]')), false)
    assert.equal(await nav.getAttribute('inert'), null)
    await page.getByRole('textbox', { name: 'SMS message', exact: true }).fill('Keep my SMS')
    await page.screenshot({ path: '/tmp/pulse-desktop-sms.png', fullPage: true })
    await action('Email').click()
    await inbox.waitFor()
    assert.equal(await composer.count(), 0)
    const unreadRow = action('Read email: Piano lessons for Jamie')
    assert.equal(await unreadRow.getByRole('img', { name: 'Unread email', exact: true }).count(), 1)
    assert.ok(await inbox.getByRole('img', { name: 'Inbound email', exact: true }).count())
    assert.ok(await inbox.getByRole('img', { name: 'Outbound email', exact: true }).count())
    await action('Read email: Piano lessons for Jamie').click()
    await reader.waitFor()
    assert.equal(await unreadRow.getByRole('img', { name: 'Unread email', exact: true }).count(), 0)
    assert.equal(await composer.count(), 0)
    assert.equal(await inbox.count(), 1)
    await page.screenshot({ path: '/tmp/pulse-desktop-email-reader.png', fullPage: true })

    await action('Reply').click()
    await composer.waitFor()
    assert.equal(await reader.count(), 1)
    assert.equal(await inbox.count(), 1)
    assert.equal(await action('SMS').count(), 1)
    assert.equal(await page.getByRole('heading', { name: 'Alex Chen', exact: true }).count(), 1)
    assert.equal(await nav.isVisible(), true)
    assert.equal(await page.getByRole('navigation', { name: 'Workspace breadcrumbs' }).count(), 0)
    await composer.getByRole('textbox', { name: 'Email body', exact: true }).fill('Keep this email draft')
    await page.screenshot({ path: '/tmp/pulse-desktop-email-compose.png', fullPage: true })
    await page.goBack(); await reader.waitFor(); assert.equal(await composer.count(), 0)
    await page.goForward(); await composer.waitFor()
    assert.equal(await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText(), 'Keep this email draft')
    await action('Save as draft').click(); await reader.waitFor()
    await action('Continue draft').click(); await composer.waitFor()
    assert.equal(await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText(), 'Keep this email draft')
    await action('Discard draft').click()
    const confirmation = page.getByRole('region', { name: 'Discard email draft', exact: true })
    await confirmation.waitFor(); await confirmation.getByRole('button', { name: 'Keep draft', exact: true }).click()
    await confirmation.waitFor({ state: 'detached' }); await composer.waitFor()

    // Templates, preview and sandbox remain part of writing, not inbox navigation.
    await composer.getByRole('button', { name: 'Use template', exact: true }).click()
    const templateLibrary = page.getByRole('dialog', { name: 'Email templates', exact: true })
    await templateLibrary.getByRole('button', { name: 'Lesson availability', exact: true }).click()
    await templateLibrary.getByRole('button', { name: 'Use template', exact: true }).click()
    await templateLibrary.getByRole('button', { name: 'Insert instead', exact: true }).click()
    assert.equal(await composer.getByRole('button', { name: 'HTML', exact: true }).count(), 0)
    await composer.getByRole('button', { name: 'Preview', exact: true }).click()
    const preview = composer.frameLocator('iframe[title="Email preview"]')
    assert.equal(await preview.locator('script,img[src^="https"],a[href^="javascript:"]').count(), 0)
    await action('Save as draft').click(); await reader.waitFor()
    await page.getByRole('button', { name: 'Back to Conversations', exact: true }).click(); await contacts.waitFor()
    await action('Open conversation with Morgan Rivera').click(); await action('Email').click()
    await page.getByText('No email history with Morgan yet.', { exact: true }).waitFor()
    await action('Draft email').click()
    await composer.waitFor()
    assert.equal(await page.getByRole('dialog', { name: 'New message', exact: true }).count(), 0)
    await composer.getByRole('textbox', { name: 'Email subject', exact: true }).fill('Guitar lessons')
    await composer.getByRole('textbox', { name: 'Email body', exact: true }).fill('Hi Morgan, we can help Sam get started.')
    await action('Save as draft').click(); await action('Read email: Guitar lessons').click()
    assert.equal(await composer.count(), 0)
    await action('Continue draft').click(); await composer.waitFor()
    assert.equal(await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText(), 'Hi Morgan, we can help Sam get started.')
    await composer.getByRole('button', { name: 'Send email', exact: true }).click()
    await reader.waitFor(); await page.getByRole('status').getByText('Mock message added. Nothing was sent.', { exact: true }).waitFor()
    await page.goBack(); assert.equal(await composer.count(), 0)
    await page.getByRole('button', { name: 'Back to Conversations', exact: true }).click(); await contacts.waitFor()
    await action('Open conversation with Alex Chen').click(); await action('Continue draft').click(); await composer.waitFor()
    assert.ok((await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText()).includes('Keep this email draft'))

    await page.setViewportSize({ width: 1280, height: 900 })
    await page.screenshot({ path: '/tmp/pulse-desktop-laptop-compose.png', fullPage: true })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await action('Save as draft').click(); await reader.waitFor()
    await action('Open lead for Alex Chen').click(); await page.getByRole('region', { name: 'Lead preview', exact: true }).waitFor()
    assert.equal(await page.getByRole('dialog').count(), 0)
    await page.goBack(); await reader.waitFor()
    await action('SMS').click()
    assert.equal(await page.getByRole('textbox', { name: 'SMS message', exact: true }).inputValue(), 'Keep my SMS')
    await page.getByRole('textbox', { name: 'SMS message', exact: true }).press('Enter')
    await page.getByLabel('SMS history', { exact: true }).getByText('Keep my SMS', { exact: true }).waitFor()
    await action('Email').click(); await action('Read email: Piano lessons for Jamie').click(); await action('Continue draft').click()
    await action('Discard draft').click(); await confirmation.getByRole('button', { name: 'Discard draft', exact: true }).click()
    await reader.waitFor(); await page.goBack(); assert.equal(await composer.count(), 0)
    assert.equal(errors.length, 0, JSON.stringify(errors))
    assert.equal(external.length, 0, JSON.stringify(external))
    console.log('PASS: desktop Odeon context + 28px gutters; stable list, tabs and reader during inline composing; draft return/resume/Back/Forward; no resurrection after send/discard; templates, sandbox, mock sending; laptop overflow; no errors/external requests')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
