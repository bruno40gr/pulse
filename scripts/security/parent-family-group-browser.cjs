/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional prototype regression tests. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], apis = []
      page.setDefaultTimeout(15000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) {
          const shell = ['/api/account/identity', '/api/account/claim-reminder', '/api/notifications', '/api/leads', '/api/inbox', '/api/inbox/reconcile', '/api/tenant/sync-status']
          if (!shell.includes(url.pathname)) { apis.push(url.pathname); return route.abort() }
          return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        }
        return route.continue()
      })
      await page.goto(`${base}?prototype=v3&view=parent&account=preview:kim&portal=account`)
      const portal = page.getByRole('main', { name: 'Parent portal', exact: true })
      const dependents = portal.getByRole('region', { name: 'Dependents', exact: true })
      await dependents.getByRole('button', { name: 'Manage Family Group', exact: true }).waitFor()
      assert.equal(await portal.locator('[data-field-label]').filter({ hasText: /^Dependents$/ }).count(), 0)
      assert.equal(await portal.getByRole('button', { name: /student record|Add a child|Confirm unlink child/i }).count(), 0)
      const summary = portal.getByRole('complementary', { name: 'Account billing summary', exact: true })
      await summary.getByRole('heading', { name: 'Your balance', exact: true }).waitFor()
      assert.equal(await summary.getByRole('button', { name: 'View billing', exact: true }).evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(220, 38, 38)')
      await summary.getByText('Dec 1', { exact: true }).waitFor()
      const holderLabel = portal.locator('[data-field-label]').first()
      const labelScale = await holderLabel.evaluate(el => ({ label: parseFloat(getComputedStyle(el).fontSize), root: parseFloat(getComputedStyle(document.documentElement).fontSize) }))
      assert.ok(Math.abs(labelScale.label / labelScale.root - 0.8125) < 0.001, 'Field labels use the label token, not the extra-small metadata token')
      if (width === 1440) {
        const billing = await summary.boundingBox(), left = await dependents.boundingBox()
        assert.ok(billing.x >= left.x + left.width, 'Balance is in the right column')
        const contact = await portal.getByRole('heading', { name: 'Contact details', exact: true }).boundingBox()
        const balance = await summary.getByRole('heading', { name: 'Your balance', exact: true }).boundingBox()
        assert.ok(Math.abs(contact.y - balance.y) < 2, 'Balance starts at the top of the right column')
      }
      await page.screenshot({ path: `/tmp/odeon-parent-account-simple-${width}.png`, fullPage: true })
      await dependents.getByRole('button', { name: 'Manage Family Group', exact: true }).click()
      assert.equal(await page.getByRole('dialog').count(), 0, 'Family management is inline')
      const members = dependents.locator('[aria-label="Family group members"]')
      await members.getByText('Sophie Kim', { exact: true }).waitFor()
      await members.getByText('Ethan Kim', { exact: true }).waitFor()
      assert.equal(await members.getByText(/^\d+ lessons$/).count(), 0)
      assert.equal(await dependents.getByText(/Saved cards stay|Future payer|Unpaid shared/).count(), 0)
      await members.getByRole('button', { name: 'Remove from Family Group', exact: true }).first().click()
      const confirmation = page.getByRole('dialog', { name: 'Remove from Family Group', exact: true })
      await confirmation.getByText('Unlink Sophie Kim from Sam Kim’s account? Sophie will remain a standalone student record, with their subscriptions, outstanding balance, and history.', { exact: true }).waitFor()
      await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
      assert.equal(await members.getByText('Sophie Kim', { exact: true }).count(), 1)
      await members.getByRole('button', { name: 'Remove from Family Group', exact: true }).first().click()
      await confirmation.getByRole('button', { name: 'Confirm', exact: true }).click({ delay: 1700 })
      await confirmation.waitFor({ state: 'hidden' })
      assert.equal(await members.getByText('Sophie Kim', { exact: true }).count(), 0)
      await dependents.getByRole('button', { name: 'Back to dependents', exact: true }).click()
      assert.equal(await dependents.getByRole('heading', { name: 'Sophie Kim', exact: true }).count(), 0)
      await dependents.getByRole('heading', { name: 'Ethan Kim', exact: true }).waitFor()
      await dependents.getByRole('button', { name: 'Add Dependent', exact: true }).click()
      await dependents.getByRole('textbox', { name: 'First name', exact: true }).fill('Jamie')
      await dependents.getByRole('textbox', { name: 'Last name', exact: true }).fill('Kim')
      await dependents.getByRole('textbox', { name: 'Email', exact: true }).fill('jamie@example.invalid')
      await dependents.getByRole('button', { name: 'Cancel', exact: true }).click()
      assert.equal(await dependents.getByRole('heading', { name: 'Jamie Kim', exact: true }).count(), 0)
      await dependents.getByRole('button', { name: 'Add Dependent', exact: true }).click()
      await dependents.getByRole('textbox', { name: 'First name', exact: true }).fill('Jamie')
      await dependents.getByRole('textbox', { name: 'Last name', exact: true }).fill('Kim')
      await dependents.getByRole('textbox', { name: 'Email', exact: true }).fill('jamie@example.invalid')
      await dependents.getByRole('button', { name: 'Add Dependent', exact: true }).click()
      await dependents.getByRole('heading', { name: 'Jamie Kim', exact: true }).waitFor()
      await dependents.getByText('jamie@example.invalid', { exact: true }).waitFor()
      assert.equal(await page.locator('[data-parent-portal]').evaluate(el => el.scrollWidth > el.clientWidth + 1), false)
      assert.deepEqual(errors, [])
      assert.deepEqual(apis, [])
      console.log(`PASS simplified parent account, balance placement, label size, family remove/cancel and add dependent ${width}px`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
