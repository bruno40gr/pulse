/* eslint-disable @typescript-eslint/no-require-imports -- Local-only fictional billing journeys. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const version of ['', 'v2', 'v3']) for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], apis = []
      page.setDefaultTimeout(10000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.hostname === 'res.cloudinary.com' && route.request().resourceType() === 'image') return route.continue()
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) {
          const shell = ['/api/account/identity', '/api/account/claim-reminder', '/api/notifications', '/api/leads', '/api/inbox', '/api/inbox/reconcile', '/api/tenant/sync-status']
          if (!shell.includes(url.pathname)) { apis.push(url.pathname); return route.abort() }
          return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        }
        return route.continue()
      })
      await page.goto(`${base}?prototype=${version || 'v1'}&view=parent&account=preview:kim`)
      const portal = page.getByRole('main', { name: 'Parent portal', exact: true })
      await portal.getByRole('heading', { name: 'Hi, Sam.', exact: true }).waitFor()
      assert.equal(await page.getByRole('treegrid', { name: 'Contacts' }).count(), 0)
      for (const text of ['Riley Kim', 'Ella Kim', 'Alex Morgan', 'PRIVATE family coordination']) assert.equal(await portal.getByText(text, { exact: false }).count(), 0)
      assert.equal(await portal.getByRole('button', { name: 'Internal notes', exact: true }).count(), 0)
      await page.screenshot({ path: `/tmp/odeon-parent-home-${version || 'v1'}-${width}.png`, fullPage: true })
      await portal.getByRole('button', { name: 'View Ethan’s lessons', exact: true }).click()
      assert.equal(await portal.getByRole('combobox', { name: 'Student', exact: true }).inputValue(), 'preview:ethan')
      assert.equal(await portal.getByRole('button', { name: /^View Sophie/ }).count(), 0)
      await portal.getByRole('combobox', { name: 'Student', exact: true }).selectOption('preview:sophie')
      await portal.getByRole('button', { name: 'View Sophie Piano 2026-11-10', exact: true }).click()
      assert.equal(await portal.getByRole('combobox', { name: 'Makeup exception', exact: true }).count(), 0)
      await portal.getByRole('button', { name: 'Cancel lesson', exact: true }).click()
      await portal.getByRole('heading', { name: 'Lesson cancelled', exact: true }).waitFor()
      await portal.getByRole('button', { name: 'Back to lessons', exact: true }).click()
      await portal.getByRole('button', { name: 'Book Piano makeup 2026-10-13', exact: true }).click()
      await portal.getByRole('heading', { name: 'Schedule Piano makeup · 30 min', exact: true }).waitFor()
      const availability = portal.getByRole('region', { name: 'Available lesson times', exact: true })
      await availability.getByRole('button', { name: /available$/ }).first().click()
      const teachers = availability.getByRole('group', { name: /Teachers at/ })
      if (await teachers.count()) await teachers.getByRole('button').first().click()
      await portal.getByRole('button', { name: 'Book makeup', exact: true }).click()
      await portal.getByText('Makeup booked. Your lesson is listed below.', { exact: true }).waitFor()
      assert.equal(await portal.getByRole('button', { name: 'Book Piano makeup 2026-10-13', exact: true }).count(), 0, 'Booked credit cannot be reused')
      await page.screenshot({ path: `/tmp/odeon-parent-lessons-${version || 'v1'}-${width}.png`, fullPage: true })
      await page.getByRole('navigation', { name: 'Parent portal navigation' }).getByRole('button', { name: 'Billing', exact: true }).click()
      assert.equal(await portal.getByRole('button', { name: 'View invoice DEMO-1004', exact: true }).count(), 0)
      await portal.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).click()
      await portal.getByRole('article', { name: 'Itemized invoice', exact: true }).waitFor()
      assert.equal(await portal.getByRole('button', { name: 'Customize invoice fields', exact: true }).count(), 0)
      await portal.getByRole('button', { name: 'Back to invoices', exact: true }).click()
      await portal.getByRole('button', { name: 'Payment methods', exact: true }).click()
      assert.equal(await portal.getByRole('combobox', { name: 'Save card for', exact: true }).getByRole('option').count(), 1)
      assert.equal(await portal.getByRole('button', { name: 'Remove Visa ···· 1881', exact: true }).count(), 0)
      await portal.getByRole('textbox', { name: 'Name on card', exact: true }).fill('Taylor Kim')
      await portal.getByRole('checkbox', { name: 'I am authorized to use this card', exact: true }).check()
      await portal.getByRole('button', { name: 'Add card', exact: true }).click()
      await portal.getByText('Name on card: Taylor Kim', { exact: false }).waitFor()
      await portal.getByRole('button', { name: 'Back to billing', exact: true }).click()
      await portal.getByRole('button', { name: 'Pay $200', exact: true }).click()
      const payment = page.getByRole('dialog', { name: 'Pay', exact: true })
      assert.equal(await payment.getByRole('combobox', { name: 'Paying as', exact: true }).getByRole('option').count(), 1)
      await payment.getByRole('combobox', { name: 'Sam Kim’s payment method', exact: true }).selectOption({ label: 'Visa ···· 4242 · Taylor Kim' })
      await payment.getByRole('button', { name: 'Pay', exact: true }).click()
      await portal.getByRole('heading', { name: '$0.00 due', exact: true }).waitFor()
      await page.screenshot({ path: `/tmp/odeon-parent-billing-${version || 'v1'}-${width}.png`, fullPage: true })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      assert.equal(await page.locator('[data-parent-portal]').evaluate(el => el.scrollWidth > el.clientWidth), false)
      await page.reload()
      await portal.getByRole('heading', { name: 'Billing', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Exit parent preview', exact: true }).click()
      await page.getByRole('searchbox', { name: 'Search contacts', exact: true }).waitFor()
      assert.deepEqual(errors, [])
      assert.deepEqual(apis, [])
      console.log(`PASS parent portal ${version || 'v1'} ${width}px: home, child filtering, cancellation, makeup booking, scoped cards and invoice payment, reload and exit`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
