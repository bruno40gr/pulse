/* eslint-disable @typescript-eslint/no-require-imports -- Optional mock browser regression runner. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    const external = []
    const url = process.env.WORKSPACE_REVIEW_URL || 'http://127.0.0.1:3101'
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (!request.url().startsWith(new URL(url).origin) && !request.url().startsWith('data:')) external.push(request.url()) })
    const button = (root, name) => root.getByRole('button', { name, exact: true })
    const modal = page.getByRole('dialog', { name: 'New message', exact: true })
    const composer = page.getByRole('region', { name: 'Email composer', exact: true })
    const library = channel => page.getByRole('dialog', { name: `${channel} templates`, exact: true })
    async function add(root, field, name, query) {
      await root.getByRole('textbox', { name: `Search ${field}`, exact: true }).fill(query)
      await button(root, `Add ${name} to ${field}`).click()
    }
    await page.goto(url)
    await button(page, 'New message').click()
    await modal.waitFor()
    assert.equal(await modal.getByRole('textbox').count(), 0)
    await modal.getByRole('heading', { name: 'Send a new message', exact: true }).waitFor()
    assert.equal(await modal.getByRole('button').count(), 3)
    assert.equal(await modal.getByText(/Mock only|sent separately|One email with/).count(), 0)
    const smsChoice = await button(modal, 'SMS').boundingBox()
    const emailChoice = await button(modal, 'Email').boundingBox()
    assert.equal(smsChoice.y, emailChoice.y)
    assert.ok(Math.abs(smsChoice.width - emailChoice.width) < 1)
    assert.deepEqual(await button(modal, 'SMS').evaluate(node => { const style = getComputedStyle(node); return [style.backgroundColor, style.color, style.border] }), await button(modal, 'Email').evaluate(node => { const style = getComputedStyle(node); return [style.backgroundColor, style.color, style.border] }))
    await page.screenshot({ path: '/tmp/pulse-channel-choice.png', fullPage: true })
    for (const channel of ['SMS', 'Email']) {
      await button(modal, channel).click()
      await button(modal, 'Close').click()
      await button(page, 'New message').click()
      await modal.getByRole('heading', { name: 'Send a new message', exact: true }).waitFor()
    }
    await button(modal, 'SMS').click()
    assert.equal(await button(modal, 'Write SMS').isDisabled(), true)
    await add(modal, 'SMS recipients', 'Alex Chen', 'Alex')
    await add(modal, 'SMS recipients', 'Morgan Rivera', 'Morgan')
    assert.equal(await modal.getByRole('button', { name: /^Remove .* from SMS recipients$/ }).count(), 2)
    await page.screenshot({ path: '/tmp/pulse-channel-sms-recipients.png', fullPage: true })
    await button(modal, 'Write SMS (2)').click()
    await modal.waitFor({ state: 'detached' })
    await page.getByRole('heading', { name: 'Write a text message', exact: true }).waitFor()
    const smsComposer = page.getByRole('region', { name: 'New SMS composer', exact: true })
    const smsInput = smsComposer.getByRole('textbox', { name: 'SMS message', exact: true })
    assert.equal(await page.getByRole('tab').count(), 0)
    assert.equal(await button(page, 'Email').count(), 0)
    assert.equal(await smsComposer.getByRole('region', { name: /^SMS phone preview for / }).count(), 1)
    assert.equal(await smsComposer.getByRole('button', { name: /^(Hide phone preview|Phone preview)$/ }).count(), 0)
    await smsInput.fill('Hi {{firstName}}, checking in for {{student}}!')
    const smsInputBox = await smsInput.boundingBox()
    const smsPreviewBox = await smsComposer.getByRole('complementary', { name: 'SMS preview pane', exact: true }).boundingBox()
    assert.ok(smsPreviewBox.x >= smsInputBox.x + smsInputBox.width, 'New SMS preview must be to the right of the composer')
    const smsWorkspaceBox = await smsComposer.getByLabel('SMS workspace', { exact: true }).boundingBox()
    assert.ok(Math.abs(smsPreviewBox.width / smsWorkspaceBox.width - 0.7) < 0.005, 'New SMS split must be 30/70')
    assert.equal(await button(smsComposer, 'Templates').count(), 0)
    await button(smsComposer, 'Edit recipients').click()
    const edit = page.getByRole('dialog', { name: 'Edit SMS recipients', exact: true })
    await button(edit, 'Remove Morgan Rivera from SMS recipients').click()
    await add(edit, 'SMS recipients', 'Morgan Rivera', 'Morgan')
    await button(edit, 'Done').click()
    assert.equal(await smsInput.inputValue(), 'Hi {{firstName}}, checking in for {{student}}!')
    await button(page, 'Back to Communications').click()
    const leaveSms = page.getByRole('dialog', { name: 'Discard message and go back', exact: true })
    await leaveSms.getByText('Going back to conversations will discard the current message', { exact: true }).waitFor()
    await button(leaveSms, 'Cancel').click()
    assert.equal(await smsInput.inputValue(), 'Hi {{firstName}}, checking in for {{student}}!')
    await page.goBack()
    await button(page, 'New message').click()
    await modal.getByRole('heading', { name: 'Send a new message', exact: true }).waitFor()
    await button(modal, 'Close').click()
    await page.goForward()
    await smsComposer.waitFor()
    assert.equal(await smsInput.inputValue(), 'Hi {{firstName}}, checking in for {{student}}!')
    await page.screenshot({ path: '/tmp/pulse-channel-sms-write.png', fullPage: true })
    await button(smsComposer, 'Send').click()
    await page.getByRole('heading', { name: 'Communications', exact: true }).waitFor()
    await page.goBack()
    assert.equal(await page.getByRole('region', { name: 'New SMS composer', exact: true }).count(), 0)
    await button(page, 'Back to Communications').click()
    await button(page, 'Open conversation with Alex Chen').click()
    await page.getByLabel('SMS history', { exact: true }).getByText('Hi Alex, checking in for Jamie!', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Back to Communications', exact: true }).click()
    await button(page, 'Open conversation with Morgan Rivera').click()
    await page.getByLabel('SMS history', { exact: true }).getByText('Hi Morgan, checking in for Sam!', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Back to Communications', exact: true }).click()

    await button(page, 'New message').click(); await button(modal, 'Email').click()
    assert.equal(await modal.getByText(/One email\. To and Cc/).count(), 0)
    assert.equal(await button(modal, 'Write email').isDisabled(), true)
    await add(modal, 'To', 'Alex Chen', 'Alex')
    await button(modal, 'Add Cc').click(); await add(modal, 'Cc', 'Morgan Rivera', 'Morgan')
    await button(modal, 'Add Bcc').click()
    const bccInput = modal.getByRole('textbox', { name: 'Search Bcc', exact: true })
    await bccInput.fill('Alex')
    assert.equal(await button(modal, 'Add Alex Chen to Bcc').count(), 0)
    await bccInput.fill('')
    const bccCandidate = modal.getByRole('button', { name: /^Add .* to Bcc$/ }).first()
    const candidateName = (await bccCandidate.getAttribute('aria-label')).replace(/^Add /, '').replace(/ to Bcc$/, '')
    await bccCandidate.click()
    await page.screenshot({ path: '/tmp/pulse-channel-email-recipients.png', fullPage: true })
    await button(modal, 'Write email').click(); await composer.waitFor()
    assert.equal(await library('Email').count(), 0)
    assert.equal(await button(page, 'New message').count(), 0)
    assert.equal(await button(page, 'Back to contacts').count(), 0)
    const toolboxButton = await button(composer, 'Use template').boundingBox()
    const subjectInput = await composer.getByRole('textbox', { name: 'Email subject', exact: true }).boundingBox()
    assert.ok(toolboxButton.y > subjectInput.y)
    assert.equal(await composer.getByLabel('Message input area', { exact: true }).getByRole('button', { name: 'Use template', exact: true }).count(), 1)
    assert.equal(await button(composer, 'Remove Alex Chen from To').count(), 1)
    assert.equal(await button(composer, 'Remove Morgan Rivera from Cc').count(), 1)
    assert.equal(await button(composer, `Remove ${candidateName} from Bcc`).count(), 1)
    assert.equal(await page.getByRole('complementary', { name: 'Email conversations', exact: true }).count(), 0)
    await composer.getByRole('textbox', { name: 'Email subject', exact: true }).fill('My original subject')
    await composer.getByRole('textbox', { name: 'Email body', exact: true }).fill('My original email')
    await button(composer, 'Use template').click()
    assert.equal(await button(library('Email'), 'Custom SMS follow-up').count(), 0)
    await button(library('Email'), 'How are lessons going?').click()
    const templatePreview = library('Email').getByRole('region', { name: 'Template preview', exact: true })
    assert.ok((await templatePreview.innerText()).includes('Hi there'))
    await page.screenshot({ path: '/tmp/pulse-channel-template-library.png', fullPage: true })
    await button(library('Email'), 'Use template').click(); await button(library('Email'), 'Insert instead').click()
    assert.equal(await composer.getByRole('textbox', { name: 'Email subject', exact: true }).inputValue(), 'My original subject')
    assert.ok((await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText()).includes('My original email'))
    await button(composer, 'Undo template').click()
    assert.equal(await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText(), 'My original email')
    await button(composer, 'Use template').click()
    await button(library('Email'), 'How are lessons going?').click()
    await button(library('Email'), 'Use template').click(); await button(library('Email'), 'Confirm replace').click()
    assert.equal(await composer.getByRole('textbox', { name: 'Email subject', exact: true }).inputValue(), 'Checking in on lessons')
    assert.equal(await button(composer, `Remove ${candidateName} from Bcc`).count(), 1)
    await button(page, 'Save as draft').click(); await button(page, 'Continue draft').click()
    assert.equal(await button(composer, 'Remove Morgan Rivera from Cc').count(), 1)
    await page.screenshot({ path: '/tmp/pulse-channel-email-compose.png', fullPage: true })
    await button(composer, 'Remove Alex Chen from To').click()
    assert.equal(await button(composer, 'Send email').isDisabled(), true)
    await add(composer, 'To', 'Alex Chen', 'Alex')
    await button(composer, 'Send email').click()
    await page.getByRole('status').getByText('Mock message added. Nothing was sent.', { exact: true }).waitFor()
    await button(page, 'Open conversation with Morgan Rivera').click(); await button(page, 'Email').click()
    await button(page, 'Read email: Checking in on lessons').click()
    await page.getByRole('region', { name: 'Email reader', exact: true }).getByText('Checking in on lessons', { exact: true }).waitFor()
    assert.equal(errors.length, 0, JSON.stringify(errors))
    assert.equal(external.length, 0, JSON.stringify(external))
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    console.log('PASS: channel first; SMS one-at-a-time selection, separate personalised histories and reset-on-close; email To/Cc/Bcc, dedupe, validation and draft resume; email-only template selection/preview/insert/confirmed replace/undo; mock send; no errors or external requests')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
