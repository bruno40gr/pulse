/* eslint-disable @typescript-eslint/no-require-imports -- Shared Contacts source contracts. */
const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync, existsSync } = require('node:fs')
const { resolve } = require('node:path')
const source = file => readFileSync(resolve(__dirname, '../..', file), 'utf8')

test('all Contacts tenants and roles use the shared panel with one history owner', () => {
  const page = source('app/dashboard/contacts/page.tsx')
  assert.match(page, /<LiveContactPanel/)
  assert.doesNotMatch(page, /ContactSlidePanel|AccountFamilyPanel|DEFAULT_TENANT|liveHeadliner/)
  assert.equal((page.match(/useMobilePanelHistory\(\{/g) || []).length, 1)
  assert.match(page, /initialNotesTab=\{initialNotesTab\} startOnNotes=\{notesDeepLink\}/)
  assert.match(page, /<ContactBulkComposer/)
  assert.match(page, /onEnroll\?\./)
  assert.match(page, /onCreateOpportunity/)
  assert.match(page, /onCreateBand/)
  assert.equal(existsSync(resolve(__dirname, '../../components/contacts/ContactSlidePanel.tsx')), false)
  const explorer = source('beta-source/app/content-studio-prototype/event-explorer/EventExplorer.tsx')
  assert.doesNotMatch(explorer, /ContactSlidePanel/)
  assert.match(explorer, /<LiveContactPanel key=\{selectedStudent.id\} simulated/)
  assert.match(explorer, /initialSection="enrollments"/)
})

test('Contacts navigation fetches explicit IDs and rejects tenant mismatches and superseded responses', () => {
  const page = source('app/dashboard/contacts/page.tsx')
  assert.match(page, /encodeURIComponent\(id\).*encodeURIComponent\(tenantId\)/)
  assert.match(page, /person\.tenant_id !== tenantId/)
  assert.match(page, /requestId !== navigationRequest.current/)
  assert.match(page, /navigationRequest.current\+\+/)
  assert.match(page, /navigationError=\{navigationError\} openingContact=\{openingContact\}/)
})

test('fictional contact editing, notes and SMS stay local and enrollment integration survives', () => {
  const page = source('app/dashboard/contacts/page.tsx')
  const panel = source('components/contacts/LiveContactPanel.tsx')
  assert.match(page, /simulated = prototype \|\| Boolean\(sampleContacts\)/)
  assert.match(page, /capabilities=\{profileCapabilities\} simulated=\{simulated\}/)
  assert.match(panel, /if \(simulated\) \{[\s\S]*?markSaved\(id\)[\s\S]*?continue/)
  assert.match(panel, /if \(simulated\) \{[\s\S]*?onNotesUpdated[\s\S]*?return true/)
  assert.match(panel, /!simulated && \(showsAccount && familyId/)
  assert.match(panel, /family=\{!simulated && capabilities.edit/)
  assert.match(panel, /mentionsEnabled=\{!simulated && notesTab === 'internal'\}/)
  assert.match(panel, /simulated \? person && channel === 'sms' && <PrototypeContactSms/)
  assert.match(panel, /section === 'enrollments' && bandEnrollments && person \? bandEnrollments\(person.id\)/)
  assert.match(source('components/contacts/PrototypeContactSms.tsx'), /LeadWorkspaceContext.Provider value=\{simulatedWorkspace\}/)
})