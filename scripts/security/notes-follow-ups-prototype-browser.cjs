/* eslint-disable @typescript-eslint/no-require-imports -- Fictional browser-only review; all domain writes blocked. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const url = process.env.NOTES_REVIEW_URL || 'http://127.0.0.1:3218/dashboard/design/notes-follow-ups'
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 900, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1100 } })
      const page = await context.newPage()
      const errors = [], writes = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => {
        const request = route.request()
        if (new URL(request.url()).pathname === '/api/inbox/reconcile') return route.fulfill({ json: { skipped: true } })
        if (request.method() !== 'GET') writes.push(request.url())
        return route.fulfill({ json: {} })
      })
      await page.goto(url)
      const sticky = page.getByRole('article', { name: 'Tuesday might work better', exact: true })
      await sticky.waitFor()
      const originalColor = await sticky.locator('div').first().evaluate(node => getComputedStyle(node).backgroundColor)
      assert.equal(await page.getByRole('button', { name: 'Cards', exact: true }).count(), 0)
      assert.equal(await page.getByRole('button', { name: 'New sticky note', exact: true }).count(), 0)
      await page.getByPlaceholder('Take a note…', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'All dates', exact: true }).waitFor()
      await sticky.getByRole('button', { name: 'Make a task', exact: true }).click()
      const dialog = page.getByRole('dialog', { name: 'Make a task', exact: true })
      await dialog.getByLabel('Action', { exact: true }).fill('Call Michelle about Tuesday')
      assert.equal(await dialog.getByLabel('Action', { exact: true }).evaluate(node => node.tagName), 'TEXTAREA')
      assert.equal(await dialog.getByText('Keep this note as it is.', { exact: false }).count(), 0)
      await dialog.getByRole('combobox', { name: 'Related to', exact: true }).fill('Michelle')
      await dialog.getByRole('option', { name: 'Michelle Morgan · Lead', exact: true }).click()
      await dialog.getByLabel('Owner', { exact: true }).selectOption('admin')
      await dialog.getByRole('button', { name: 'Create task', exact: true }).click()
      assert.equal(await sticky.locator('div').first().evaluate(node => getComputedStyle(node).backgroundColor), originalColor)
      assert.match(await sticky.innerText(), /Tuesday might work better/)
      assert.match(await sticky.innerText(), /Check availability before calling/)
      assert.match(await sticky.innerText(), /Due today.*Alex/)
      const tasks = page.getByRole('combobox', { name: 'Tasks', exact: true })
      await tasks.selectOption('mine')
      await sticky.waitFor()
      assert.equal(await page.getByRole('article', { name: 'First outreach to Michelle', exact: true }).count(), 0)
      await tasks.selectOption('today')
      await sticky.getByRole('button', { name: 'Mark note as done', exact: true }).click()
      assert.equal(await sticky.count(), 0)
      await page.getByRole('switch', { name: 'Hide notes marked ‘done’' }).click()
      await tasks.selectOption('completed')
      await sticky.getByRole('button', { name: 'Mark note as open', exact: true }).click()
      await tasks.selectOption('all')
      await page.getByRole('switch', { name: 'Hide notes marked ‘done’' }).click()
      await sticky.getByRole('button', { name: 'Task details', exact: true }).click()
      await dialog.getByLabel('Due date').fill('2099-12-15')
      await dialog.getByRole('button', { name: 'Save task', exact: true }).click()
      await tasks.selectOption('upcoming')
      await sticky.getByText(/2099-12-15/).waitFor()
      await page.reload()
      await sticky.getByText(/2099-12-15/).waitFor()
      await sticky.getByRole('button', { name: 'Edit', exact: true }).click()
      await sticky.getByPlaceholder('Title').fill('Tuesday callback')
      await sticky.getByRole('button', { name: 'Save', exact: true }).click()
      const renamed = page.getByRole('article', { name: 'Tuesday callback', exact: true })
      await renamed.getByRole('button', { name: 'Pin note', exact: true }).click()
      await renamed.getByRole('button', { name: 'Unpin note', exact: true }).waitFor()
      await renamed.getByRole('button', { name: 'Reply', exact: true }).click()
      const replies = page.getByRole('dialog', { name: 'Note replies' })
      await replies.getByLabel('Reply', { exact: true }).fill('Checked availability')
      await replies.getByRole('button', { name: 'Reply', exact: true }).click()
      await replies.getByRole('button', { name: 'Close', exact: true }).click()
      await renamed.getByRole('button', { name: 'Replies 1', exact: true }).waitFor()
      await page.getByPlaceholder('Title', { exact: true }).fill('Front desk reminder')
      await page.getByPlaceholder('Take a note…', { exact: true }).fill('Spare keys are in the drawer.')
      await page.getByRole('button', { name: 'Add', exact: true }).click()
      const added = page.getByRole('article', { name: 'Front desk reminder', exact: true })
      await added.getByRole('button', { name: 'Make a task', exact: true }).waitFor()
      await page.getByPlaceholder('Title', { exact: true }).fill('Call about lessons')
      const composer = page.getByPlaceholder('Take a note…', { exact: true })
      await composer.fill('@Michelle')
      await page.getByRole('button', { name: '@Michelle Morgan · lead', exact: true }).click()
      const composerTask = page.getByRole('button', { name: 'Make a task', exact: true })
      // Composer is above the saved stickies; conversion opens without a separate Add.
      await composerTask.first().click()
      await dialog.waitFor()
      assert.equal(await dialog.getByRole('combobox', { name: 'Related to', exact: true }).inputValue(), 'Michelle Morgan')
      await dialog.getByLabel('Action', { exact: true }).fill('Call Michelle\nAsk about preferred lesson days')
      await dialog.getByRole('button', { name: 'Create task', exact: true }).click()
      await page.getByPlaceholder('Title', { exact: true }).fill('Staff follow-through')
      await composer.fill('@Jordan')
      await page.getByRole('button', { name: '@Jordan · staff', exact: true }).click()
      await page.getByRole('button', { name: 'Make a task', exact: true }).first().click()
      assert.equal(await dialog.getByLabel('Owner', { exact: true }).inputValue(), 'jordan')
      assert.equal(await dialog.getByRole('combobox', { name: 'Related to', exact: true }).inputValue(), '')
      await dialog.getByRole('combobox', { name: 'Related to', exact: true }).fill('not a person')
      await dialog.getByRole('combobox', { name: 'Related to', exact: true }).press('Tab')
      await dialog.getByRole('button', { name: 'Create task', exact: true }).click()
      await dialog.getByRole('alert').waitFor()
      await dialog.getByRole('combobox', { name: 'Related to', exact: true }).fill('Alexandra')
      await dialog.getByRole('option', { name: 'Alexandra Brooks · Contact', exact: true }).click()
      await dialog.getByRole('button', { name: 'Create task', exact: true }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true)
      await page.screenshot({ path: `/private/tmp/notes-follow-ups-${width}.png`, fullPage: true })
      assert.deepEqual(errors, [])
      assert.deepEqual(writes, [])
      console.log(`PASS ${width}px: existing Notes layout, conversion, task filters, done/reopen, reschedule, reload, edit/pin/reply/composer, no writes`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })