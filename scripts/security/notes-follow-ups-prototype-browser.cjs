/* eslint-disable @typescript-eslint/no-require-imports -- Fictional browser-only review; all domain writes blocked. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const url = process.env.NOTES_REVIEW_URL || 'http://127.0.0.1:3218/dashboard/design/notes-follow-ups'
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 900, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1100 } })
      const page = await context.newPage()
      const errors = [], writes = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => {
        const request = route.request()
        if (new URL(request.url()).pathname === '/api/inbox/reconcile') return route.fulfill({ json: { skipped: true } })
        if (request.method() !== 'GET') writes.push(request.url())
        return route.fulfill({ json: {} })
      })
      await page.goto(url)
      const sticky = page.getByRole('article', { name: 'Tuesday might work better', exact: true })
      await sticky.waitFor()
      const originalColor = await sticky.locator('section, div').first().evaluate(node => getComputedStyle(node).backgroundColor)
      await sticky.getByRole('button', { name: 'Make a follow-up', exact: true }).click()
      const dialog = page.getByRole('dialog', { name: 'Make a follow-up', exact: true })
      await dialog.getByLabel('Action', { exact: true }).fill('Call Michelle about Tuesday')
      await dialog.getByLabel('Related lead or contact').selectOption('lead-michelle')
      await dialog.getByLabel('Owner', { exact: true }).selectOption('admin')
      await dialog.getByRole('button', { name: 'Create follow-up', exact: true }).click()
      assert.equal(await sticky.locator('section, div').first().evaluate(node => getComputedStyle(node).backgroundColor), originalColor)
      await sticky.getByRole('heading', { name: 'Call Michelle about Tuesday' }).waitFor()
      assert.match(await sticky.innerText(), /Check availability before calling/)
      await page.getByRole('combobox', { name: 'Show notes' }).selectOption('today')
      await page.getByRole('group', { name: 'Notes view' }).getByRole('button', { name: 'List', exact: true }).click()
      const table = page.getByRole('table', { name: 'Notes and follow-ups' })
      const row = table.getByRole('row').filter({ hasText: 'Call Michelle about Tuesday' })
      await row.getByRole('button', { name: 'Michelle Morgan · Lead', exact: true }).click()
      const person = page.getByRole('dialog', { name: 'Related person preview' })
      await person.getByRole('button', { name: 'Complete Call Michelle about Tuesday', exact: true }).click()
      await person.getByRole('button', { name: 'Reopen Call Michelle about Tuesday', exact: true }).waitFor()
      await person.getByRole('button', { name: 'Back to notes' }).click()
      assert.equal(await row.count(), 0)
      await page.getByRole('combobox', { name: 'Show notes' }).selectOption('completed')
      await row.getByRole('button', { name: 'Reopen Call Michelle about Tuesday' }).click()
      await page.getByRole('combobox', { name: 'Show notes' }).selectOption('all')
      await row.getByRole('button', { name: 'Reschedule / edit' }).click()
      await dialog.getByLabel('Due date').fill('2099-12-15')
      await dialog.getByRole('button', { name: 'Save follow-up' }).click()
      await page.getByRole('combobox', { name: 'Show notes' }).selectOption('upcoming')
      await row.getByText('Due 2099-12-15', { exact: true }).waitFor()
      await page.getByRole('combobox', { name: 'Related record type' }).selectOption('contact')
      assert.equal(await row.count(), 0)
      await page.getByRole('combobox', { name: 'Related record type' }).selectOption('lead')
      assert.equal(await row.count(), 1)
      await page.reload()
      await table.waitFor()
      await row.getByText('Due 2099-12-15', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'New sticky note', exact: true }).click()
      const create = page.getByRole('dialog', { name: 'New sticky note', exact: true })
      await create.getByLabel('Title', { exact: true }).fill('Front desk reminder')
      await create.getByLabel('Note', { exact: true }).fill('Spare keys are in the drawer. No action required.')
      await create.getByLabel('Sticky color').selectOption('blue')
      await create.getByRole('button', { name: 'Save note', exact: true }).click()
      const noteRow = table.getByRole('row').filter({ hasText: 'Front desk reminder' })
      assert.match(await noteRow.innerText(), /Not a task/)
      await page.getByRole('group', { name: 'Notes view' }).getByRole('button', { name: 'Cards', exact: true }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true)
      await page.screenshot({ path: `/private/tmp/notes-follow-ups-${width}.png`, fullPage: true })
      assert.deepEqual(errors, [])
      assert.deepEqual(writes, [])
      console.log(`PASS ${width}px: explicit conversion, retained color/context, shared completion, reopen/reschedule, filters, reload, no writes`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })