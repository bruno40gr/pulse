/* eslint-disable @typescript-eslint/no-require-imports -- Local-only actual-component preview; no real records. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.FOLLOW_UP_PREVIEW_URL || 'http://127.0.0.1:3226'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local preview only')
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    for (const [width, height] of [[1440, 1000], [390, 844], [844, 390]]) {
      const page = await browser.newPage({ viewport: { width, height } })
      const errors = []; const writes = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => { writes.push(route.request().url()); return route.abort() })
      await page.goto(base)
      const dialog = page.getByRole('dialog', { name: 'Alex Morgan follow-up', exact: true })
      await dialog.waitFor()
      const save = dialog.getByRole('button', { name: 'Save follow-up', exact: true })
      assert.equal(await save.isEnabled(), true)
      await page.screenshot({ path: `/tmp/pulse-follow-up-modal-${width}x${height}.png`, fullPage: true })
      const box = await dialog.boundingBox()
      assert.ok(box.x >= 0 && box.x + box.width <= width + 1)
      assert.ok(box.y >= 0 && box.y + box.height <= height + 1)
      const footer = await save.boundingBox()
      assert.ok(footer.y >= 0 && footer.y + footer.height <= height)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      await save.click()
      await dialog.getByText('Choose a follow-up date.', { exact: true }).waitFor()
      await dialog.getByLabel('Quick pick', { exact: true }).selectOption('tomorrow')
      await dialog.getByLabel('Reminder note', { exact: true }).fill('Call after school')
      await save.click()
      await dialog.waitFor({ state: 'hidden' })
      await page.getByText('Follow-up saved in this preview only.', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Save failure: Off', exact: true }).click()
      await page.getByRole('button', { name: 'Preview existing follow-up', exact: true }).click()
      await dialog.getByLabel('Reminder note', { exact: true }).fill('Keep my failed draft')
      await save.click()
      await dialog.getByText('Could not save follow-up. Your draft is retained. Please try again.', { exact: true }).waitFor()
      assert.equal(await dialog.getByLabel('Reminder note', { exact: true }).inputValue(), 'Keep my failed draft')
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      await page.getByRole('button', { name: 'Save failure: On', exact: true }).click()
      await page.getByRole('button', { name: 'Preview existing follow-up', exact: true }).click()
      await dialog.getByRole('button', { name: 'Clear follow-up', exact: true }).click()
      await dialog.waitFor({ state: 'hidden' })
      await page.getByText('Follow-up cleared in this preview only.', { exact: true }).waitFor()
      assert.deepEqual(errors, []); assert.deepEqual(writes, [])
      console.log(`PASS ${width}x${height}: visible modal/footer, no horizontal overflow, validation, quick pick, save, failed draft, Escape, clear; no API calls`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })