/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional UI checks. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:3231'
assert.match(base, /^http:\/\/127\.0\.0\.1:/)

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [390, 1440]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 }, hasTouch: width === 390 })
      page.setDefaultTimeout(30000)
      const errors = [], writes = []
      page.on('pageerror', error => errors.push(error.message))
      page.on('request', request => { if (request.url().includes('/api/') && request.method() !== 'GET') writes.push(request.url()) })
      await page.goto(`${base}/odeon-demo?screen=calendar`)
      await page.getByRole('heading', { name: 'Academy calendar', exact: true }).waitFor()
      if (width === 390) {
        await page.getByRole('button', { name: 'Filters', exact: true }).waitFor()
        assert.equal(await page.getByRole('button', { name: 'Staff: All', exact: true }).count(), 0)
        await page.getByLabel('Calendar date', { exact: true }).waitFor()
        await page.getByRole('group', { name: 'View by', exact: true }).waitFor()
        await page.getByRole('button', { name: 'Filters', exact: true }).click()
        const filters = page.getByRole('dialog', { name: 'Calendar filters', exact: true })
        await filters.waitFor()
        assert.equal(await filters.getByLabel('Calendar date', { exact: true }).count(), 0)
        assert.equal(await filters.getByRole('group', { name: 'Calendar range', exact: true }).count(), 0)
        const staff = filters.locator('fieldset').filter({ has: page.locator('legend', { hasText: /^Staff$/ }) })
        await staff.getByRole('checkbox').nth(1).check()
        await staff.getByRole('checkbox').nth(2).check()
        await filters.getByRole('button', { name: 'Done', exact: true }).click()
        assert.equal(await page.locator('[data-resource-column]').count(), 2)
        await page.getByRole('button', { name: 'Filters (2)', exact: true }).click()
        await filters.getByRole('button', { name: 'Reset filters', exact: true }).click()
        await page.keyboard.press('Escape')
        await filters.waitFor({ state: 'hidden' })
        assert.equal(await page.getByRole('button', { name: 'Filters', exact: true }).evaluate(element => element === document.activeElement), true)
        const slot = page.locator('button[aria-label^="Book "]:not(:disabled)').first()
        await slot.dispatchEvent('pointerdown', { pointerType: 'touch', button: 0 })
        await page.waitForTimeout(650)
        await slot.dispatchEvent('pointerup', { pointerType: 'touch', button: 0 })
        await slot.dispatchEvent('click', { detail: 1 })
        assert.equal(await page.getByRole('dialog').count(), 0, 'Touch hold never opens booking')
        await slot.dispatchEvent('pointerdown', { pointerType: 'mouse', button: 0 })
        await slot.dispatchEvent('pointerup', { pointerType: 'mouse', button: 0 })
        assert.equal(await page.getByRole('dialog').count(), 0, 'Narrow viewport disables drawing even with a mouse')
        await page.getByRole('group', { name: 'Calendar range', exact: true }).getByRole('button', { name: 'Week', exact: true }).click()
        assert.equal(await page.getByLabel('Week teacher', { exact: true }).count(), 0)
        await page.getByRole('button', { name: 'Filters', exact: true }).click()
        await filters.getByLabel('Week teacher', { exact: true }).selectOption({ index: 1 })
        await filters.getByRole('button', { name: 'Done', exact: true }).click()
        assert.equal(await page.locator('[data-resource-column]').count(), 7)
        await page.getByRole('button', { name: 'Add booking', exact: true }).click()
        await page.getByRole('dialog').waitFor()
        await page.keyboard.press('Escape')
        await page.screenshot({ path: '/tmp/odeon-mobile-calendar-filters.png', fullPage: true })
      }
      await page.goto(`${base}/odeon-demo?screen=staff`)
      if (width === 390) await page.getByRole('button', { name: 'Open menu', exact: true }).click()
      const teacherLink = page.getByRole('link', { name: 'Teacher day', exact: true })
      assert.equal(await teacherLink.evaluate(element => element.nextElementSibling.textContent.trim()), 'Calendar')
      await teacherLink.click()
      await page.getByRole('heading', { name: 'My teaching day', exact: true }).waitFor()
      const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('odeon:app-sample:v2')).snapshot.data.lessons)
      assert.equal(await page.getByText('Fictional records only').count(), 0, 'A teacher screen carries no demo banner')
      await page.getByLabel('Teaching date', { exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'This week', exact: true }).count(), 0, 'Day mode has no week controls')
      assert.match(await page.locator('[data-teacher-experience]').innerText(), /Today, [A-Z][a-z]{2} [A-Z][a-z]{2} \d{1,2}/, 'The section starts with one plain date heading')
      assert.deepEqual((await page.locator('[aria-label="Teaching summary"] > *').allInnerTexts()).map(text => text.replace(/\s+/g, ' ').trim()),
        ['Sessions 4', 'Students 4', 'Attendance to mark 4', 'Lesson notes to add 4'])
      await page.getByRole('group', { name: 'Teaching range', exact: true }).getByRole('button', { name: 'Week', exact: true }).click()
      await page.getByRole('button', { name: 'This week', exact: true }).waitFor()
      assert.equal(await page.getByLabel('Teaching date', { exact: true }).count(), 0, 'Week mode has no day picker')
      assert.equal(await page.getByRole('button', { name: 'Families', exact: true }).count(), 0)
      assert.equal(await page.getByText(/Sample-only mockup/).count(), 0, 'No prototype banner')
      assert.equal(await page.getByLabel('Preview teacher').count(), 1, 'Owners can preview a teacher')
      const firstAttendance = page.getByRole('group', { name: /^Attendance for / }).first()
      await firstAttendance.getByRole('button', { name: 'Present', exact: true }).click()
      assert.equal(await firstAttendance.getByRole('button', { name: 'Present', exact: true }).getAttribute('aria-pressed'), 'true')
      await page.getByRole('group', { name: 'Teacher workspace', exact: true }).getByRole('button', { name: /^To do/ }).click()
      await page.getByRole('button', { name: 'Leave notes', exact: true }).first().click()
      const noteDialog = page.getByRole('dialog', { name: 'Leave notes', exact: true })
      await noteDialog.getByLabel(/^Lesson note for /).first().fill('Great progress. Practise slowly this week.')
      await noteDialog.getByRole('button', { name: 'Save note', exact: true }).first().click()
      await noteDialog.getByText('Saved · not published', { exact: true }).waitFor()
      await noteDialog.getByRole('button', { name: 'Done', exact: true }).click()
      await page.getByRole('group', { name: 'Teacher workspace', exact: true }).getByRole('button', { name: /^Schedule/ }).click()
      await page.getByRole('button', { name: 'Send message', exact: true }).first().click()
      await page.getByLabel('Family', { exact: true }).selectOption({ index: 1 })
      await page.getByLabel('SMS draft', { exact: true }).fill('Thank you for a great lesson!')
      await page.getByRole('button', { name: 'Save draft', exact: true }).click()
      await page.getByText('Draft · not sent', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Email', exact: true }).click()
      await page.getByLabel('Email draft', { exact: true }).fill('Email follow-up')
      await page.getByRole('button', { name: 'Save draft', exact: true }).click()
      assert.equal(await page.getByText('Draft · not sent', { exact: true }).count(), 2)
      await page.getByRole('dialog', { name: 'Message family', exact: true }).getByRole('button', { name: 'Done', exact: true }).click()
      await page.getByRole('button', { name: 'Availability', exact: true }).click()
      await page.getByText(/Published teaching hours/).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Add availability', exact: true }).count(), 0, 'Only the school office edits availability')
      assert.equal(await page.getByRole('button', { name: 'Add Time Off', exact: true }).count(), 0)
      assert.equal(await page.getByText('Save sample proposal', { exact: true }).count(), 0, 'Availability reuses the setup editor')
      await page.getByRole('button', { name: 'Profile', exact: true }).click()
      await page.getByLabel('Name', { exact: true }).waitFor()
      await page.getByLabel('Email', { exact: true }).waitFor()
      await page.getByText('Teaching skills by level', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Save profile', exact: true }).waitFor()
      for (const tab of ['Schedule', 'To do', 'Availability', 'Profile']) {
        await page.getByRole('group', { name: 'Teacher workspace', exact: true }).getByRole('button', { name: new RegExp(`^${tab}`) }).click()
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${tab}: no overflow at ${width}`)
        await page.screenshot({ path: `/tmp/odeon-teacher-${tab.replace(' ', '-')}-${width}.png`, fullPage: true })
      }
      const lessonsAfter = await page.evaluate(() => JSON.parse(localStorage.getItem('odeon:app-sample:v2')).snapshot.data.lessons)
      assert.deepEqual(lessonsAfter, saved, 'Teacher preview never moves or cancels lessons')

      assert.deepEqual(writes, [], 'Mockup never writes to APIs')
      await page.reload()
      await page.getByRole('heading', { name: 'My teaching day', exact: true }).waitFor()
      assert.equal(await page.getByText('Draft · not sent', { exact: true }).count(), 0, 'Drafts are not persisted')
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: calendar controls, teacher schedule/tasks/drafts/availability, no live writes/errors/overflow`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })