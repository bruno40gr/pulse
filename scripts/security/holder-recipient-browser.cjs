/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional fixture only. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 390]) {
      for (const three of [false, true]) {
        const page = await browser.newPage({ viewport: { width, height: 1000 } })
        page.setDefaultTimeout(8000)
        const sends = [], errors = []
        page.on('pageerror', error => errors.push(error.message))
        await page.route('**/api/campaigns**', route => { sends.push(route.request().url()); return route.abort() })
        if (three) {
          const response = await page.request.get(`${process.env.CONTACT_ROLE_REVIEW_ORIGIN || 'http://127.0.0.1:3218'}/api/contacts`)
          const contacts = await response.json()
          contacts.find(contact => contact.id === 'mock-sophie').account_holders.push({ person_id: 'mock-taylor', name: 'Taylor Kim', phone: '(202) 555-0107', is_primary: false })
          await page.route('**/api/contacts?*', route => route.fulfill({ json: contacts }))
        }
        await page.goto(`${process.env.CONTACT_ROLE_REVIEW_ORIGIN || 'http://127.0.0.1:3218'}/dashboard/contacts`)
        const table = page.getByRole('table', { name: 'Contacts', exact: true })
        const nameWeight = name => table.getByRole('button', { name, exact: true }).locator('[data-person-name]').evaluate(el => getComputedStyle(el).fontWeight)
        assert.equal(await nameWeight('Jamie Kim'), await nameWeight('Sam Kim'))
        assert.ok(Number(await nameWeight('Jamie Kim')) > Number(await nameWeight('Sophie Kim')))
        const familyOrder = await table.locator('[data-person-name]').allTextContents()
        const samIndex = familyOrder.indexOf('Sam Kim')
        assert.deepEqual(familyOrder.slice(samIndex, samIndex + 4), ['Sam Kim', 'Jamie Kim', 'Ethan Kim', 'Sophie Kim'])
        await table.getByRole('button', { name: 'Sophie Kim', exact: true }).click()
        await page.getByRole('button', { name: 'Send SMS', exact: true }).click()
        const dialog = page.getByRole('dialog', { name: 'Send a Text Message', exact: true })
        const rows = dialog.getByRole('list', { name: 'Account holder recipients' })
        await rows.getByText('Sam Kim', { exact: true }).waitFor()
        assert.equal(await rows.getByRole('button', { name: 'Remove Sam Kim' }).count(), 0)
        await table.getByRole('button', { name: 'Jamie Kim', exact: true }).waitFor({ state: 'attached' })
        const draft = dialog.getByPlaceholder('Write your message... Use {first_name} to personalize.')
        await draft.fill('Sophie has a schedule update.')
        await dialog.getByRole('button', { name: 'Add account holder' }).click()
        if (three) {
          const available = dialog.getByRole('group', { name: 'Available account holders' })
          await available.getByRole('button', { name: 'Jamie Kim', exact: true }).waitFor()
          await available.getByRole('button', { name: 'Jamie Kim', exact: true }).press('Escape')
          assert.equal(await dialog.getByRole('button', { name: 'Add account holder' }).getAttribute('aria-expanded'), 'false')
          await dialog.getByRole('button', { name: 'Add account holder' }).click()
          await available.getByRole('button', { name: 'Jamie Kim', exact: true }).click()
          const lastRow = rows.getByRole('listitem').last()
          assert.equal(await lastRow.getByRole('button', { name: 'Remove Jamie Kim' }).count(), 1)
          assert.equal(await lastRow.getByRole('button', { name: 'Add account holder' }).count(), 1)
          await page.screenshot({ path: `/tmp/pulse-holder-inline-mixed-${width}.png` })
          await dialog.getByRole('button', { name: 'Add account holder' }).click()
          await rows.getByText('Taylor Kim', { exact: true }).waitFor()
        }
        await rows.getByText('Jamie Kim', { exact: true }).waitFor()
        assert.equal(await rows.getByRole('listitem').count(), three ? 3 : 2)
        assert.equal(await draft.inputValue(), 'Sophie has a schedule update.')
        assert.equal(await dialog.getByRole('button', { name: 'Add account holder' }).count(), 0)
        await page.screenshot({ path: `/tmp/pulse-holder-rows-${three ? 3 : 2}-${width}.png` })
        await rows.getByRole('button', { name: 'Remove Sam Kim', exact: true }).click()
        if (three) await rows.getByRole('button', { name: 'Remove Taylor Kim', exact: true }).click()
        assert.equal(await rows.getByRole('button', { name: 'Remove Jamie Kim', exact: true }).count(), 0)
        assert.equal(await rows.getByRole('listitem').last().getByRole('button', { name: 'Add account holder' }).count(), 1)
        await page.screenshot({ path: `/tmp/pulse-holder-inline-single-${three ? 3 : 2}-${width}.png` })
        assert.equal(await rows.getByRole('listitem').count(), 1)
        await dialog.getByRole('button', { name: 'Send message', exact: true }).click()
        await dialog.getByRole('status').filter({ hasText: 'Message sent.' }).waitFor()
        assert.deepEqual(sends, [])
        assert.deepEqual(errors, [])
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
        await dialog.getByRole('button', { name: 'Back to contact', exact: true }).click()
        await page.getByRole('button', { name: 'Close', exact: true }).click()
        await table.getByRole('button', { name: 'Emma Smith', exact: true }).click()
        await page.getByRole('button', { name: 'Send SMS', exact: true }).click()
        assert.equal(await dialog.getByRole('button', { name: 'Add account holder' }).count(), 0)
        assert.equal(await dialog.getByLabel('SMS message', { exact: true }).evaluate(el => Array.from(el.labels || []).some(label => label.textContent === 'About Emma Smith')), true)
        console.log(`PASS ${width}, ${three ? 3 : 2} holders: add/remove, last retained, stable rows, draft, simulated send, single-holder label`)
        await page.unrouteAll({ behavior: 'wait' })
        await page.close()
      }
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
