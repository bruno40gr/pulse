/* eslint-disable @typescript-eslint/no-require-imports -- Isolated sample-data browser review. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')

;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 900, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      const errors = [], writes = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => {
        if (new URL(route.request().url()).pathname === '/api/inbox/reconcile') return route.fulfill({ json: { skipped: true } })
        if (route.request().method() !== 'GET') writes.push(route.request().url())
        return route.fulfill({ json: {} })
      })
      await page.goto(process.env.CONTACTS_SHELL_URL || 'http://127.0.0.1:3218/dashboard/design/contacts-table')
      const table = page.getByRole('table', { name: 'Contacts prototype', exact: true })
      const results = page.getByRole('region', { name: 'Table results and actions' })
      await table.waitFor()
      assert.match(await results.innerText(), /12 contacts/)
      assert.equal(await results.getByRole('button', { name: 'Text', exact: true }).isDisabled(), true)
      assert.equal(await results.getByRole('button', { name: 'Clear selection' }).count(), 0)
      await page.getByRole('button', { name: 'Enroll new student', exact: true }).waitFor()
      const editX = (await results.getByRole('button', { name: 'Edit', exact: true }).boundingBox()).x
      await page.getByRole('button', { name: 'Filters', exact: true }).click()
      const dialog = page.getByRole('dialog')
      assert.ok((await dialog.boundingBox()).width <= (width <= 960 ? width : 380), 'Narrow desktop drawer; existing full-screen mobile convention')
      await dialog.getByLabel('Service type', { exact: true }).selectOption('Private lessons')
      await dialog.getByLabel('Status', { exact: true }).selectOption('Active')
      assert.match(await results.innerText(), /12 contacts/, 'Draft filters do not update results')
      await page.screenshot({ path: `/private/tmp/pulse-contacts-shell-filters-${width}.png`, fullPage: true })
      await dialog.getByRole('button', { name: 'Submit search' }).click()
      assert.match(await results.innerText(), /3 contacts/, 'Filters aggregate with AND')
      await page.getByRole('button', { name: 'Remove Service type filter' }).click()
      assert.match(await results.innerText(), /6 contacts/)
      await page.getByRole('button', { name: 'Remove Status filter' }).click()
      await table.getByRole('checkbox', { name: 'Select all visible contacts', exact: true }).check()
      assert.match(await results.innerText(), /12 contacts · 5 selected/)
      assert.equal((await results.getByRole('button', { name: 'Edit', exact: true }).boundingBox()).x, editX, 'Selection does not shift action buttons')
      assert.equal(await results.getByText('Bulk Edit', { exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Next', exact: true }).click()
      assert.match(await results.innerText(), /5 selected/)
      await results.getByRole('button', { name: 'Clear selection' }).click()
      await page.getByRole('textbox', { name: 'Search contacts', exact: true }).fill('Morgan')
      await page.getByRole('button', { name: 'Search', exact: true }).click()
      assert.match(await results.innerText(), /1 contact/)
      await table.getByRole('checkbox', { name: 'Select Olivia Morgan', exact: true }).check()
      await results.getByRole('button', { name: 'Email', exact: true }).click()
      assert.match(await page.getByRole('dialog').innerText(), /morgan@example.invalid/)
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: 'Search: Morgan' }).click()
      await page.getByRole('group', { name: 'Contact view', exact: true }).getByRole('switch', { name: 'Families', exact: true }).check()
      assert.equal(await table.getByRole('checkbox').count(), 13)
      await page.getByRole('button', { name: 'Table Preferences', exact: true }).click()
      await page.getByRole('combobox', { name: 'Row spacing' }).selectOption('compact')
      await page.keyboard.press('Escape')
      await page.screenshot({ path: `/private/tmp/pulse-contacts-shell-selected-${width}.png`, fullPage: true })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'No page-level overflow')
      assert.deepEqual(errors, [])
      assert.deepEqual(writes, [])
      console.log(`PASS ${width}px: draft/aggregate filters, selection, pagination, messaging preview, family view, preferences, no writes`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })