/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional billing regression. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')

;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = []
      page.setDefaultTimeout(10000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        return route.continue()
      })
      await page.goto(`${base}?prototype=v3&view=quick&account=preview%3Akim&section=billing`)
      const invoices = page.getByRole('region', { name: 'Invoices', exact: true })
      await invoices.getByRole('button', { name: 'Past invoices', exact: true }).click()
      await invoices.getByRole('button', { name: 'View invoice DEMO-1002', exact: true }).waitFor()
      assert.equal(await invoices.getByRole('button', { name: 'Pay $200', exact: true }).count(), 0)
      await page.screenshot({ path: `/tmp/odeon-invoice-history-${width}.png`, fullPage: true })
      await invoices.getByRole('button', { name: 'View invoice DEMO-1002', exact: true }).click()
      await page.getByRole('button', { name: 'Download invoice DEMO-1002', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Refund', exact: true }).click()
      const refund = page.getByRole('dialog', { name: 'Refund invoice', exact: true })
      const confirm = refund.getByRole('button', { name: 'Refund', exact: true })
      assert.equal(await confirm.isDisabled(), true)
      await refund.getByRole('textbox', { name: 'Refund reason', exact: true }).fill('Lesson credit correction')
      await confirm.click()
      assert.equal(await refund.isVisible(), true, 'Quick click never refunds')
      await confirm.click({ delay: 300 })
      assert.equal(await refund.isVisible(), true, 'Early release never refunds')
      await refund.getByRole('button', { name: 'Cancel', exact: true }).click()
      assert.equal(await page.getByRole('article', { name: 'Itemized invoice', exact: true }).getByText('Paid', { exact: true }).count(), 2, 'Cancelling preserves paid state and amount label')
      await page.getByRole('button', { name: 'Refund', exact: true }).click()
      await refund.getByRole('textbox', { name: 'Refund reason', exact: true }).fill('Lesson credit correction')
      await confirm.click({ delay: 1700 })
      await refund.waitFor({ state: 'hidden' })
      const confirmation = page.getByRole('dialog', { name: 'Confirmation', exact: true })
      await confirmation.getByRole('button', { name: 'Done', exact: true }).click()
      await page.getByRole('article', { name: 'Itemized invoice', exact: true }).getByText('Lesson credit correction', { exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Refund', exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Back to invoices', exact: true }).click()
      await invoices.getByText('Refunded', { exact: true }).waitFor()
      await page.goto(`${base}?prototype=v3&view=parent&account=preview%3Akim&portal=billing`)
      const portal = page.getByRole('main', { name: 'Parent portal', exact: true })
      const parentInvoices = portal.getByRole('region', { name: 'Your invoices', exact: true })
      await parentInvoices.getByRole('button', { name: 'Past invoices', exact: true }).click()
      await parentInvoices.getByRole('button', { name: 'View invoice DEMO-1002', exact: true }).click()
      await portal.getByRole('button', { name: 'Download invoice DEMO-1002', exact: true }).waitFor()
      assert.equal(await portal.getByRole('button', { name: 'Refund', exact: true }).count(), 0, 'Refunds are staff-only')
      await portal.getByRole('button', { name: 'Back to invoices', exact: true }).click()
      await parentInvoices.getByRole('button', { name: 'Unpaid', exact: true }).click()
      assert.equal(await parentInvoices.getByRole('button', { name: 'View invoice DEMO-1004', exact: true }).count(), 0, 'Other payer invoices remain private')
      await parentInvoices.getByRole('button', { name: 'Pay $200', exact: true }).click()
      const payment = page.getByRole('dialog', { name: 'Pay', exact: true })
      const pay = payment.getByRole('button', { name: 'Pay', exact: true })
      await pay.click()
      assert.equal(await payment.isVisible(), true, 'Parent payment requires the same deliberate hold')
      await pay.click({ delay: 300 })
      assert.equal(await payment.isVisible(), true)
      await pay.focus()
      await page.keyboard.down('Space')
      await page.waitForTimeout(400)
      assert.equal(await pay.textContent(), 'Pay', 'Parent action label remains action-only')
      assert.equal(await pay.locator('.lb-fill').count(), 1)
      await page.keyboard.up('Space')
      await pay.click({ delay: 1700 })
      await payment.waitFor({ state: 'hidden' })
      await page.getByRole('dialog', { name: 'Confirmation', exact: true }).getByRole('button', { name: 'Done', exact: true }).click()
      await parentInvoices.getByRole('button', { name: 'Past invoices', exact: true }).click()
      await parentInvoices.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).waitFor()
      await page.screenshot({ path: `/tmp/odeon-parent-invoice-history-${width}.png`, fullPage: true })
      assert.deepEqual(errors, [])
      console.log(`PASS staff invoice history/refund, parent history/privacy and hold payment ${width}px`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })