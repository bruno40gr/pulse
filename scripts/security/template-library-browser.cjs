/* eslint-disable @typescript-eslint/no-require-imports -- Optional mock preview browser runner. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const button = (root, name) => root.getByRole('button', { name, exact: true })
    const library = page.getByRole('dialog', { name: 'Email templates', exact: true })
    const composer = page.getByRole('region', { name: 'Email composer', exact: true })
    await page.goto(process.env.WORKSPACE_REVIEW_URL || 'http://127.0.0.1:3101')
    await button(page, 'Open conversation with Alex Chen').click()
    await button(page, 'Email').click()
    await button(page, 'Read email: Piano lessons for Jamie').click()
    assert.equal(await page.getByRole('navigation', { name: 'Workspace breadcrumbs' }).count(), 0)
    await button(page, 'Back to Communications').waitFor()
    await button(page, 'New email').click()
    await composer.waitFor()
    assert.equal(await library.count(), 0)
    assert.equal(await page.getByRole('dialog', { name: 'New message', exact: true }).count(), 0)
    await button(composer, 'Use template').click(); await library.waitFor()
    assert.equal(await library.getByText(/Suggested|previous outbound/).count(), 0)
    assert.equal(await button(library, 'Use template').isDisabled(), true)
    assert.equal(await button(library, 'Replace draft').count(), 0)
    await page.screenshot({ path: '/tmp/pulse-library-no-suggestions.png', fullPage: true })
    const gallery = library.getByRole('region', { name: 'Template gallery', exact: true })
    assert.equal(await gallery.getByRole('button').count(), 8)
    assert.equal(await library.getByRole('textbox').count(), 0)
    assert.equal(await library.getByRole('combobox').count(), 0)
    assert.equal(await button(library, 'Create template').count(), 0)
    assert.equal(await library.getByText(/reusable starting point|preview session/i).count(), 0)
    await button(library, 'Friendly follow-up').click()
    await button(library, 'Use template').click()
    assert.equal(await composer.getByRole('textbox', { name: 'Email subject', exact: true }).inputValue(), 'Checking in about lessons')
    assert.ok((await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText()).includes('Hi Alex'))
    assert.equal(await button(composer, 'Remove Alex Chen from To').count(), 0)
    assert.equal(await composer.getByRole('searchbox').count(), 0)
    await button(composer, 'Send email').click()
    await button(page, 'New email').click(); await button(composer, 'Use template').click(); await library.waitFor()
    await button(library, 'Friendly follow-up').click()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    assert.ok(await library.evaluate(element => element.scrollWidth <= element.clientWidth))
    await page.screenshot({ path: '/tmp/pulse-library-mobile.png', fullPage: true })
    await button(library, 'Write from scratch').click()
    await button(composer, 'Use template').click(); await library.waitFor()
    await page.keyboard.press('Escape')
    await library.waitFor({ state: 'detached' })
    assert.equal(await button(composer, 'Use template').evaluate(element => element === document.activeElement), true)
    assert.deepEqual(errors, [])
    console.log('PASS: direct contact email; single back navigation; manual selection without suggestions; eight-template selection-only gallery; mobile overflow; Escape/focus restoration')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })