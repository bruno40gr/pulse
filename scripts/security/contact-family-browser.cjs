/* eslint-disable @typescript-eslint/no-require-imports -- Optional isolated lab; no live routes or services. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')

;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 900, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      const errors = [], requests = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => { requests.push(route.request().url()); return route.abort() })
      await page.goto(process.env.CONTACT_FAMILY_REVIEW_URL || 'http://127.0.0.1:3198')
      const tree = page.getByRole('treegrid', { name: 'Contacts families' })
      const holder = page.getByRole('row', { name: 'Open Kim family', exact: true })
      const sophie = page.getByRole('row', { name: 'Open Sophie family', exact: true })
      await holder.waitFor()
      await sophie.getByText('To: Sam', { exact: true }).waitFor()
      await sophie.getByText('Regarding: Sophie', { exact: true }).waitFor()
      const review = page.getByRole('region', { name: 'Recipient review' })
      await page.getByRole('checkbox', { name: 'Select Sophie', exact: true }).check()
      await page.getByRole('checkbox', { name: 'Select Ethan', exact: true }).check()
      await review.getByText('2 people selected → 1 recipient', { exact: true }).waitFor()
      await review.getByText('Regarding: Ethan, Sophie', { exact: true }).waitFor()
      assert.equal(await review.getByRole('list', { name: 'Proposed recipients' }).getByRole('listitem').count(), 1)
      assert.equal(await page.getByText(/^Opened:/).count(), 0, 'Selecting does not open a profile')
      await holder.focus()
      await holder.press('ArrowLeft')
      assert.equal(await sophie.count(), 0)
      await holder.press('ArrowRight')
      await sophie.waitFor()
      await holder.press('ArrowRight')
      assert.equal(await page.getByRole('row', { name: 'Open Ethan family' }).evaluate(node => node === document.activeElement), true)
      await page.keyboard.press('ArrowDown')
      assert.equal(await sophie.evaluate(node => node === document.activeElement), true)
      await sophie.press('ArrowLeft')
      assert.equal(await holder.evaluate(node => node === document.activeElement), true)
      await holder.press('Enter')
      await page.getByText('Opened: preview:family / preview:Sam', { exact: true }).waitFor()
      await sophie.click()
      await page.getByText('Opened: preview:family / preview:Sophie', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'SMS', exact: true }).click()
      assert.equal(await page.getByRole('button', { name: 'SMS', exact: true }).getAttribute('aria-pressed'), 'true')
      await sophie.getByText('Not sendable: No verified messaging recipient', { exact: true }).waitFor()
      await review.getByText('2 people selected → 0 recipients', { exact: true }).waitFor()
      await review.getByRole('button', { name: 'See contacts', exact: true }).click()
      await review.getByText('Sophie — No verified messaging recipient', { exact: true }).waitFor()
      await review.getByText('Ethan — No verified messaging recipient', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Email', exact: true }).click()
      await page.getByRole('searchbox', { name: 'Search contacts' }).fill('Sophie')
      assert.equal(await tree.locator('[aria-level="1"]').count(), 1)
      await holder.waitFor()
      await page.getByRole('searchbox', { name: 'Search contacts' }).fill('Alex')
      await review.getByText('Selection includes people hidden by this search.', { exact: true }).waitFor()
      await review.getByText('2 people selected → 1 recipient', { exact: true }).waitFor()
      assert.equal(await tree.locator('[aria-level="1"]').count(), 1)
      assert.equal(await tree.locator('[aria-level="2"]').count(), 0)
      await page.getByRole('checkbox', { name: 'Select Alex', exact: true }).check()
      await review.getByText('3 people selected → 2 recipients', { exact: true }).waitFor()
      await review.getByRole('button', { name: 'Clear selection', exact: true }).click()
      await review.getByText('0 people selected → 0 recipients', { exact: true }).waitFor()
      await page.getByRole('searchbox', { name: 'Search contacts' }).fill('not-present')
      await page.getByText('No matching contacts', { exact: true }).waitFor()
      await page.getByRole('searchbox', { name: 'Search contacts' }).fill('')
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      await page.screenshot({ path: `/tmp/pulse-contact-family-${width}.png`, fullPage: true })
      assert.deepEqual(requests, [], 'No API calls from isolated family integration')
      assert.deepEqual(errors, [])
      console.log(`PASS: family tree, recipient identity, channel switch, search, keyboard, no overflow/API calls at ${width}px`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })