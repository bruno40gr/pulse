/* eslint-disable @typescript-eslint/no-require-imports -- Local preview navigation only. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = 'http://127.0.0.1:3197'
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], writes = []
      page.setDefaultTimeout(10000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const request = route.request(), url = new URL(request.url())
        if (url.origin !== base) return route.abort()
        if (url.pathname.startsWith('/api/')) {
          if (['/api/contacts', '/api/tenant-fields', '/api/tenant/sync-status'].includes(url.pathname) && request.method() === 'GET') return route.continue()
          if (!['GET', 'HEAD'].includes(request.method())) writes.push(url.pathname)
          return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        }
        return route.continue()
      })
      await page.goto(`${base}/dashboard/contacts`)
      await page.getByRole('heading', { name: 'Contacts', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Import Contacts', exact: true }).waitFor()
      await page.getByRole('button', { name: /Filters/ }).waitFor()
      await page.getByRole('button', { name: '+ Add contact', exact: true }).waitFor()
      await page.getByText('Sophie Kim', { exact: true }).first().waitFor()
      assert.equal(await page.getByRole('dialog', { name: 'Filters', exact: true }).count(), 0)
      assert.equal(await page.getByRole('button', { name: /^Filters/ }).isDisabled(), true)
      const families = page.getByRole('button', { name: 'View families', exact: true })
      const students = page.getByRole('button', { name: 'View students', exact: true })
      await families.click()
      const table = page.getByRole('table', { name: 'Contacts', exact: true })
      const sam = table.getByRole('button', { name: 'Sam Kim', exact: true })
      const familyGroup = table.getByRole('rowgroup').filter({ has: page.getByRole('button', { name: 'Sam Kim', exact: true }) })
      const checkbox = familyGroup.getByRole('checkbox', { name: 'Select Sam Kim', exact: true })
      const nameBox = await sam.boundingBox(), checkBox = await checkbox.boundingBox()
      assert.ok(Math.abs(nameBox.y + nameBox.height / 2 - checkBox.y - checkBox.height / 2) < 3, 'Checkbox aligns with account holder')
      const backgrounds = await table.getByRole('rowgroup').evaluateAll(groups => groups.map(group => getComputedStyle(group.querySelector('[role="row"]')).backgroundColor))
      assert.notEqual(backgrounds[0], backgrounds[1], 'Alternating family stripes')
      const familyRow = familyGroup.getByRole('row').first()
      await page.getByRole('heading', { name: 'Contacts', exact: true }).hover()
      await page.waitForTimeout(150)
      const normal = await familyRow.evaluate(row => getComputedStyle(row).backgroundColor)
      await sam.hover()
      await page.waitForTimeout(150)
      const hover = await familyRow.evaluate(row => getComputedStyle(row).backgroundColor)
      assert.notEqual(normal, hover, 'Hover highlights entire family')
      await checkbox.check()
      await page.waitForTimeout(150)
      const selected = await familyRow.evaluate(row => getComputedStyle(row).backgroundColor)
      assert.notEqual(selected, normal, 'Selection distinct from zebra')
      assert.equal(await familyGroup.getByRole('checkbox').count(), 1)
      await page.screenshot({ path: `/tmp/odeon-family-table-selected-${width}.png`, fullPage: true })
      await checkbox.uncheck()
      await students.click()
      assert.equal(await students.getAttribute('aria-pressed'), 'true')
      assert.equal(await page.getByRole('button', { name: 'Sam Kim', exact: true }).count(), 0)
      await page.getByText('Table Preferences', { exact: true }).click()
      const columns = page.getByRole('group', { name: 'Visible columns', exact: true })
      await columns.getByRole('checkbox', { name: 'Email', exact: true }).uncheck()
      assert.equal(await columns.getByRole('checkbox', { name: 'Email', exact: true }).isChecked(), false)
      await columns.getByRole('checkbox', { name: 'Email', exact: true }).check()
      await page.getByText('Table Preferences', { exact: true }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      await page.screenshot({ path: `/tmp/odeon-real-contacts-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Sophie Kim', exact: true }).click()
      const panel = page.getByRole('dialog', { name: 'Family workspace V3', exact: true })
      await panel.waitFor()
      await panel.getByText('Student profile', { exact: true }).waitFor()
      await panel.getByRole('button', { name: 'Billing', exact: true }).click()
      await panel.getByRole('button', { name: 'Edit Contact', exact: true }).click()
      await panel.getByRole('heading', { name: 'Edit Contact', exact: true }).waitFor()
      await panel.getByRole('button', { name: 'Cancel', exact: true }).click()
      await page.screenshot({ path: `/tmp/odeon-real-contacts-slidepanel-${width}.png`, fullPage: true })
      await panel.getByRole('button', { name: 'Close', exact: true }).click()
      await panel.waitFor({ state: 'hidden' })
      await families.click()
      await page.screenshot({ path: `/tmp/odeon-contact-families-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Sam Kim', exact: true }).click()
      await panel.waitFor()
      await panel.getByText('Account manager', { exact: true }).waitFor()
      await panel.getByRole('button', { name: 'Close', exact: true }).click()
      await panel.waitFor({ state: 'hidden' })
      assert.equal(await page.getByRole('navigation', { name: 'Odeon preview navigation' }).count(), 0)
      assert.equal(await page.getByRole('button', { name: 'Preview parent portal', exact: true }).count(), 0)
      if (width < 700) await page.getByRole('button', { name: /menu/i }).first().click()
      await page.getByRole('link', { name: 'Enrollments', exact: true }).click()
      await page.getByRole('heading', { name: 'Enrollment', exact: true }).waitFor()
      assert.equal(await page.getByText('Mock enrollments', { exact: true }).count(), 0)
      assert.equal(await page.getByText('Fictional records · changes stay in this browser.', { exact: true }).count(), 0)
      await page.getByRole('group', { name: /Enrollment progress:/ }).first().waitFor()
      await page.screenshot({ path: `/tmp/odeon-enrollment-nav-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: /Resume enrollment for/ }).first().click()
      await page.getByRole('heading', { name: 'Enroll a student', exact: true }).waitFor()
      assert.equal(await page.getByText('Draft only · proposed times are not reserved.', { exact: true }).count(), 0)
      await page.goto(`${base}/dashboard/contacts`)
      await page.getByRole('button', { name: '+ Enroll contact', exact: true }).click()
      await page.getByRole('heading', { name: 'Enroll a student', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      await page.getByRole('heading', { name: 'Enrollment', exact: true }).waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      assert.deepEqual(errors, [])
      // Existing dashboard shell reconciliation is intercepted above, never sent.
      assert.deepEqual(writes.filter(path => path !== '/api/inbox/reconcile'), [])
      console.log(`PASS Contacts family checkbox alignment, zebra/hover/selection, views, preferences, profile and enrollment ${width}px`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })