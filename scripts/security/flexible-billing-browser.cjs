/* eslint-disable @typescript-eslint/no-require-imports -- Local preview only. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = []
      page.setDefaultTimeout(15000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.hostname === 'res.cloudinary.com' && route.request().resourceType() === 'image') return route.continue()
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        return route.continue()
      })
      await page.clock.install({ time: new Date('2026-11-10T12:00:00Z') })
      await page.goto(`${base}?prototype=v3&view=quick&account=preview%3Akim&section=billing`)
      const openIssue = async () => {
        await page.getByRole('button', { name: 'Billing actions', exact: true }).click()
        await page.getByRole('menuitem', { name: 'Create invoice', exact: true }).click()
        await page.getByLabel('Months to bill upfront', { exact: true }).fill('3')
      }
      const done = async text => {
        const confirmation = page.getByRole('dialog', { name: 'Confirmation', exact: true })
        if (text) await confirmation.getByText(text, { exact: true }).waitFor()
        await confirmation.getByRole('button', { name: 'Done', exact: true }).click()
      }
      await openIssue()
      assert.equal(await page.getByLabel('Student', { exact: true }).count(), 0)
      await page.getByRole('checkbox', { name: 'Sophie · Piano', exact: true }).check()
      await page.getByRole('checkbox', { name: 'Sophie · Voice', exact: true }).check()
      const liveTotal = page.getByRole('complementary', { name: 'Live invoice preview', exact: true }).locator('[aria-live]')
      assert.match(await liveTotal.innerText(), /\$[\d,]+\.\d{2}/)
      assert.doesNotMatch(await liveTotal.innerText(), /\$0\.00/)
      const draftHeading = await page.getByRole('heading', { name: /^Create invoice · DEMO-/ }).innerText()
      const draftId = draftHeading.split(' · ')[1]
      await page.getByLabel('Months to bill upfront', { exact: true }).fill('2')
      const pianoTwoMonths = page.locator('[data-subscription]').filter({ has: page.getByRole('checkbox', { name: 'Sophie · Piano', exact: true }) })
      await pianoTwoMonths.getByText('Nov 1, 2026 – Dec 31, 2026', { exact: true }).waitFor()
      const twoMonthTotal = await liveTotal.innerText()
      await page.getByLabel('Months to bill upfront', { exact: true }).fill('3')
      assert.notEqual(await liveTotal.innerText(), twoMonthTotal, 'An arbitrary two-month duration updates charges')
      assert.equal(await page.getByRole('heading', { name: draftHeading, exact: true }).count(), 1, 'Draft number is stable while editing')
      const reviewedTotal = await liveTotal.innerText()
      const voiceRow = page.locator('[data-subscription]').filter({ has: page.getByRole('checkbox', { name: 'Sophie · Voice', exact: true }) })
      await voiceRow.getByText('Nov 1, 2026 – Jan 31, 2027', { exact: true }).waitFor()
      const pianoRow = page.locator('[data-subscription]').filter({ has: page.getByRole('checkbox', { name: 'Sophie · Piano', exact: true }) })
      await pianoRow.getByText('Nov 1, 2026 – Jan 31, 2027', { exact: true }).waitFor()
      assert.equal(await page.getByText(/Replaces .*existing unpaid/).count(), 0)
      assert.equal(await page.getByText(/Partial month adjusted/).count(), 0)
      const configuration = page.getByRole('checkbox', { name: 'Sophie · Piano', exact: true })
      const livePreview = page.getByRole('complementary', { name: 'Live invoice preview', exact: true })
      const configBox = await configuration.boundingBox(), previewBox = await livePreview.boundingBox()
      if (width === 1440) {
        assert.ok(previewBox.x > configBox.x + configBox.width, 'Desktop preview sits beside configuration')
        assert.equal(await livePreview.evaluate(element => getComputedStyle(element).position), 'sticky')
      } else assert.ok(previewBox.y > configBox.y, 'Mobile preview stacks below configuration')
      assert.equal(await page.getByLabel('Payer', { exact: true }).isVisible(), true, 'Billing details are visible')
      assert.equal(await page.locator('form details').count(), 0, 'No hidden composer controls')
      for (const label of ['Coverage starts', 'Partial-period pricing', 'Months per invoice', 'Generate every (months)']) assert.equal(await page.getByLabel(label, { exact: true }).count(), 0)
      assert.equal(await page.getByText('Already covered · excluded', { exact: true }).count(), 0)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      const previewDividers = await livePreview.evaluate(element => { const lines = element.querySelectorAll('[class*=line]'); const last = [...lines].filter(item => item.className.includes('_line__')).pop(); return last ? getComputedStyle(last).borderBottomWidth : null })
      assert.equal(previewDividers, '0px', 'Last charge does not duplicate the amount-due divider')
      await page.screenshot({ path: `/tmp/odeon-composer-${width}.png`, fullPage: true })

      await page.getByLabel('Payer', { exact: true }).selectOption('')
      await page.getByLabel('Bill to (optional)', { exact: true }).fill('Arts Foundation')
      await page.getByLabel('Billing reference (optional)', { exact: true }).fill('Funding reference 42')
      await page.getByLabel('Issue date', { exact: true }).fill('2026-11-08')
      await page.getByLabel('Payment terms', { exact: true }).selectOption('45')
      await page.clock.resume()
      await page.getByRole('button', { name: 'Review invoice', exact: true }).click()
      const review = page.getByRole('dialog', { name: 'Review invoice', exact: true })
      assert.equal(await liveTotal.innerText(), reviewedTotal, 'Recipient edits do not change charges')
      await review.getByRole('article', { name: 'Itemized invoice', exact: true }).waitFor()
      await review.getByRole('heading', { name: `Invoice ${draftId}`, exact: true }).waitFor()
      const logo = review.getByRole('img', { name: 'Headliner Music Academy', exact: true })
      await logo.waitFor()
      await page.waitForFunction(() => [...document.querySelectorAll('img')].some(image => image.alt === 'Headliner Music Academy' && image.complete && image.naturalWidth > 0))
      await review.getByRole('table', { name: 'Invoice line items', exact: true }).waitFor()
      assert.equal(await review.getByText(/Replaces .*existing unpaid/).count(), 0)
      assert.equal(await review.getByText(/Partial month adjusted/).count(), 0)
      await review.getByRole('button', { name: 'Create invoice', exact: true }).click()
      assert.equal(await review.isVisible(), true, 'Early release must not issue')
      await page.screenshot({ path: `/tmp/odeon-flexible-review-${width}.png`, fullPage: true })
      await review.getByRole('button', { name: 'Back', exact: true }).click()
      await page.getByRole('button', { name: 'Review invoice', exact: true }).click()
      await review.getByRole('button', { name: 'Create invoice', exact: true }).click({ delay: 1700 })
      await done('Invoice issued.')
      const invoices = page.getByRole('region', { name: 'Invoices', exact: true })
      assert.equal(await invoices.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).count(), 0)
      assert.equal(await invoices.getByText('Replaced', { exact: true }).count(), 0)
      const view = invoices.getByRole('button', { name: /^View invoice DEMO-/ }).first()
      const id = (await view.getAttribute('aria-label')).replace('View invoice ', '')
      assert.equal(id, draftId, 'Created invoice retains its composer and review number')
      const download = page.waitForEvent('download')
      await invoices.getByRole('button', { name: `Download invoice ${id}`, exact: true }).click()
      assert.match((await download).suggestedFilename(), /\.pdf$/)
      await view.click()
      await page.getByRole('article', { name: 'Itemized invoice', exact: true }).getByText('Arts Foundation', { exact: true }).waitFor()
      await page.getByText('Preview payment and void controls', { exact: true }).click()
      await page.getByLabel('Payment amount', { exact: true }).fill('1')
      await page.getByRole('button', { name: 'Record preview payment', exact: true }).click({ delay: 1700 })
      await done('Preview payment recorded.')
      await page.getByText('Partially paid', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Back to invoices', exact: true }).click()
      await openIssue()
      await page.getByRole('checkbox', { name: 'Sophie · Piano', exact: true }).check()
      const nextPiano = page.locator('[data-subscription]').filter({ has: page.getByRole('checkbox', { name: 'Sophie · Piano', exact: true }) })
      assert.doesNotMatch(await nextPiano.innerText(), /\$0\.00|Already covered|excluded/)
      await page.getByRole('checkbox', { name: 'Ethan · Guitar', exact: true }).check()
      await page.getByLabel('Apply this billing period', { exact: true }).selectOption('repeat')
      assert.equal(await page.getByLabel('Months to bill upfront', { exact: true }).inputValue(), '3')
      await page.screenshot({ path: `/tmp/odeon-flexible-builder-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Review invoice', exact: true }).click()
      await review.getByRole('table', { name: 'Invoice line items', exact: true }).getByText('Ethan Kim', { exact: true }).first().waitFor()
      await review.getByText('Upfront every 3 months', { exact: true }).waitFor()
      await review.getByRole('button', { name: 'Create invoice', exact: true }).click({ delay: 1700 })
      await done('Invoice issued. Preview billing schedule saved.')
      const schedules = page.getByRole('region', { name: 'Billing schedules', exact: true })
      await schedules.getByRole('button', { name: 'Simulate next invoice', exact: true }).click()
      await done('Preview billing run completed. Already covered dates were skipped.')
      await schedules.getByRole('button', { name: 'Pause schedule', exact: true }).click()
      await done('Preview billing schedule updated.')
      assert.equal(await schedules.getByRole('button', { name: 'Simulate next invoice', exact: true }).count(), 0)
      await schedules.getByRole('button', { name: 'Resume schedule', exact: true }).click()
      await done()
      await schedules.getByText('Edit future invoices', { exact: true }).click()
      await schedules.getByLabel('Generate every (months)', { exact: true }).fill('6')
      await schedules.getByRole('button', { name: 'Save schedule changes', exact: true }).click()
      await done('Preview billing schedule updated.')
      await schedules.getByRole('button', { name: 'Cancel schedule', exact: true }).click()
      await done()
      await schedules.getByRole('heading', { name: 'Billing schedule · cancelled', exact: true }).waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      assert.deepEqual(errors, [])
      console.log(`PASS account-wide advance invoice, live totals, reservations, unpaid November–January replacement, full-month charges and branded review, PDF and recurring simulation ${width}px`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })