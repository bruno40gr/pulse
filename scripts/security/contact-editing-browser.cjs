/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional prototype regression tests. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], apis = []
      page.setDefaultTimeout(15000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) {
          const shell = ['/api/account/identity', '/api/account/claim-reminder', '/api/notifications', '/api/leads', '/api/inbox', '/api/inbox/reconcile', '/api/tenant/sync-status']
          if (!shell.includes(url.pathname)) { apis.push(url.pathname); return route.abort() }
          return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        }
        return route.continue()
      })
      await page.goto(`${base}?prototype=v3&view=parent&account=preview:kim`)
      const portal = page.locator('[data-parent-portal]')
      await portal.getByRole('heading', { name: 'Hi, Sam.', exact: true }).waitFor()
      const layout = await portal.evaluate(el => ({ position: getComputedStyle(el).position, x: el.getBoundingClientRect().x, width: el.getBoundingClientRect().width, overflow: el.scrollWidth > el.clientWidth + 1, nav: getComputedStyle(el.querySelector('nav')).display }))
      assert.equal(layout.position, 'fixed')
      assert.equal(layout.x, 0)
      assert.equal(layout.width, width)
      assert.equal(layout.overflow, false)
      assert.equal(layout.nav, 'flex')
      await portal.getByRole('button', { name: 'Account', exact: true }).click()
      await portal.getByRole('button', { name: 'Edit contact', exact: true }).first().click()
      assert.equal(await portal.getByRole('textbox', { name: 'First name', exact: true }).evaluate(el => el.labels.length), 1)
      await portal.getByRole('textbox', { name: 'First name', exact: true }).fill('Cancelled')
      await portal.getByRole('button', { name: 'Cancel', exact: true }).click()
      await portal.getByRole('button', { name: 'Edit contact', exact: true }).first().click()
      assert.equal(await portal.getByRole('textbox', { name: 'First name', exact: true }).inputValue(), 'Sam')
      await portal.getByRole('textbox', { name: 'First name', exact: true }).fill('Samuel')
      await portal.getByRole('button', { name: 'Save', exact: true }).click()
      await portal.getByText('Parent portal · Samuel Kim', { exact: true }).waitFor()
      const childContact = portal.getByRole('region', { name: 'Sophie Kim contact details', exact: true })
      await childContact.getByRole('button', { name: 'Edit contact', exact: true }).click()
      await childContact.getByRole('textbox', { name: 'Email', exact: true }).fill('sophie.edited@example.invalid')
      await childContact.getByRole('textbox', { name: 'Phone', exact: true }).fill('2025550199')
      await childContact.getByRole('button', { name: 'Save', exact: true }).click()
      await childContact.getByText('sophie.edited@example.invalid', { exact: true }).waitFor()
      await childContact.getByText('2025550199', { exact: true }).waitFor()
      await portal.getByText('sam.kim@example.invalid', { exact: true }).waitFor()
      assert.equal(await portal.getByRole('button', { name: 'Manage relationships', exact: true }).count(), 0)
      await portal.getByRole('button', { name: 'Manage Family Group', exact: true }).waitFor()
      await portal.getByRole('button', { name: 'Billing', exact: true }).click()
      await portal.getByRole('button', { name: 'Payment methods', exact: true }).click()
      await portal.getByRole('button', { name: 'Remove Visa ···· 4242', exact: true }).click()
      const removal = page.getByRole('dialog', { name: 'Remove saved card', exact: true })
      await removal.getByText(/will become the default/).waitFor()
      await removal.getByRole('button', { name: 'Cancel', exact: true }).click()
      assert.equal(await portal.getByRole('button', { name: 'Remove Visa ···· 4242', exact: true }).count(), 1)
      await portal.getByRole('button', { name: 'Remove Visa ···· 4242', exact: true }).click()
      await removal.getByRole('button', { name: 'Confirm remove card', exact: true }).click()
      assert.equal(await portal.getByRole('button', { name: 'Remove Visa ···· 4242', exact: true }).count(), 0)
      await page.screenshot({ path: `/tmp/odeon-contact-parent-${width}.png`, fullPage: true })
      await page.goto(`${base}?prototype=v3&view=quick&account=preview:mia-account&student=preview:mia&section=profile`)
      await page.getByRole('button', { name: 'Add account holder', exact: true }).click()
      const relationships = page.getByRole('dialog', { name: 'Manage relationships', exact: true })
      await relationships.getByRole('textbox', { name: 'Search contacts', exact: true }).fill('Sam')
      await relationships.getByRole('combobox', { name: 'Account holder', exact: true }).selectOption('preview:sam-kim')
      await relationships.getByRole('button', { name: 'Confirm account holder', exact: true }).click()
      await page.getByText('Primary account holder: Sam Kim', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Manage relationships', exact: true }).click()
      await relationships.getByRole('button', { name: 'Confirm unlink child', exact: true }).click()
      await relationships.waitFor({ state: 'hidden' })
      await page.goto(`${base}?prototype=v3&view=quick&account=preview:mia-account&student=preview:mia&section=profile`)
      await page.getByRole('button', { name: 'Add account holder', exact: true }).click()
      await relationships.getByRole('combobox', { name: 'Account holder', exact: true }).selectOption('new')
      await relationships.getByRole('textbox', { name: 'First name', exact: true }).fill('Morgan')
      await relationships.getByRole('textbox', { name: 'Last name', exact: true }).fill('Chen')
      await relationships.getByRole('textbox', { name: 'Email', exact: true }).fill('morgan.chen@example.invalid')
      await relationships.getByRole('button', { name: 'Confirm account holder', exact: true }).click()
      await page.getByText('Primary account holder: Morgan Chen', { exact: true }).waitFor()
      await page.goto(`${base}?prototype=v3&view=quick&account=preview:kim&student=preview:sophie&section=notes`)
      await page.getByRole('navigation', { name: 'Family sections', exact: true }).getByRole('button', { name: 'Account', exact: true }).click()
      await page.getByRole('button', { name: 'Edit contact', exact: true }).click()
      await page.getByRole('textbox', { name: 'Email', exact: true }).fill('sophie.direct@example.invalid')
      await page.getByRole('textbox', { name: 'Phone', exact: true }).fill('2025550188')
      await page.getByRole('button', { name: 'Save', exact: true }).click()
      await page.getByRole('button', { name: 'Send SMS', exact: true }).click()
      const messaging = page.getByRole('region', { name: 'Messaging Sophie Kim', exact: true })
      await messaging.getByText('2025550188', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Back to profile', exact: true }).click()
      await page.getByRole('button', { name: 'Send email', exact: true }).click()
      await messaging.getByText('sophie.direct@example.invalid', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Back to profile', exact: true }).click()
      await page.getByRole('navigation', { name: 'Family sections', exact: true }).getByRole('button', { name: 'Notes', exact: true }).click()
      await page.getByRole('button', { name: 'Add note', exact: true }).click()
      await page.getByPlaceholder('Write a note...').fill('Original authored note')
      await page.getByRole('button', { name: 'Save note', exact: true }).click()
      await page.getByRole('button', { name: 'Edit', exact: true }).click()
      await page.getByRole('textbox', { name: 'Edit note', exact: true }).fill('Updated authored note')
      await page.getByRole('button', { name: 'Save changes', exact: true }).click()
      await page.getByText('Updated authored note', { exact: true }).waitFor()
      await page.getByText(/Preview staff · .* · Edited /).waitFor()
      await page.getByRole('navigation', { name: 'Family sections', exact: true }).getByRole('button', { name: 'Account', exact: true }).click()
      await page.getByRole('button', { name: 'Manage relationships', exact: true }).click()
      await relationships.getByRole('button', { name: 'Confirm unlink child', exact: true }).click()
      await relationships.waitFor({ state: 'hidden' })
      await page.getByRole('heading', { name: 'Sophie Kim', exact: true }).waitFor()
      assert.ok(page.url().includes('unlinked'), 'Student remains selected in the standalone account')
      await page.getByRole('button', { name: 'Add account holder', exact: true }).waitFor()
      assert.deepEqual(errors, [])
      assert.deepEqual(apis, [])
      console.log(`PASS contact editing, parent layout, card confirmation, holder linking and note editing ${width}px`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
