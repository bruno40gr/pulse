/* eslint-disable @typescript-eslint/no-require-imports -- Optional isolated browser validation; mocked APIs only. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    for (const width of [1440, 900, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      const errors = [], emails = [], sms = []
      page.on('pageerror', error => errors.push(error.message))
      const people = ['Alex', 'Blair', 'Casey'].map((first_name, index) => ({ id: `00000000-0000-0000-0000-00000000010${index}`, first_name, last_name: 'Student', email: `${first_name.toLowerCase()}@example.com`, phone: '+12025550100', client_status: 'Active', is_minor: true, opted_out: false, account_holders: [], custom_fields: {} }))
      await page.route('**/api/**', route => {
        const request = route.request(), url = new URL(request.url())
        const fulfill = body => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) })
        if (url.pathname === '/api/contacts') return fulfill(people)
        if (url.pathname === '/api/tenant-fields' || url.pathname === '/api/staff' || url.pathname === '/api/conversations/templates') return fulfill(url.pathname.endsWith('templates') ? { templates: [] } : [])
        if (url.pathname === '/api/communications/recipients') return fulfill({ selectedCount: 3, recipients: [{ destination: 'parent1@example.com', name: 'Parent One', contactIds: [people[0].id, people[1].id] }, { destination: 'parent2@example.com', name: 'Parent Two', contactIds: [people[0].id, people[1].id] }], excluded: [{ id: people[2].id, name: 'Casey Student', reason: 'No account-holder details' }], version: 'reviewed-version' })
        if (url.pathname === '/api/communications/senders') return fulfill({ senders: width === 900 ? [{ id: 'office@example.com', email: 'office@example.com', name: 'Music Academy', mine: false }] : [{ id: 'teacher@example.com', email: 'teacher@example.com', name: 'Teacher', mine: true }, { id: 'office@example.com', email: 'office@example.com', name: 'Music Academy', mine: false }] })
        if (url.pathname === '/api/conversations/signature') return fulfill({ company: 'Music Academy', name: '', phone: '+12025550199', logoUrl: '' })
        if (url.pathname === '/api/communications/email') { emails.push(request.postDataJSON()); return fulfill({ sent: 2, failed: 0, uncertain: 0, pending: 0 }) }
        if (url.pathname === '/api/campaigns' && request.method() === 'POST') return fulfill({ id: 'synthetic-campaign' })
        if (url.pathname === '/api/campaigns/synthetic-campaign/send') { sms.push(request.postDataJSON()); return fulfill({ ok: true, sent: 2, failed: 0, missing_phone: 1 }) }
        if (url.pathname === '/api/contacts/check-sensitive') return fulfill({ flagged: [], opted_out: [] })
        if (url.pathname === '/api/media-suggestions') return fulfill({ approvedImages: [], suggestedGifs: [], detectedVibes: [], shouldAutoShowMedia: false, shouldShowThumbnails: false })
        return fulfill({})
      })
      await page.goto(process.env.BULK_REVIEW_URL || 'http://127.0.0.1:3111/bulk')
      await page.getByText('Viewing 3 contacts', { exact: true }).waitFor()
      await page.getByRole('checkbox', { name: 'Select all contacts', exact: true }).check()
      await page.getByRole('button', { name: 'Send email', exact: true }).click()
      await page.getByText('2 recipients', { exact: true }).waitFor()
      await page.getByText('1 contact cannot be reached by email.', { exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Manage recipients' }).count(), 0)
      assert.equal(await page.getByRole('combobox', { name: 'Send email from' }).count(), width === 900 ? 0 : 1)
      if (width !== 900) {
        await page.getByRole('combobox', { name: 'Send email from' }).selectOption('office@example.com')
      }
      await page.getByRole('textbox', { name: 'Email subject', exact: true }).fill('Updated lesson schedule')
      await page.getByRole('textbox', { name: 'Email body', exact: true }).fill('Hello families, here is the new schedule.')
      await page.getByRole('button', { name: 'Save as draft', exact: true }).click()
      await page.getByRole('button', { name: 'Send email', exact: true }).click()
      await page.getByRole('textbox', { name: 'Email subject', exact: true }).waitFor()
      assert.equal(await page.getByRole('textbox', { name: 'Email subject', exact: true }).inputValue(), 'Updated lesson schedule')
      const panel = page.getByRole('dialog').last()
      assert.ok(await panel.evaluate(node => node.scrollWidth <= node.clientWidth))
      await page.screenshot({ path: `/tmp/pulse-bulk-email-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Send 2 emails', exact: true }).click()
      await page.getByRole('textbox', { name: 'Email subject', exact: true }).waitFor({ state: 'hidden' })
      assert.equal(emails.length, 1)
      assert.equal(emails[0].senderEmail, 'office@example.com')
      assert.equal(emails[0].version, 'reviewed-version')
      assert.equal(emails[0].contactIds.length, 3)
      await page.getByRole('button', { name: 'Send SMS', exact: true }).click()
      await page.getByText('1 contact cannot be reached by SMS.', { exact: true }).waitFor()
      const message = page.locator('textarea').first()
      await message.fill('Hello families, here is the new schedule.')
      const send = page.getByRole('button', { name: 'Send message', exact: true })
      await send.waitFor()
      assert.ok(await page.getByRole('dialog').last().evaluate(node => node.scrollWidth <= node.clientWidth))
      await page.screenshot({ path: `/tmp/pulse-bulk-sms-${width}.png`, fullPage: true })
      await send.click()
      await page.waitForFunction(() => !document.querySelector('[role="dialog"]'))
      assert.equal(sms.length, 1); assert.equal(sms[0].recipientVersion, 'reviewed-version')
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: Contacts actions, automatic counts, unreachable notice, sender identities, draft restore, individual-send payload, SMS preview version, no overflow`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })