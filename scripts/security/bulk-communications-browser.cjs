/* eslint-disable @typescript-eslint/no-require-imports -- Optional isolated browser validation; mocked APIs only. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    for (const width of [1440, 900, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      page.setDefaultTimeout(15000)
      const errors = [], emails = [], sms = []
      page.on('pageerror', error => errors.push(error.message))
      page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()) })
      page.on('response', response => { if (response.status() >= 400) console.error('HTTP', response.status(), response.url()) })
      const people = ['Alex', 'Blair', 'Casey'].map((first_name, index) => ({ id: `00000000-0000-0000-0000-00000000010${index}`, first_name, last_name: 'Student', email: `${first_name.toLowerCase()}@example.com`, phone: '+12025550100', client_status: 'Active', is_minor: true, opted_out: false, account_holders: [], custom_fields: {} }))
      await page.route('**/api/**', route => {
        const request = route.request(), url = new URL(request.url())
        const fulfill = body => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) })
        if (url.pathname === '/api/contacts') return fulfill(people)
        if (url.pathname === '/api/tenant-fields' || url.pathname === '/api/staff' || url.pathname === '/api/conversations/templates') return fulfill(url.pathname.endsWith('templates') ? { templates: [] } : [])
        if (url.pathname === '/api/communications/recipients') return fulfill({ selectedCount: 3, recipients: [{ destination: 'parent1@example.com', name: 'Parent One', contactIds: [people[0].id, people[1].id] }, { destination: 'parent2@example.com', name: 'Parent Two', contactIds: [people[0].id, people[1].id] }], excluded: [{ id: people[2].id, name: 'Casey Student', reason: 'No account-holder details' }], version: 'reviewed-version' })
        if (url.pathname === '/api/communications/senders') return fulfill({ senders: width === 900 ? [{ id: 'office@example.com', email: 'office@example.com', name: 'Music Academy', mine: false }] : [{ id: 'teacher@example.com', email: 'teacher@example.com', name: 'Teacher', mine: true }, { id: 'office@example.com', email: 'office@example.com', name: 'Music Academy', mine: false }] })
        if (url.pathname === '/api/conversations/signature') return fulfill({ company: 'Music Academy', name: '', phone: '+12025550199', logoUrl: '' })
        if (url.pathname === '/api/communications/email') { emails.push(request.postDataJSON()); return fulfill({ sent: 2, failed: 0, uncertain: 0, pending: 0 }) }
        if (url.pathname === '/api/campaigns' && request.method() === 'POST') return fulfill({ id: 'synthetic-campaign' })
        if (url.pathname === '/api/campaigns/synthetic-campaign/send') { sms.push(request.postDataJSON()); return fulfill({ ok: true, sent: 2, failed: 0, missing_phone: 1 }) }
        if (url.pathname === '/api/contacts/check-sensitive') return fulfill({ flagged: [], opted_out: [] })
        if (url.pathname === '/api/media-suggestions') return fulfill({ approvedImages: [], suggestedGifs: [], detectedVibes: [], shouldAutoShowMedia: false, shouldShowThumbnails: false })
        return fulfill({})
      })
      await page.goto(process.env.BULK_REVIEW_URL || 'http://127.0.0.1:3111/bulk')
      await page.getByText('Viewing 3 contacts', { exact: true }).waitFor()
      const counter = page.getByText(/^(Viewing 3 contacts|3 out of 3 contacts selected)$/, { exact: true }).locator('..')
      const counterBefore = await counter.boundingBox()
      for (const name of ['Send new text message', 'Send new email']) {
        const action = page.getByRole('button', { name, exact: true })
        assert.ok(await action.isVisible(), `${name} is discoverable before selecting contacts`)
        assert.ok(await action.isDisabled())
        assert.ok(await action.evaluate(node => parseFloat(getComputedStyle(node).fontSize) <= 14), 'Toolbar labels stay compact')
      }
      await page.getByRole('checkbox', { name: 'Select all contacts', exact: true }).check()
      const counterAfter = await counter.boundingBox()
      assert.ok(Math.abs(counterBefore.height - counterAfter.height) <= 1, 'Selecting contacts does not change counter row height')
      assert.ok(Math.abs(counterBefore.y - counterAfter.y) <= 1, 'Selecting contacts does not shift counter row')
      const clearAction = page.getByRole('button', { name: 'Unselect all', exact: true }).filter({ visible: true }).first()
      assert.equal(await clearAction.getAttribute('data-kind'), 'link')
      assert.equal(await clearAction.evaluate(node => getComputedStyle(node).textDecorationLine), 'none')
      await clearAction.click()
      await page.getByText('Viewing 3 contacts', { exact: true }).waitFor()
      await page.getByRole('checkbox', { name: 'Select all contacts', exact: true }).check()
      await page.getByRole('button', { name: 'Send new email', exact: true }).click()
      await page.getByRole('dialog', { name: 'Sending emails to a group of contacts', exact: true }).waitFor()
      assert.equal(await page.getByRole('heading', { name: 'Sending emails to a group of contacts' }).evaluate(node => getComputedStyle(node).fontSize), '18px')
      assert.equal(await page.getByRole('dialog').getByRole('list').count(), 0)
      assert.equal(await page.getByRole('dialog').getByText('3 contacts selected', { exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Cancel', exact: true }).click()
      assert.equal(await page.getByRole('dialog').count(), 0)
      await page.getByRole('button', { name: 'Send new email', exact: true }).click()
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await page.getByText('2 recipients', { exact: true }).waitFor()
      await page.getByText('1 contact cannot be reached by email.', { exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Manage recipients' }).count(), 0)
      assert.equal(await page.getByRole('combobox', { name: 'Send email from' }).count(), 1)
      assert.ok(await page.getByRole('option', { name: 'Music Academy — office@example.com', exact: true }).count())
      if (width !== 900) {
        assert.ok(await page.getByRole('option', { name: 'Me — Teacher — teacher@example.com', exact: true }).count())
        await page.getByRole('combobox', { name: 'Send email from' }).selectOption('office@example.com')
      }
      await page.getByRole('textbox', { name: 'Email subject', exact: true }).fill('Updated lesson schedule')
      await page.getByRole('textbox', { name: 'Email body', exact: true }).fill('Hello families, here is the new schedule.')
      await page.getByRole('button', { name: 'Save as draft', exact: true }).click()
      await page.goto(process.env.BULK_REVIEW_URL || 'http://127.0.0.1:3111/bulk')
      await page.getByRole('checkbox', { name: 'Select all contacts', exact: true }).check()
      await page.getByRole('button', { name: 'Send new email', exact: true }).click()
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await page.getByRole('textbox', { name: 'Email subject', exact: true }).waitFor()
      assert.equal(await page.getByRole('textbox', { name: 'Email subject', exact: true }).inputValue(), 'Updated lesson schedule')
      const panel = page.getByRole('region', { name: 'Bulk message composer', exact: true })
      assert.ok(await panel.evaluate(node => node.scrollWidth <= node.clientWidth))
      assert.ok(page.url().includes('/dashboard/inbox/bulk?selection='))
      assert.equal(await page.getByRole('dialog').count(), 0)
      await page.getByRole('button', { name: 'See contacts', exact: true }).click()
      await page.getByRole('list', { name: 'Excluded contacts' }).waitFor()
      await page.getByText('Casey Student — No account-holder details', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Hide contacts', exact: true }).click()
      assert.equal(await page.locator('.slide-panel--drawer').count(), 0)
      await page.screenshot({ path: `/tmp/pulse-bulk-email-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Send 2 emails', exact: true }).click()
      await page.getByRole('textbox', { name: 'Email subject', exact: true }).waitFor({ state: 'hidden' })
      assert.equal(emails.length, 1)
      assert.equal(emails[0].senderEmail, 'office@example.com')
      assert.equal(emails[0].version, 'reviewed-version')
      assert.equal(emails[0].contactIds.length, 3)
      await page.goto(process.env.BULK_REVIEW_URL || 'http://127.0.0.1:3111/bulk')
      await page.getByRole('checkbox', { name: 'Select all contacts', exact: true }).check()
      await page.getByRole('button', { name: 'Send new text message', exact: true }).click()
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      const smsPanel = page.getByRole('region', { name: 'Bulk message composer', exact: true })
      await smsPanel.waitFor()
      await smsPanel.getByText('1 contact cannot be reached by SMS.', { exact: true }).waitFor()
      const message = smsPanel.locator('textarea').first()
      await message.fill('Hello families, here is the new schedule.')
      await page.reload()
      await message.waitFor()
      assert.equal(await message.inputValue(), 'Hello families, here is the new schedule.')
      const send = page.getByRole('button', { name: 'Send message', exact: true })
      await send.waitFor()
      assert.ok(await smsPanel.evaluate(node => node.scrollWidth <= node.clientWidth))
      assert.ok(page.url().includes('/dashboard/inbox/bulk?selection='))
      assert.equal(await page.getByRole('dialog').count(), 0)
      await page.getByRole('button', { name: 'See contacts', exact: true }).click()
      await page.getByRole('list', { name: 'Excluded contacts' }).waitFor()
      await page.screenshot({ path: `/tmp/pulse-bulk-sms-${width}.png`, fullPage: true })
      await send.click()
      await page.waitForURL('**/dashboard/inbox')
      assert.equal(sms.length, 1); assert.equal(sms[0].recipientVersion, 'reviewed-version')
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: Contacts actions, automatic counts, unreachable notice, sender identities, draft restore, individual-send payload, SMS preview version, no overflow`)
      await page.close()
    }
    const blocked = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const recipientError = 'Account-holder routing is not set up in the contacts database. Ask the account owner to apply Student Accounts Migration 001 before sending. No messages were sent.'
    const senderError = 'Organisation email settings unavailable. Apply Migration 026 in the CRM database.'
    await blocked.route('**/api/**', route => {
      const path = new URL(route.request().url()).pathname
      const response = (body, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) })
      if (path === '/api/contacts') return response(['Alex', 'Blair'].map((first_name, index) => ({ id: `00000000-0000-0000-0000-00000000010${index}`, first_name, last_name: 'Student', client_status: 'Active', custom_fields: {} })))
      if (path === '/api/communications/recipients') return response({ error: recipientError }, 409)
      if (path === '/api/communications/senders') return response({ error: senderError }, 409)
      return response([])
    })
    await blocked.goto(process.env.BULK_REVIEW_URL || 'http://127.0.0.1:3111/bulk')
    await blocked.getByRole('checkbox', { name: 'Select all contacts', exact: true }).check()
    await blocked.getByRole('button', { name: 'Send new email', exact: true }).click()
    await blocked.getByRole('button', { name: 'Continue', exact: true }).click()
    await blocked.getByText(recipientError, { exact: true }).waitFor()
    await blocked.getByText(senderError, { exact: true }).waitFor()
    assert.equal(await blocked.getByRole('button', { name: /^Send \d+ emails$/ }).count(), 0)
    console.log('PASS setup failure: routing and sender errors remain visible together; sending is blocked')
    await blocked.route('**/api/communications/recipients?**', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ selectedCount: 2, recipients: [{ destination: 'parent@example.com', name: 'Parent', contactIds: ['00000000-0000-0000-0000-000000000100'] }], excluded: [{ id: '00000000-0000-0000-0000-000000000101', name: 'Blair Student', reason: 'Opted out' }], version: 'reviewed-version' }) }))
    await blocked.reload()
    await blocked.getByText(senderError, { exact: true }).waitFor()
    const warning = blocked.getByRole('alert').filter({ hasText: 'Excluded from sending' })
    await warning.waitFor()
    const errorBounds = await blocked.getByText(senderError, { exact: true }).boundingBox()
    const warningBounds = await warning.boundingBox()
    assert.ok(warningBounds.y >= errorBounds.y + errorBounds.height, 'Warning follows blocking sender error')
    assert.ok(await blocked.getByRole('combobox', { name: 'Send email from' }).isDisabled())
    assert.ok(await blocked.getByRole('button', { name: 'Send 1 email', exact: true }).isDisabled())
    await blocked.getByRole('button', { name: 'See contacts', exact: true }).click()
    await blocked.getByText('Blair Student — Opted out', { exact: true }).waitFor()
    console.log('PASS sender setup: error then expandable warning; no placeholder sender; sending blocked')
    const requestCount = { recipients: 0 }
    await blocked.route('**/api/communications/recipients?**', route => { requestCount.recipients += 1; return route.abort() })
    await blocked.goto('http://127.0.0.1:3111/dashboard/inbox/bulk?selection=not-a-selection')
    await blocked.getByText('This contact selection is unavailable. Return to Contacts and select the recipients again.', { exact: true }).waitFor()
    assert.equal(requestCount.recipients, 0)
    console.log('PASS invalid selection: no recipient request or composer')
    await blocked.close()
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })