/* eslint-disable @typescript-eslint/no-require-imports -- Isolated sample workflow. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:3227'
assert.match(base, /^http:\/\/127\.0\.0\.1:/)

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1100 } })
      const errors = [], writes = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => { if (route.request().method() !== 'GET') writes.push(route.request().url()); return route.fulfill({ json: { roleKey: 'owner' } }) })
      await page.goto(`${base}/odeon-demo?view=quick&account=demo%3Afamily-9&section=enrollments`)
      const panel = page.getByRole('dialog', { name: 'Family workspace V3' })
      await panel.waitFor()
      assert.equal(await panel.getByRole('button', { name: /^Reschedule(?: together)?$/, exact: true }).count(), 0)
      await panel.getByRole('checkbox', { name: /Include Adam/ }).check()
      await panel.getByRole('checkbox', { name: /Include Sara/ }).check()
      const weekToolbar = panel.locator('[data-lesson-selection-toolbar]')
      await weekToolbar.waitFor()
      const actionBox = await weekToolbar.getByRole('button', { name: 'Reschedule together', exact: true }).boundingBox()
      const weekBox = await weekToolbar.getByRole('button', { name: 'Next week', exact: true }).boundingBox()
      const toolbarBox = await weekToolbar.boundingBox()
      assert.ok(Math.abs(actionBox.x + actionBox.width - toolbarBox.x - toolbarBox.width) <= 2, 'Reschedule together is right-aligned in the week toolbar')
      if (width > 1200) assert.ok(Math.abs(actionBox.y + actionBox.height / 2 - weekBox.y - weekBox.height / 2) <= 2, 'Action and week picker share the same vertical center')
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      await page.screenshot({ path: `/tmp/beta-reschedule-toolbar-${width}.png`, fullPage: true })
      await panel.getByRole('button', { name: 'Clear selection', exact: true }).click()
      assert.equal(await panel.getByRole('button', { name: /^Reschedule(?: together)?$/, exact: true }).count(), 0)
      await panel.getByRole('checkbox', { name: /Include Adam/ }).check()
      await panel.getByRole('checkbox', { name: /Include Sara/ }).check()
      await panel.getByRole('button', { name: 'Reschedule together', exact: true }).click()
      const planner = panel.getByRole('region', { name: 'Reschedule together', exact: true })
      await planner.waitFor()
      assert.equal(await planner.getByRole('button', { name: 'Back to schedule', exact: true }).count(), 1, 'Keep only the existing back arrow')
      assert.equal(await planner.getByText('Reschedule together · 2 selected', { exact: true }).count(), 0)
      const saraOriginal = planner.locator('[data-family-reference][data-calendar-date="2026-11-04"][data-calendar-time="15:00"]')
      await saraOriginal.waitFor()
      assert.equal(await saraOriginal.locator('span').first().innerText(), 'Sara')
      const referenceStyle = await saraOriginal.evaluate(element => {
        const style = getComputedStyle(element)
        const cell = element.parentElement
        return { overflow: style.overflow, row: cell.style.gridRow, color: style.color, fits: element.scrollHeight <= element.clientHeight + 1 }
      })
      assert.equal(referenceStyle.row, '5 / span 2', 'Sara remains in the 3pm block')
      assert.equal(referenceStyle.overflow, 'hidden')
      assert.equal(referenceStyle.fits, true)
      assert.notEqual(referenceStyle.color, 'rgb(88, 28, 135)', 'Existing lessons are not tentative purple')
      assert.equal(await planner.getByText('Only lessons with a new time will change.', { exact: true }).count(), 0)
      assert.equal(await planner.getByText('In focus', { exact: true }).count(), 0)
      const controls = planner.getByRole('complementary', { name: 'Booking controls' })
      const cards = controls.getByRole('group', { name: 'Lessons to reschedule' })
      await cards.waitFor()
      assert.equal(await planner.getByRole('button', { name: 'Confirm 0 changes', exact: true }).isDisabled(), true)
      const a = await controls.getByRole('button', { name: 'Plan Adam Guitar', exact: true }).boundingBox()
      const s = await controls.getByRole('button', { name: 'Plan Sara Voice & Vocals', exact: true }).boundingBox()
      const c = await controls.getByRole('button', { name: 'Confirm 0 changes', exact: true }).boundingBox()
      assert.ok(s.y > a.y && c.y > s.y, 'Lesson cards stack above confirmation')
      if (width > 700) {
        const grid = await planner.getByRole('region', { name: 'Available lesson times' }).boundingBox()
        assert.ok(a.x >= grid.x + grid.width, 'Cards occupy existing right column')
      }
      const calendar = planner.getByRole('region', { name: 'Available lesson times' })
      await page.screenshot({ path: `/tmp/beta-reschedule-originals-${width}.png`, fullPage: true })
      await planner.getByRole('button', { name: 'Next week', exact: true }).click()
      await calendar.getByRole('button', { name: /teacher.*available/ }).first().click()
      await planner.getByRole('button', { name: 'Confirm 1 change', exact: true }).waitFor()
      const original = await page.evaluate(() => JSON.parse(sessionStorage.getItem('odeon:app-sample:v2')).snapshot.data.lessons)
      assert.equal(original.find(item => item.id === 'demo:enrollment-10:calendar:2026-11-03').date, '2026-11-03', 'Draft not saved')
      await planner.getByRole('button', { name: 'Plan Sara Voice & Vocals', exact: true }).click()
      await planner.getByRole('button', { name: 'Next week', exact: true }).click()
      const adamProposal = planner.locator('[data-proposed-reference]')
      await adamProposal.waitFor()
      assert.equal(await adamProposal.locator('span').first().innerText(), 'Adam')
      assert.equal(await adamProposal.evaluate(element => getComputedStyle(element).overflow), 'hidden')
      assert.equal(await adamProposal.evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(219, 234, 254)')
      assert.equal(await planner.getByText('Unchanged', { exact: true }).count(), 1)
      await calendar.getByRole('button', { name: /teacher.*available/ }).first().click()
      await planner.getByRole('button', { name: 'Confirm 2 changes', exact: true }).waitFor()
      await page.screenshot({ path: `/tmp/beta-reschedule-proposals-${width}.png`, fullPage: true })
      await planner.getByRole('button', { name: 'Clear Sara change', exact: true }).click()
      await planner.getByRole('button', { name: 'Confirm 1 change', exact: true }).waitFor()
      await planner.getByRole('button', { name: 'Plan Adam Guitar', exact: true }).click()
      await calendar.locator('[data-selected-replacement]').waitFor()
      await page.screenshot({ path: `/tmp/beta-reschedule-together-${width}.png`, fullPage: true })
      const confirm = planner.getByRole('button', { name: 'Confirm 1 change', exact: true })
      await confirm.focus(); await page.keyboard.down('Space'); await page.waitForTimeout(1700); await page.keyboard.up('Space')
      await page.getByRole('dialog', { name: 'Confirmation', exact: true }).waitFor()
      const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('odeon:app-sample:v2')).snapshot.data.lessons)
      assert.equal(saved.find(item => item.id === 'demo:enrollment-10:calendar:2026-11-03').date, '2026-11-09')
      assert.deepEqual(saved.find(item => item.id === 'demo:enrollment-11:calendar:2026-11-04'), original.find(item => item.id === 'demo:enrollment-11:calendar:2026-11-04'))
      assert.deepEqual(errors, []); assert.deepEqual(writes, [])
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      console.log(`PASS ${width}: checkbox selection, clear, focus-compatible slots, two drafts, undo one, retained draft, confirm only one, sibling unchanged, no writes/errors/overflow`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })