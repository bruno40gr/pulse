/* eslint-disable @typescript-eslint/no-require-imports -- Fictional local browser rehearsal, all APIs intercepted. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.ENROLLMENT_HUB_REVIEW_URL || 'http://127.0.0.1:3197/enrollment'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Use an isolated local enrollment lab.')

;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 900, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage()
      page.setDefaultTimeout(15000)
      const errors = [], writes = []
      page.on('pageerror', error => errors.push(error.message))
      const lead = { id: 'won-one', status: 'won', intake_type: 'lesson_inquiry', updated_at: '2026-10-30T12:00:00Z', program_label: 'Private · Guitar', contact: { full_name: 'Jamie Example', email: 'jamie@example.invalid', phone: '' }, payload: { student_name: 'Riley Example', student_preferences: { preferred_days: ['Tuesday'], preferred_times: ['evening'] } } }
      let failLeads = false
      lead.payload.potential_value_base = 200
      await context.route('**/*', route => {
        const request = route.request(), url = new URL(request.url())
        if (url.origin !== new URL(base).origin) return route.abort()
        if (!url.pathname.startsWith('/api/')) return route.continue()
        if (request.method() !== 'GET') { writes.push(url.pathname); return route.abort() }
        assert.equal(url.pathname, '/api/leads')
        assert.equal(url.searchParams.get('intake_type'), 'enrolled')
        assert.equal(url.searchParams.get('include_activity'), '0')
        return route.fulfill({ status: failLeads ? 503 : 200, json: failLeads ? { error: 'Unavailable' } : [lead, { ...lead, id: 'service', intake_type: 'service_inquiry' }] })
      })
      await page.goto(base)
      const table = page.getByRole('table', { name: 'Enrollments', exact: true })
      await table.getByRole('button', { name: 'Riley Example', exact: true }).waitFor()
      assert.equal(await table.getByRole('group', { name: 'Enrollment progress: Not started', exact: true }).count(), 1)
      assert.equal(await table.getByText('From won lead', { exact: true }).count(), 0)
      await table.getByText('$200', { exact: true }).waitFor()
      const circle = table.locator('[aria-label="Step 2: Lessons"]').first()
      await circle.hover()
      await page.getByRole('tooltip', { name: 'Lessons', exact: true }).waitFor()
      await circle.focus()
      await circle.press('Escape')
      assert.equal(await page.getByRole('tooltip').count(), 0)
      await page.getByRole('button', { name: 'Start new enrollment', exact: true }).click()
      await page.getByRole('heading', { name: 'Contact details', exact: true }).waitFor()
      const first = page.getByLabel('First name', { exact: true })
      await first.fill('Taylor')
      await page.getByLabel('Last name', { exact: true }).fill('Draft')
      await page.getByLabel('Email', { exact: true }).fill('taylor@example.invalid')
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await page.getByRole('heading', { name: 'Set up lessons', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Save & close', exact: true }).click()
      await table.getByRole('button', { name: 'Taylor Draft', exact: true }).waitFor()
      await page.reload()
      await table.getByRole('button', { name: 'Taylor Draft', exact: true }).click()
      await page.getByRole('heading', { name: 'Set up lessons', exact: true }).waitFor()
      assert.match(await page.locator('[aria-current="step"]').innerText(), /2\s*Lessons/)
      const storedBeforeClose = await page.evaluate(() => JSON.stringify(localStorage))
      await page.getByRole('button', { name: 'Back', exact: true }).click()
      await page.getByRole('button', { name: 'Close', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
      assert.equal(await first.inputValue(), 'Taylor')
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      assert.equal(await page.evaluate(() => JSON.stringify(localStorage)), storedBeforeClose)

      await table.getByRole('button', { name: 'Taylor Draft', exact: true }).click()
      await page.getByRole('heading', { name: 'Set up lessons', exact: true }).waitFor()
      const length = page.locator('label').filter({ hasText: /^Length/ }).locator('select')
      await length.selectOption('60')
      await page.getByRole('button', { name: 'Save & close', exact: true }).waitFor()
      await length.selectOption('30')
      await page.getByRole('button', { name: 'Close', exact: true }).click()

      await table.getByRole('button', { name: 'Riley Example', exact: true }).click()
      await page.getByText('From the inquiry', { exact: true }).waitFor()
      assert.match(await page.getByText(/Riley Example: Private/).innerText(), /Tuesday.*evening/)
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      await page.reload()
      await table.getByRole('button', { name: 'Riley Example', exact: true }).waitFor()
      assert.equal(await table.getByRole('button', { name: 'Riley Example', exact: true }).count(), 1)
      await table.getByRole('button', { name: 'Resume enrollment for Riley Example', exact: true }).click()
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await page.getByRole('heading', { name: 'Set up lessons', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await page.getByRole('button', { name: 'Tuesday, Nov 3 4:00 pm, 1 teacher available', exact: true }).click()
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await page.getByRole('checkbox', { name: 'I accept the terms and conditions.', exact: true }).check()
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      const breakdown = page.locator('summary').filter({ hasText: 'Lesson breakdown' }).first()
      await breakdown.waitFor()
      assert.equal(await breakdown.evaluate(element => getComputedStyle(element).fontSize), '14px')
      assert.equal(await breakdown.locator('svg.lucide-chevron-right').count(), 1)
      await breakdown.click()
      await page.getByRole('checkbox', { name: 'Add payment later', exact: true }).check()
      for (const copy of ['Payment will be added later.', 'Monthly billing on the 1st, based on scheduled lessons.', 'No scheduled charges.']) assert.equal(await page.getByText(copy, { exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Save draft', exact: true }).click()
      await table.getByRole('group', { name: 'Enrollment progress: Ready for review', exact: true }).waitFor()
      await page.reload()
      await table.getByRole('group', { name: 'Enrollment progress: Ready for review', exact: true }).waitFor()
      // Simulate a stored proposal whose selected teacher no longer exists.
      await page.evaluate(() => {
        const key = Object.keys(localStorage).find(key => key.startsWith('odeon:enrollment-drafts:'))
        const envelope = JSON.parse(localStorage.getItem(key))
        envelope.records.find(record => record.sourceLeadId === 'won-one').draft.lessons[0].teacher = 'Unavailable teacher'
        localStorage.setItem(key, JSON.stringify(envelope))
      })
      await page.reload()
      await table.getByRole('button', { name: 'Riley Example', exact: true }).click()
      await page.getByRole('heading', { name: 'Choose times', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      await page.getByRole('searchbox', { name: 'Search enrollments', exact: true }).fill('guitar')
      assert.equal(await table.getByRole('button', { name: 'Taylor Draft', exact: true }).count(), 0)
      await page.getByRole('searchbox', { name: 'Search enrollments', exact: true }).fill('')
      await page.screenshot({ path: `/tmp/odeon-enrollment-hub-${width}.png`, fullPage: true })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)

      // Failure must not erase browser drafts or imply the queue is complete.
      failLeads = true
      await page.reload()
      await page.getByText(/Won leads could not be loaded/).waitFor()
      await table.getByRole('button', { name: 'Taylor Draft', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Start new enrollment', exact: true }).click()
      await page.getByLabel('First name', { exact: true }).fill('Incomplete')
      // A concurrent tab edit fails safely, keeping the open wizard intact.
      const original = await page.evaluate(() => {
        const key = Object.keys(localStorage).find(key => key.startsWith('odeon:enrollment-drafts:'))
        const raw = localStorage.getItem(key)
        localStorage.setItem(key, `${raw} `)
        return { key, raw }
      })
      await page.getByRole('button', { name: 'Save & close', exact: true }).click()
      await page.getByText(/Drafts changed in another tab/).waitFor()
      await page.evaluate(({ key, raw }) => localStorage.setItem(key, raw), original)
      await page.getByRole('button', { name: 'Save & close', exact: true }).click()
      await table.getByRole('button', { name: 'Incomplete', exact: true }).waitFor()
      assert.deepEqual(errors, [])
      assert.deepEqual(writes, [])
      console.log(`PASS ${width}px: shared hub, won-lead queue, prefill, reload/resume, finish review, invalidated selection, incomplete draft, deduplication, search, source failure, stale-tab protection and no live writes`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })