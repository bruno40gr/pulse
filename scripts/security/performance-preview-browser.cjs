/* eslint-disable @typescript-eslint/no-require-imports -- Isolated sample-workspace browser test. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const url = new URL('/odeon-demo?screen=events', process.env.BASE_URL || 'http://127.0.0.1:3248')
assert.equal(url.hostname, '127.0.0.1')

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 900 }, screen: { width, height: 900 } })
      page.setDefaultTimeout(12000)
      const requests = [], errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => { requests.push(route.request().url()); return route.abort() })
      await page.goto(url.href)
      await page.getByRole('button', { name: 'Preview performance workflow' }).click()
      const workflow = page.getByRole('region', { name: 'Performance workflow' })
      await page.getByRole('button', { name: 'Event details', exact: true }).click()
      await page.getByRole('button', { name: 'Details & image', exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Performance', exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Back', exact: true }).click()
      const events = page.getByRole('table', { name: 'Events', exact: true })
      await events.getByRole('columnheader', { name: 'Type', exact: true }).waitFor()
      await events.getByRole('button', { name: 'Manage performance: Student Showcase (sample)', exact: true }).click()
      const candidates = workflow.getByRole('checkbox')
      await candidates.first().waitFor()
      await workflow.getByRole('searchbox', { name: 'Search students' }).fill('drum players')
      await workflow.getByRole('button', { name: 'Search', exact: true }).click()
      await candidates.first().waitFor()
      const matches = await candidates.evaluateAll(nodes => nodes.map(input => input.closest('label').textContent))
      assert.ok(matches.every(label => /\bdrums?\b/i.test(label)))
      await workflow.getByRole('button', { name: `Select all matching (${matches.length})`, exact: true }).click()
      await workflow.getByRole('button', { name: `Draft invitation (${matches.length})`, exact: true }).waitFor()
      await workflow.getByRole('button', { name: `Deselect matching (${matches.length})`, exact: true }).click()
      await workflow.getByRole('button', { name: 'Clear search', exact: true }).click()
      const names = await candidates.evaluateAll(nodes => nodes.slice(0, 2).map(input => input.closest('label').querySelector('span').firstChild.textContent.trim()))
      assert.equal(names.length, 2)
      await candidates.nth(0).check()
      await candidates.nth(1).check()
      await workflow.getByRole('button', { name: 'Draft invitation (2)', exact: true }).click()
      let dialog = page.getByRole('dialog', { name: 'Performance email' })
      await dialog.getByRole('button', { name: 'Preview email' }).click()
      await dialog.getByRole('button', { name: 'Yes, I’m interested in participating' }).waitFor()
      await dialog.getByRole('button', { name: 'Simulate send' }).click()
      for (const name of names) {
        await workflow.getByRole('button', { name: `Preview response for ${name}`, exact: true }).click()
        dialog = page.getByRole('dialog', { name: 'Family response preview' })
        await dialog.getByRole('button', { name: 'Yes, I’m interested in participating' }).click()
        assert.equal(await workflow.getByRole('button', { name: 'Confirm performer', exact: true }).count(), 0)
        await dialog.getByRole('button', { name: 'Submit response' }).click()
        await workflow.getByRole('button', { name: 'Confirm performer', exact: true }).click()
      }
      await workflow.getByRole('button', { name: `Move ${names[1]} up`, exact: true }).click()
      const order = workflow.getByRole('region', { name: /^Running order:/ })
      assert.match(await order.first().innerText(), new RegExp(`^1\\. ${names[1].replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`))
      await order.first().getByLabel('Piece title').fill('Opening piece')
      await order.first().getByLabel('Estimated minutes').fill('3')
      await workflow.getByLabel('Follow-up audience').selectOption('Confirmed')
      await workflow.getByRole('button', { name: 'Draft follow-up (2)' }).click()
      await page.getByRole('dialog', { name: 'Performance email' }).getByRole('button', { name: 'Simulate send' }).click()
      await workflow.getByText('An update about Student Showcase (sample)', { exact: true }).waitFor()
      await page.reload()
      await page.getByRole('button', { name: 'Preview performance workflow' }).click()
      assert.equal(await order.first().getByLabel('Piece title').inputValue(), 'Opening piece')
      assert.deepEqual(requests, [])
      assert.deepEqual(errors, [])
      console.log(`Performance preview passed at ${width}px — no API calls`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })