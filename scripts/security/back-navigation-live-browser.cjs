/* eslint-disable @typescript-eslint/no-require-imports -- Isolated fixture app; no provider calls. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 900 } })
      const writes = []; const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => { writes.push(route.request().url()); return route.fulfill({ json: {} }) })
      const button = (name, root = page) => root.getByRole('button', { name, exact: true })
      async function checkBack(control, title) {
        await control.hover()
        await page.getByRole('tooltip', { name: await control.getAttribute('aria-label'), exact: true }).waitFor()
        await page.mouse.move(0, 0)
        await control.focus()
        const tooltip = page.getByRole('tooltip', { name: await control.getAttribute('aria-label'), exact: true })
        await tooltip.waitFor()
        const bounds = await control.boundingBox(); const heading = await title.boundingBox()
        assert.equal(bounds.width, 44); assert.equal(bounds.height, 44)
        assert.ok(bounds.y < heading.y + heading.height && bounds.y + bounds.height > heading.y)
        assert.equal(await control.innerText(), '')
        assert.equal(await control.locator('svg').getAttribute('width'), '22')
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      }
      await page.goto(process.env.BACK_NAVIGATION_FLOW_URL || 'http://127.0.0.1:3102/back-regression')
      await button('New message').click()
      const modal = page.getByRole('dialog', { name: 'New message', exact: true })
      await button('SMS', modal).click()
      await modal.getByRole('textbox', { name: 'Search SMS recipients' }).fill('Alex')
      await button('Add Alex Chen to SMS recipients', modal).click()
      await checkBack(button('Back to message type', modal), modal.getByRole('heading', { name: 'SMS recipients', exact: true }))
      await button('Back to message type', modal).press('Enter')
      await button('SMS', modal).click()
      await button('Remove Alex Chen from SMS recipients', modal).waitFor()
      await modal.getByRole('textbox', { name: 'Search SMS recipients' }).fill('Morgan')
      await button('Add Morgan Rivera to SMS recipients', modal).click()
      await button('Write SMS (2)', modal).click()
      const sms = page.getByRole('textbox', { name: 'SMS message', exact: true })
      await sms.fill('Keep this unsent SMS')
      await checkBack(button('Back to Communications'), page.getByRole('heading', { name: 'Write a text message', exact: true }))
      await button('Back to Communications').click()
      const discard = page.getByRole('dialog', { name: 'Discard message and go back', exact: true })
      await button('Cancel', discard).click()
      assert.equal(await sms.inputValue(), 'Keep this unsent SMS')
      await button('Back to Communications').click()
      await button('Continue', discard).click()
      await button('Open conversation with Alex Chen').click()
      await button('Email').click()
      await button('Read email: Piano lessons for Jamie').click()
      if (width < 1000) {
        await checkBack(button('Back to emails'), page.getByRole('heading', { name: 'Email conversation', exact: true }))
        await button('Back to emails').click()
        await button('Read email: Piano lessons for Jamie').click()
      }
      await button('Reply').click()
      const editor = page.getByRole('textbox', { name: 'Email body', exact: true })
      await editor.fill('Keep this unsent email')
      await button('Back to Communications').click()
      await button('Open conversation with Alex Chen').click()
      await button('Email').click()
      await button('Read email: Piano lessons for Jamie').click()
      await button('Continue draft').click()
      assert.equal(await editor.innerText(), 'Keep this unsent email')
      assert.deepEqual(writes, []); assert.deepEqual(errors, [])
      await page.screenshot({ path: `/tmp/pulse-back-navigation-live-${width}.png`, fullPage: true })
      console.log(`PASS ${width}: title chevrons, hover/focus tooltip, 44px targets, keyboard Back, recipient retention, SMS discard confirmation, email draft retention, no API calls or sends`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })