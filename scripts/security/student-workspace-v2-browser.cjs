/* eslint-disable @typescript-eslint/no-require-imports -- Local prototype regression journey. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')

;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 1366, 900, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 768 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], apis = []
      page.setDefaultTimeout(10000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.hostname === 'res.cloudinary.com' && route.request().resourceType() === 'image') return route.continue()
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) {
          const shell = ['/api/account/identity', '/api/account/claim-reminder', '/api/notifications', '/api/leads', '/api/inbox', '/api/inbox/reconcile', '/api/tenant/sync-status']
          if (!shell.includes(url.pathname)) { apis.push(url.pathname); return route.abort() }
          return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        }
        return route.continue()
      })
      await page.goto(`${base}?prototype=v2`)
      const search = page.getByRole('searchbox', { name: 'Search contacts' })
      await search.fill('Kim')
      const selection = page.getByRole('checkbox', { name: 'Select Sam Kim', exact: true })
      await selection.check()
      // Mark the DOM node to prove the table is never unmounted while working.
      await search.evaluate(el => { el.dataset.retained = 'yes' })
      await page.getByRole('button', { name: 'Open Sophie Kim family', exact: true }).click()
      let panel = page.getByRole('dialog', { name: 'Account quick reference' })
      await panel.waitFor()
      const avatarInset = await panel.locator('[data-profile-avatar]').first().evaluate(element => element.getBoundingClientRect().x - element.closest('[role="dialog"]').getBoundingClientRect().x)
      assert.equal(avatarInset, width <= 960 ? 16 : 24, 'Profile starts at the header gutter without an empty Back slot')
      for (const name of ['Call', 'Send SMS', 'Send email']) {
        const action = panel.getByRole('button', { name, exact: true })
        await action.waitFor()
        assert.equal(await action.isDisabled(), name === 'Call', 'Messaging opens a local conversation preview')
      }
      const tabs = panel.getByRole('navigation', { name: 'Account sections' })
      assert.deepEqual(await tabs.getByRole('button').allTextContents(), ['Account', 'Upcoming lessons', 'Notes'])
      await panel.getByRole('heading', { name: 'Contact details', exact: true }).waitFor()
      await panel.getByRole('heading', { name: 'Billing', exact: true }).waitFor()
      await panel.getByRole('heading', { name: 'Makeup credits', exact: true }).waitFor()
      await panel.getByText('2 available', { exact: true }).waitFor()
      const contactCard = await panel.getByRole('heading', { name: 'Contact details', exact: true }).boundingBox()
      const subscriptionCard = await panel.getByRole('heading', { name: 'Piano • 30 min', exact: true }).boundingBox()
      if (width >= 1366) assert.ok(subscriptionCard.x > contactCard.x + 100 && Math.abs(subscriptionCard.y - contactCard.y) < 3, 'Wide Account uses aligned columns')
      if (width === 390) assert.ok(subscriptionCard.y > contactCard.y, 'Narrow Account stacks')
      await panel.getByRole('heading', { name: 'Makeup credits', exact: true }).scrollIntoViewIfNeeded()
      await page.screenshot({ path: `/tmp/odeon-v2-account-summaries-${width}.png`, fullPage: true })
      await panel.getByRole('heading', { name: 'Contact details', exact: true }).scrollIntoViewIfNeeded()
      await page.screenshot({ path: `/tmp/odeon-v2-account-${width}.png`, fullPage: true })
      await tabs.getByRole('button', { name: 'Upcoming lessons', exact: true }).click()
      await panel.getByRole('region', { name: 'Upcoming bookings' }).waitFor()
      assert.equal(await panel.getByRole('button', { name: 'Calendar', exact: true }).count(), 0)
      for (let week = 0; week < 4; week++) await panel.getByRole('button', { name: 'Next lesson week', exact: true }).click()
      await panel.getByRole('button', { name: 'Sophie Piano lesson 2026-12-01 actions', exact: true }).click()
      await panel.getByRole('menuitem', { name: 'Cancel lesson', exact: true }).click()
      assert.equal(await page.getByRole('dialog', { name: 'Family workspace V2' }).count(), 0, 'Cancellation stays in the profile panel')
      await tabs.waitFor()
      await panel.getByRole('heading', { name: 'Cancel lesson', exact: true }).waitFor()
      await panel.getByRole('button', { name: 'Cancel lesson', exact: true }).click()
      await panel.getByRole('heading', { name: 'Lesson cancelled', exact: true }).waitFor()
      await panel.getByRole('button', { name: 'Back to lessons', exact: true }).click()
      await panel.getByRole('region', { name: 'Upcoming bookings' }).waitFor()
      await tabs.getByRole('button', { name: 'Notes', exact: true }).click()
      await panel.getByRole('group', { name: 'Note audience' }).waitFor()
      await panel.getByRole('button', { name: 'Send SMS', exact: true }).click()
      const smsRecipients = panel.getByRole('region', { name: 'Messaging Sam Kim', exact: true })
      await smsRecipients.getByText('Messaging Sam Kim', { exact: true }).waitFor()
      await smsRecipients.getByText('(202) 555-0142', { exact: true }).waitFor()
      assert.equal(await panel.getByText('1 recipient', { exact: true }).count(), 0)
      await panel.getByRole('region', { name: 'SMS history', exact: true }).waitFor()
      assert.equal(await panel.getByRole('navigation', { name: 'Account sections' }).count(), 0)
      await panel.getByRole('textbox', { name: 'SMS message', exact: true }).fill('V2 direct action draft')
      assert.equal(await panel.getByRole('button', { name: 'Send', exact: true }).isDisabled(), true)
      await page.screenshot({ path: `/tmp/odeon-direct-sms-v2-${width}.png`, fullPage: true })
      await panel.getByRole('button', { name: 'Back to profile', exact: true }).click()
      await panel.getByRole('group', { name: 'Note audience' }).waitFor()
      await panel.getByRole('button', { name: 'Send email', exact: true }).click()
      const emailRecipients = panel.getByRole('region', { name: 'Messaging Sam Kim', exact: true })
      await emailRecipients.getByText('Messaging Sam Kim', { exact: true }).waitFor()
      await emailRecipients.getByText('sam.kim@example.invalid', { exact: true }).waitFor()
      assert.equal(await panel.getByText('1 recipient', { exact: true }).count(), 0)
      await panel.getByRole('button', { name: 'New email', exact: true }).waitFor()
      assert.equal(await panel.getByRole('group', { name: 'Message channel' }).count(), 0)
      assert.equal(await panel.getByRole('navigation', { name: 'Account sections' }).count(), 0)
      await panel.getByRole('button', { name: 'Back to profile', exact: true }).click()
      await panel.getByRole('group', { name: 'Note audience' }).waitFor()

      await tabs.getByRole('button', { name: 'Account', exact: true }).click()
      await panel.getByText('3 available', { exact: true }).waitFor()
      const workspace = page.getByRole('dialog', { name: 'Family workspace V2' })
      await panel.getByRole('button', { name: 'Book makeup', exact: true }).click()
      await workspace.getByRole('button', { name: /^Schedule Sophie makeup/ }).first().click()
      await workspace.getByRole('heading', { level: 1, name: 'Schedule makeup', exact: true }).waitFor()
      await workspace.getByRole('button', { name: 'Back to Sophie Kim', exact: true }).click()
      await workspace.getByRole('region', { name: 'Makeup classes', exact: true }).waitFor()
      await workspace.getByRole('button', { name: 'Back to profile', exact: true }).click()
      assert.equal(await panel.getByRole('button', { name: 'View communication history', exact: true }).count(), 0)
      assert.equal(await panel.getByRole('heading', { name: 'Account managers', exact: true }).count(), 0)
      await panel.getByText('Sam Kim', { exact: true }).first().waitFor()
      await panel.getByRole('button', { name: 'View Account Details', exact: true }).click()
      await workspace.getByRole('heading', { name: 'Contact details', exact: true }).waitFor()
      await workspace.getByRole('button', { name: 'Back to profile', exact: true }).click()
      await panel.getByRole('button', { name: 'View billing', exact: true }).click()
      await workspace.getByRole('heading', { name: 'Invoices', exact: true }).waitFor()
      await workspace.getByRole('button', { name: 'Pay $200', exact: true }).first().click()
      const payment = page.getByRole('dialog', { name: 'Pay', exact: true })
      await payment.getByRole('button', { name: 'Pay' }).click()
      await workspace.getByRole('region', { name: 'Invoices', exact: true }).waitFor()
      await workspace.getByRole('button', { name: 'Back to profile', exact: true }).click()
      await panel.getByRole('button', { name: 'View billing', exact: true }).waitFor()
      await panel.getByRole('button', { name: 'Sophie Piano subscription actions', exact: true }).click()
      await panel.getByRole('menuitem', { name: 'Manage subscription', exact: true }).click()
      await workspace.getByRole('heading', { name: 'Manage subscription', exact: true }).waitFor()
      await workspace.getByRole('combobox', { name: 'Level', exact: true }).selectOption('3')
      await workspace.getByRole('button', { name: 'Save subscription', exact: true }).click()
      await panel.getByText('Level 3', { exact: true }).waitFor()
      await panel.getByRole('button', { name: 'Close', exact: true }).click()
      await search.waitFor()
      assert.equal(await search.inputValue(), 'Kim')
      assert.equal(await search.getAttribute('data-retained'), 'yes')
      assert.equal(await selection.isChecked(), true)
      assert.deepEqual(errors, []); assert.deepEqual(apis, [])
      console.log(`PASS V2 three-tab panel, account summaries, V1 upcoming, notes, billing/comms/makeup/subscription workspace, cancellation and retained table ${width}px`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })