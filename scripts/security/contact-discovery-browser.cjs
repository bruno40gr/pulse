/* eslint-disable @typescript-eslint/no-require-imports -- Intercepted browser fixtures only. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const review = require('./fixtures/contact-list-review.cjs')
const rows = review.map(row => ({ ...row, last_attended: new Date().toISOString() }))
  .concat(Array.from({ length: 70 }, (_, i) => ({ ...review[6], id: `extra-${i}`, first_name: `Extra ${i}`, last_name: 'Student', account_id: null, client_status: i === 69 ? 'Lost' : 'Member' })))
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 900, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 950 } })
      const requests = [], errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => {
        const path = new URL(route.request().url()).pathname
        requests.push(path)
        if (path === '/api/inbox/reconcile') return route.fulfill({ json: { skipped: true } })
        if (route.request().method() !== 'GET') throw new Error(`Unexpected write ${path}`)
        return route.fulfill({ json: path === '/api/contacts' ? rows : path === '/api/tenant-fields' ? [{ field_key: 'program', field_label: 'Program', field_options: ['Piano'] }, { field_key: 'plan_name', field_label: 'Plan', field_options: ['Monthly'] }, { field_key: 'band_name', field_label: 'Band', field_options: ['Band A'] }] : {} })
      })
      await page.goto('http://127.0.0.1:3218/dashboard/contacts')
      const table = page.getByRole('table', { name: 'Contacts', exact: true })
      await table.getByRole('button', { name: 'Ethan Kim', exact: true }).waitFor()
      const count = page.locator('p[role="status"]')
      const initialCount = await count.innerText()
      assert.equal(initialCount, '75 contacts')
      const view = page.getByRole('group', { name: 'Contact view', exact: true })
      assert.equal(await view.getByRole('button', { name: 'View families', exact: true }).getAttribute('aria-pressed'), 'true')
      assert.equal(await view.getByRole('switch').count(), 0)
      assert.equal(await page.getByRole('combobox', { name: 'families per page', exact: true }).inputValue(), '50')
      await page.getByRole('combobox', { name: 'families per page', exact: true }).selectOption('25')
      await page.getByRole('navigation', { name: 'Contacts pagination' }).getByRole('button', { name: 'Next', exact: true }).click()
      await page.getByText('Page 2 of 3', { exact: true }).waitFor()
      await page.getByRole('combobox', { name: 'families per page', exact: true }).selectOption('250')
      await page.getByText('Page 1 of 1', { exact: true }).waitFor()
      await view.getByRole('button', { name: 'View students', exact: true }).click()
      assert.equal(await page.getByRole('combobox', { name: 'contacts per page', exact: true }).inputValue(), '250')
      await view.getByRole('button', { name: 'View families', exact: true }).click()
      await page.getByRole('button', { name: 'Filters', exact: true }).click()
      let drawer = page.getByRole('dialog')
      assert.equal(await drawer.getByRole('checkbox', { name: 'Show only active students & families', exact: true }).isChecked(), true)
      assert.equal(await page.getByLabel('1 filters applied', { exact: true }).count(), 1)
      assert.ok(await drawer.getByLabel('Status', { exact: true }).evaluate(el => el.getBoundingClientRect().height <= 36))
      const before = requests.length
      await drawer.getByLabel('Name', { exact: true }).fill('Kim')
      await drawer.getByLabel('Email', { exact: true }).fill('sam@')
      await drawer.getByLabel('Last active', { exact: true }).selectOption('7')
      assert.equal(await count.innerText(), initialCount)
      assert.equal(requests.length, before, 'Draft edits do not query')
      await drawer.getByRole('button', { name: 'Close', exact: true }).click()
      await page.getByRole('button', { name: 'Filters', exact: true }).click()
      drawer = page.getByRole('dialog')
      assert.equal(await drawer.getByLabel('Name', { exact: true }).inputValue(), '')
      await drawer.getByLabel('Name', { exact: true }).fill('Kim')
      await drawer.getByLabel('Email', { exact: true }).fill('sam@')
      await drawer.getByLabel('Last active', { exact: true }).selectOption('7')
      await drawer.locator('summary').click()
      assert.equal(await drawer.getByLabel('Email availability', { exact: true }).count(), 0)
      assert.equal(await drawer.getByLabel('Phone availability', { exact: true }).count(), 0)
      assert.equal(await drawer.getByLabel('Plan', { exact: true }).count(), 0)
      assert.equal(await drawer.getByLabel('Band', { exact: true }).count(), 0)
      await drawer.getByRole('button', { name: 'Submit search', exact: true }).click()
      await page.getByText('2 contacts', { exact: true }).waitFor()
      assert.equal(await page.getByLabel('4 filters applied', { exact: true }).count(), 1)
      assert.equal(await table.getByRole('checkbox', { name: 'Select Ethan Kim', exact: true }).count(), 0)
      await table.getByRole('checkbox', { name: 'Select Sam Kim', exact: true }).check()
      await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
      await page.getByRole('button', { name: 'Filters', exact: true }).click()
      drawer = page.getByRole('dialog')
      assert.equal(await drawer.getByLabel('Name', { exact: true }).inputValue(), 'Kim')
      await drawer.getByRole('button', { name: 'Clear filters', exact: true }).click()
      assert.equal(await count.innerText(), '2 contacts')
      await drawer.getByRole('button', { name: 'Submit search', exact: true }).click()
      await page.getByText('82 contacts', { exact: true }).waitFor()
      assert.equal(await page.getByLabel('1 filters applied', { exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Filters', exact: true }).click()
      drawer = page.getByRole('dialog')
      await drawer.getByRole('checkbox', { name: 'Show only active students & families', exact: true }).check()
      await drawer.getByRole('button', { name: 'Submit search', exact: true }).click()
      await page.getByText('75 contacts', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Filters', exact: true }).click()
      drawer = page.getByRole('dialog')
      await drawer.getByRole('checkbox', { name: 'Show only active students & families', exact: true }).uncheck()
      assert.equal(await count.innerText(), '75 contacts')
      await drawer.getByRole('button', { name: 'Submit search', exact: true }).click()
      await page.getByText('82 contacts', { exact: true }).waitFor()
      await table.getByRole('button', { name: 'Extra 69 Student', exact: true }).waitFor()

      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      assert.deepEqual(errors, [])
      await page.screenshot({ path: `/private/tmp/contact-discovery-${width}.png`, fullPage: true })
      console.log(`PASS ${width}px: active-student default, aggregate submit-only filters, draft discard, segmented views, page size, holder-only family selection`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })