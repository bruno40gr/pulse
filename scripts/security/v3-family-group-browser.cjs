/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional prototype regression tests. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, hasTouch: true, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], apis = []
      page.setDefaultTimeout(15000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) {
          const shell = ['/api/account/identity', '/api/account/claim-reminder', '/api/notifications', '/api/leads', '/api/inbox', '/api/inbox/reconcile', '/api/tenant/sync-status']
          if (!shell.includes(url.pathname)) { apis.push(url.pathname); return route.abort() }
          return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        }
        return route.continue()
      })
      await page.goto(`${base}?prototype=v3&view=quick&account=preview:kim&section=profile`)
      const portal = page.getByRole('dialog', { name: 'Family workspace V3', exact: true })
      const dependents = portal
      await portal.getByRole('button', { name: 'Edit Contact', exact: true }).waitFor()
      assert.equal(await portal.getByRole('heading', { name: 'Family Group', exact: true }).count(), 0)
      assert.equal(await portal.getByRole('button', { name: 'Edit contact', exact: true }).count(), 0)
      assert.equal(await portal.getByRole('button', { name: /Add Dependent/ }).count(), 0)
      const metadata = portal.getByLabel('Contact details metadata', { exact: true })
      for (const label of ['Dependents', 'Member since', 'Birthday']) await metadata.locator('[data-field-label]').filter({ hasText: new RegExp(`^${label}$`) }).waitFor()
      assert.equal(await metadata.getByText('Not added', { exact: true }).count(), 2)
      const widths = await metadata.locator(':scope > *').evaluateAll(items => items.map(el => el.getBoundingClientRect().width))
      assert.ok(Math.max(...widths) - Math.min(...widths) < 1)
      await portal.getByRole('button', { name: 'Send email', exact: true }).getByText('sam.kim@example.invalid', { exact: true }).waitFor()
      assert.equal(await portal.getByRole('button', { name: 'View billing', exact: true }).evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(220, 38, 38)')
      const sophieSubscriptions = portal.getByRole('region', { name: 'Sophie Kim subscriptions', exact: true })
      const programTitle = sophieSubscriptions.getByRole('heading', { name: 'Piano • 30 min', exact: true })
      const levelTitle = sophieSubscriptions.getByRole('heading', { name: 'Level 1', exact: true })
      const titleBox = await programTitle.boundingBox(), levelBox = await levelTitle.boundingBox()
      assert.ok(levelBox.y - titleBox.y - titleBox.height < 16, 'No extra card header/content gutter before Level')
      assert.equal(await portal.getByRole('button', { name: 'Edit Contact', exact: true }).locator('svg').count(), 1)

      assert.deepEqual(await levelTitle.evaluate(el => ({ size: getComputedStyle(el).fontSize, weight: getComputedStyle(el).fontWeight })), await programTitle.evaluate(el => ({ size: getComputedStyle(el).fontSize, weight: getComputedStyle(el).fontWeight })), 'Level has equal type emphasis to program')
      assert.equal(await sophieSubscriptions.getByLabel('Visa card', { exact: true }).count(), 2)
      assert.equal(await sophieSubscriptions.getByText('Paid by Sam with ***4242', { exact: true }).count(), 2)
      await page.screenshot({ path: `/tmp/odeon-v3-global-account-${width}.png`, fullPage: true })
      await portal.getByRole('button', { name: 'Edit Contact', exact: true }).click()
      const holderFields = portal.getByRole('region', { name: 'Sam Kim contact fields', exact: true })
      const sophieFields = portal.getByRole('region', { name: 'Sophie Kim contact fields', exact: true })
      await holderFields.getByRole('textbox', { name: 'Email', exact: true }).fill('cancelled@example.invalid')
      await portal.getByRole('button', { name: 'Cancel', exact: true }).click()
      await portal.getByRole('button', { name: 'Send email', exact: true }).getByText('sam.kim@example.invalid', { exact: true }).waitFor()
      await portal.getByRole('button', { name: 'Edit Contact', exact: true }).click()
      await holderFields.getByRole('textbox', { name: 'Email', exact: true }).fill('sam.updated@example.invalid')
      await holderFields.getByLabel('Birthday', { exact: true }).fill('1980-01-01')
      await sophieFields.getByRole('textbox', { name: 'Email', exact: true }).fill('sophie.updated@example.invalid')
      await portal.getByRole('button', { name: 'Save changes', exact: true }).click()
      await portal.getByRole('button', { name: 'Send email', exact: true }).getByText('sam.updated@example.invalid', { exact: true }).waitFor()
      await portal.getByText('sophie.updated@example.invalid', { exact: true }).waitFor()
      assert.equal(await portal.getByRole('button', { name: 'Edit contact', exact: true }).count(), 0)
      await portal.getByRole('button', { name: 'Edit Contact', exact: true }).click()
      await page.screenshot({ path: `/tmp/odeon-v3-global-editor-${width}.png`, fullPage: true })
      const members = dependents.locator('[aria-label="Family group members"]')
      await members.getByText('Sophie Kim', { exact: true }).waitFor()
      await members.getByText('Ethan Kim', { exact: true }).waitFor()
      assert.equal(await members.getByText(/^\d+ lessons$/).count(), 0)
      const relationship = members.getByRole('combobox', { name: 'Sophie Kim relationship', exact: true })
      await relationship.selectOption('Sibling')
      assert.equal(await relationship.inputValue(), 'Sibling')
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('button', { name: 'Add Dependent', exact: true }).click()
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('textbox', { name: 'First name', exact: true }).waitFor()
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click()
      assert.equal(await relationship.inputValue(), 'Sibling', 'Relationship survives task navigation')
      await page.screenshot({ path: `/tmp/odeon-v3-family-management-${width}.png`, fullPage: true })
      assert.equal(await dependents.getByText(/Saved cards stay|Future payer|Unpaid shared/).count(), 0)
      await members.getByRole('button', { name: 'Remove from Family Group', exact: true }).first().click()
      const confirmation = page.getByRole('dialog', { name: 'Remove from Family Group', exact: true })
      await confirmation.getByText('Unlink Sophie Kim from Sam Kim’s account? Sophie will remain a standalone student record, with their subscriptions, outstanding balance, and history.', { exact: true }).waitFor()
      await confirmation.getByRole('button', { name: 'Cancel', exact: true }).hover()
      assert.equal(await confirmation.evaluate(el => { const r = el.getBoundingClientRect(); return el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) }), true, 'Confirmation is painted above the slide panel')
      await page.screenshot({ path: `/tmp/odeon-v3-family-modal-${width}.png`, fullPage: true })
      const modalBox = await confirmation.boundingBox()
      assert.ok(modalBox.width <= width - 20 && modalBox.height < 700, 'Confirmation is compact and contained')
      await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
      assert.equal(await members.getByText('Sophie Kim', { exact: true }).count(), 1)
      await members.getByRole('button', { name: 'Remove from Family Group', exact: true }).first().click()
      const confirmRemoval = confirmation.getByRole('button', { name: 'Confirm', exact: true })
      await confirmRemoval.tap()
      assert.equal(await confirmation.isVisible(), true, 'A touch tap does not remove a dependent')
      await confirmRemoval.focus()
      await page.keyboard.down('Space')
      await page.waitForTimeout(450)
      assert.equal(await confirmRemoval.textContent(), 'Confirm', 'Button label stays unchanged during the hold')
      assert.ok(await confirmRemoval.locator('.lb-fill').count(), 'Hold paints a progress fill')
      await page.screenshot({ path: `/tmp/odeon-hold-confirm-${width}.png`, fullPage: true })
      await page.keyboard.up('Space')
      await confirmRemoval.waitFor()
      assert.equal(await confirmation.isVisible(), true, 'Releasing keyboard early cancels removal')
      await confirmRemoval.focus()
      await page.keyboard.down('Enter')
      await page.waitForTimeout(1700)
      await page.keyboard.up('Enter')

      await confirmation.waitFor({ state: 'hidden' })
      assert.equal(await members.getByText('Sophie Kim', { exact: true }).count(), 0)
      await dependents.getByRole('button', { name: 'Back to Sam Kim', exact: true }).click()
      assert.equal(await dependents.getByRole('heading', { name: 'Sophie Kim', exact: true }).count(), 0)
      await dependents.getByRole('heading', { name: 'Ethan Kim', exact: true }).waitFor()
      await portal.getByRole('button', { name: 'Edit Contact', exact: true }).click()
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('button', { name: 'Add Dependent', exact: true }).click()
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('textbox', { name: 'First name', exact: true }).fill('Jamie')
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('textbox', { name: 'Last name', exact: true }).fill('Kim')
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('textbox', { name: 'Email', exact: true }).fill('jamie@example.invalid')
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click()
      assert.equal(await dependents.getByRole('heading', { name: 'Jamie Kim', exact: true }).count(), 0)
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('button', { name: 'Add Dependent', exact: true }).click()
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('textbox', { name: 'First name', exact: true }).fill('Jamie')
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('textbox', { name: 'Last name', exact: true }).fill('Kim')
      await portal.getByRole('region', { name: 'Manage Family Group', exact: true }).getByRole('textbox', { name: 'Email', exact: true }).fill('jamie@example.invalid')
      await dependents.getByRole('button', { name: 'Add Dependent', exact: true }).click()
      await portal.getByRole('button', { name: 'Save changes', exact: true }).click()
      await dependents.getByRole('heading', { name: 'Jamie Kim', exact: true }).waitFor()
      await dependents.getByText('jamie@example.invalid', { exact: true }).waitFor()
      assert.equal(await portal.evaluate(el => el.scrollWidth > el.clientWidth + 1), false)
      await page.goto(`${base}?prototype=v3&view=quick&account=preview:kim&student=preview:sophie&section=profile`)
      await portal.getByRole('heading', { name: 'Contact details', exact: true }).waitFor()
      assert.equal(await portal.getByRole('button', { name: 'Send SMS', exact: true }).isDisabled(), true, 'Missing dependent phone never falls back to holder')
      assert.equal(await portal.getByRole('button', { name: 'Send email', exact: true }).isDisabled(), true, 'Missing dependent email never falls back to holder')
      await portal.getByRole('button', { name: 'Send email', exact: true }).getByText('Not added', { exact: true }).waitFor()
      assert.deepEqual(errors, [])
      assert.deepEqual(apis, [])
      console.log(`PASS V3 global edit account, metadata, atomic contact save/cancel, embedded family remove/cancel and add dependent ${width}px`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
