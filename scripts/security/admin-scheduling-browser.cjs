/* eslint-disable @typescript-eslint/no-require-imports -- Loopback fictional browser acceptance only. */
const assert = require('node:assert/strict')
const crypto = require('node:crypto')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:3242'
assert.match(base, /^http:\/\/127\.0\.0\.1:/)
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      page.setDefaultTimeout(15000)
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      const payload = Buffer.from(JSON.stringify({ actor: { instructorId: 'fixture', personId: 'fixture', fullName: 'Fictional Reviewer', displayName: 'Reviewer', access: { kind: 'demo', tenantId: '00000000-0000-0000-0000-000000000002' } }, expiresAt: Date.now() + 3600000 })).toString('base64url')
      const signature = crypto.createHmac('sha256', 'local-scheduling-fixture-only').update(payload).digest('base64url')
      if (!process.env.LOCAL_REVIEW_NO_SESSION) await page.context().addCookies([{ name: 'pulse_access', value: `${payload}.${signature}`, url: base }])
      await page.goto(`${base}/odeon-demo?screen=setup&section=teachers`)
      await page.waitForURL('**screen=staff*')
      await page.getByText('Maya Chen', { exact: true }).click()
      await page.getByRole('button', { name: 'Qualifications & availability', exact: true }).click()
      await page.getByLabel('Teacher name', { exact: true }).waitFor()
      await page.getByRole('heading', { name: 'Availability', exact: true }).waitFor()
      await page.getByLabel('Apply availability changes to', { exact: true }).selectOption('week')
      assert.equal(await page.getByLabel('Piano maximum level', { exact: true }).inputValue(), '3')
      await page.screenshot({ path: `/private/tmp/pulse-staff-profile-${width}.png`, fullPage: true })
      await page.getByRole('checkbox', { name: /Can be scheduled for administrative time/ }).check()
      await page.getByRole('button', { name: 'Save changes', exact: true }).click()
      await page.getByRole('heading', { name: 'Staff', exact: true }).waitFor()
      await page.goto(`${base}/odeon-demo?screen=setup&section=adminResponsibilities`)
      await page.evaluate(async () => { await document.fonts.ready })
      assert.match(await page.getByRole('heading', { level: 1 }).evaluate(element => getComputedStyle(element).fontFamily), /Baloo/i)
      assert.equal(await page.getByRole('button', { name: 'Teachers & Staff', exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Configure administrative time', exact: true }).click()
      let configure = page.getByRole('dialog', { name: 'Configure administrative time' })
      await configure.getByRole('button', { name: 'Add duty', exact: true }).click()
      await configure.getByLabel('Duty 1', { exact: true }).fill('Reception')
      await configure.getByRole('button', { name: 'Add duty', exact: true }).click()
      await configure.getByLabel('Duty 2', { exact: true }).fill('Temporary duty')
      await configure.getByRole('button', { name: 'Remove duty 2', exact: true }).click()
      await configure.getByRole('button', { name: 'Save changes', exact: true }).click()
      await configure.waitFor({ state: 'detached' })
      await page.reload()
      await page.getByRole('button', { name: 'Configure administrative time', exact: true }).waitFor()
      await page.screenshot({ path: `/private/tmp/pulse-teachers-staff-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Configure administrative time', exact: true }).click()
      configure = page.getByRole('dialog', { name: 'Configure administrative time' })
      assert.equal(await configure.getByLabel('Duty 1', { exact: true }).inputValue(), 'Reception')
      await configure.getByLabel('Duty 1', { exact: true }).fill('Front desk')
      await configure.getByRole('button', { name: 'Save changes', exact: true }).click()
      await configure.waitFor({ state: 'detached' })
      await page.goto(`${base}/odeon-demo?screen=staff`)
      await page.getByText('Maya Chen', { exact: true }).click()
      await page.getByRole('button', { name: 'Assign administrative time', exact: true }).click()
      const modal = page.getByRole('dialog')
      await modal.getByLabel('Duty', { exact: true }).selectOption({ label: 'Front desk' })
      assert.equal(await modal.getByLabel('Start time', { exact: true }).locator('option').evaluateAll(options => options.every(option => /:(00|30)$/.test(option.value))), true)
      assert.equal(await modal.getByLabel('Room (optional)', { exact: true }).count(), 1)
      assert.equal(await modal.getByRole('heading', { name: 'Duty details', exact: true }).count(), 1)
      assert.equal(await modal.getByRole('heading', { name: 'Schedule', exact: true }).count(), 1)
      assert.match(await modal.getByLabel('Notes', { exact: true }).evaluate(element => getComputedStyle(element).fontFamily), /DM[ _]Sans/i)
      assert.equal(await modal.getByLabel('Notes', { exact: true }).evaluate(element => element.tagName), 'TEXTAREA')
      await modal.getByRole('heading', { name: 'Duty details', exact: true }).scrollIntoViewIfNeeded()
      await page.waitForTimeout(200) // Capture after the shared dialog entrance animation.
      await page.screenshot({ path: `/private/tmp/pulse-admin-scheduling-${width}.png` })
      assert.equal(await modal.getByLabel('Assigned staff', { exact: true }).inputValue(), 'demo:teacher-1')
      await modal.getByLabel('Location', { exact: true }).selectOption('studio')
      await modal.getByLabel('Start time', { exact: true }).selectOption('12:00')
      await modal.getByLabel('Booking date', { exact: true }).fill('2026-11-05')
      await modal.getByRole('button', { name: 'Save administrative time', exact: true }).click()
      await modal.waitFor({ state: 'detached' })
      await page.reload()
      const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('odeon:app-sample:v2')))
      const assignment = saved.snapshot.data.calendarBookings.find(item => item.kind === 'admin' && item.teacherId === 'demo:teacher-1')
      assert.ok(assignment, 'person-first assignment persists across reload')
      assert.equal(assignment.responsibilityName, 'Front desk')
      assert.equal(assignment.roomId, '', 'no implicit room reservation')
      await page.goto(`${base}/odeon-demo?screen=calendar`)
      await page.getByRole('button', { name: 'Add booking', exact: true }).click()
      await page.getByRole('button', { name: 'Choose Administrative time', exact: true }).click()
      await page.getByRole('dialog').getByLabel('Duty', { exact: true }).selectOption({ label: 'Front desk' })
      assert.deepEqual(errors, [])
      await page.close()
      console.log(`PASS: ${width}px setup redirect, staff qualifications/availability save, duty configuration/reload and person-first assignment`)
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })