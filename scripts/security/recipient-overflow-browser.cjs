/* eslint-disable @typescript-eslint/no-require-imports -- Synthetic browser regression checks. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    for (const width of [1440, 1024, 768, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 900 } })
      const errors = []; const writes = []
      page.on('pageerror', error => errors.push(error.message))
      const people = Array.from({ length: 69 }, (_, index) => ({ id: `person:${index}`, name: `Contact ${String(index).padStart(2, '0')} With A Long Name`, email: `contact-${index}@example.com`, phone: '+12025550123', student: '', stage: '', profileType: 'contact', profileId: `${index}`, smsContactId: `${index}` }))
      await page.route('**/api/**', route => {
        const request = route.request(); const url = new URL(request.url())
        if (request.method() === 'POST') writes.push(url.pathname)
        const json = url.pathname === '/api/conversations' ? { people }
          : url.pathname === '/api/conversations/email' ? url.searchParams.has('mailbox') ? { threads: [], nextCursor: null } : { mailboxes: [{ id: 'box', email: 'office@example.com', canSend: true }] }
          : []
        return route.fulfill({ json })
      })
      const button = (root, name) => root.getByRole('button', { name, exact: true })
      const fits = async root => assert.ok(await root.evaluate(node => node.scrollWidth <= node.clientWidth + 1), 'Container must not overflow horizontally')
      await page.goto(process.env.CONVERSATIONS_LIVE_REVIEW_URL || 'http://127.0.0.1:3102')
      await button(page, `Open conversation with ${people[0].name}`).press('Enter')
      await page.getByText(people[0].phone, { exact: true }).waitFor()
      await page.getByRole('textbox', { name: 'SMS message', exact: true }).fill('Preview remains visible')
      if (width >= 1000) {
        const preview = page.getByRole('complementary', { name: 'SMS preview pane' })
        await preview.getByText('Preview remains visible', { exact: true }).waitFor()
        const workspace = await page.getByLabel('SMS workspace', { exact: true }).boundingBox()
        const pane = await preview.boundingBox()
        assert.ok(Math.abs(pane.width / workspace.width - 0.7) < 0.005, 'SMS must stay 30/70')
      }
      await button(page, 'Email').click()
      await page.getByText(people[0].email, { exact: true }).waitFor()
      await button(page, 'SMS').click()
      await page.getByText(people[0].phone, { exact: true }).waitFor()
      await button(page, 'Back to Communications').click()
      await button(page, 'Send new email').click()
      const modal = page.getByRole('dialog', { name: 'New message', exact: true })
      const height = (await modal.boundingBox()).height
      const toResults = modal.getByRole('table', { name: 'To search results', exact: true })
      await toResults.getByRole('checkbox', { name: `Select Add ${people[0].name} to To`, exact: true }).waitFor()
      const resultBounds = await toResults.locator('..').boundingBox()
      const searchBounds = await modal.getByRole('textbox', { name: 'Search To', exact: true }).boundingBox()
      const radioBounds = await modal.getByRole('radiogroup', { name: 'Send as' }).boundingBox()
      assert.ok(searchBounds.y + searchBounds.height <= radioBounds.y, 'Search must precede Send as')
      const selectBounds = await modal.getByRole('checkbox', { name: 'Select all', exact: true }).boundingBox()
      assert.ok(selectBounds.y >= resultBounds.y, 'Select all belongs in the table header')
      assert.ok(Math.abs(resultBounds.y + resultBounds.height - ((await modal.boundingBox()).y + height - 90)) < 40, 'List should fill body to footer')
      assert.equal(await toResults.getByRole('checkbox').count(), 70)
      const nameColor = await toResults.locator('strong').first().evaluate(node => getComputedStyle(node).color)
      assert.equal(nameColor, 'rgb(26, 26, 26)')
      await page.screenshot({ path: `/tmp/pulse-email-picker-${width}.png` })
      await modal.getByRole('checkbox', { name: 'Select all', exact: true }).click()
      await modal.getByText(/^…and \d+ more$/).last().waitFor()
      assert.equal((await modal.boundingBox()).height, height)
      await fits(modal)
      const summary = modal.getByRole('group', { name: 'To selected recipients', exact: true })
      const selectedPills = summary.getByRole('button', { name: /^Remove .* from To$/ })
      assert.ok(await selectedPills.count() <= 10)
      assert.ok((await summary.boundingBox()).height <= 64, 'Collapsed selection must fit two rows')
      const listBounds = await toResults.locator('..').boundingBox()
      const summaryBounds = await summary.boundingBox()
      const ctaBounds = await button(modal, 'Write email').boundingBox()
      assert.ok(summaryBounds.y >= listBounds.y + listBounds.height, 'Pills belong below table')
      assert.ok(summaryBounds.y + summaryBounds.height <= ctaBounds.y, 'Pills belong above CTA')
      const pillBackground = await selectedPills.first().locator('..').evaluate(node => getComputedStyle(node).backgroundColor)
      assert.equal(pillBackground, 'rgb(243, 244, 246)')
      await page.screenshot({ path: `/tmp/pulse-gray-pills-${width}.png` })
      await button(modal, 'See all').click()
      assert.equal(await modal.getByRole('button', { name: /^Remove .* from To$/ }).count(), 69)
      await button(modal, 'See fewer').click()
      await modal.getByRole('checkbox', { name: 'Deselect all', exact: true }).click()
      await toResults.getByRole('checkbox', { name: `Select Add ${people[0].name} to To`, exact: true }).click()
      await modal.getByRole('radio', { name: 'Cc', exact: true }).check()
      const ccResults = modal.getByRole('table', { name: 'Cc search results', exact: true })
      await ccResults.getByRole('checkbox', { name: `Select Add ${people[1].name} to Cc`, exact: true }).waitFor()
      await modal.getByRole('checkbox', { name: 'Select all', exact: true }).last().click()
      await modal.getByText(/^…and \d+ more$/).last().waitFor()
      await button(modal, 'Write email').click()
      const composer = page.getByRole('region', { name: 'Email composer', exact: true })
      assert.equal(await composer.getByRole('table').count(), 0, 'Composer must not show the selector table')
      await button(composer, 'Manage recipients').click()
      const manage = page.getByRole('dialog', { name: 'Manage recipients', exact: true })
      await manage.getByText(/^…and \d+ more$/).last().waitFor()
      await button(manage, 'See all').click()
      assert.equal(await manage.getByRole('button', { name: /^Remove .* from Cc$/ }).count(), 68)
      await button(manage, 'Done').click()
      await fits(composer)
      const composeBounds = await composer.boundingBox()
      assert.ok(composeBounds.width >= width - (width >= 768 ? 60 : 30), 'Standalone composer should fill the available width')
      await composer.getByRole('textbox', { name: 'Email subject' }).fill('Responsive regression check')
      await composer.getByRole('textbox', { name: 'Email body' }).fill('Draft only; never sent.')
      await fits(page.locator('html'))
      await page.screenshot({ path: `/tmp/pulse-recipient-overflow-${width}.png`, fullPage: true })
      await button(composer, 'Save as draft').click()
      const draftTitle = page.getByText('You have a message in draft', { exact: true })
      await draftTitle.waitFor()
      const tableBounds = await page.getByRole('table', { name: 'Communications', exact: true }).boundingBox()
      const draftBounds = await draftTitle.boundingBox()
      assert.ok(draftBounds.y < tableBounds.y, 'Draft notice must precede table')
      const inTablePanel = await draftTitle.evaluate(node => {
        const table = document.querySelector('[role="table"][aria-label="Communications"]')
        return table.parentElement.contains(node)
      })
      assert.equal(inTablePanel, false, 'Draft notice must be outside the table panel')
      const nameHeader = page.getByRole('table', { name: 'Communications', exact: true }).getByRole('columnheader').first()
      const nameBounds = await nameHeader.boundingBox()
      assert.ok(Math.abs(nameBounds.x - tableBounds.x - 26) < 1, 'Text inset should match shared selection checkbox')
      const firstRowBounds = await page.getByRole('table', { name: 'Communications', exact: true }).getByRole('row').nth(1).boundingBox()
      assert.ok(firstRowBounds.y >= nameBounds.y + nameBounds.height, 'Header must not overlap the first row')
      await page.screenshot({ path: `/tmp/pulse-draft-notices-${width}.png` })
      assert.deepEqual(errors, [])
      assert.deepEqual(writes, [])
      console.log(`PASS ${width}px: phone/channel header, SMS preview, visible recipients, 69-person selection, 68-person Cc summary/expansion, responsive composer; no sends`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })