/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional browser regression. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      page.setDefaultTimeout(20000)
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.goto('http://127.0.0.1:3231/odeon-demo?screen=calendar')
      assert.equal(await page.getByLabel('Preview public booking rules').count(), 0)
      assert.equal(await page.getByRole('button', { name: 'Close', exact: true }).count(), 0)
      await page.waitForTimeout(200)
      await page.screenshot({ path: `/tmp/odeon-toolbar-feedback-${width}.png`, fullPage: true })
      await page.getByLabel('View by', { exact: true }).selectOption('service')
      await page.getByLabel('Calendar range', { exact: true }).selectOption('Day')
      await page.getByLabel('Calendar date', { exact: true }).fill('2026-11-10')
      const bass = page.locator('[data-resource-column="Bass"] button[aria-label^="Book "]').first()
      const slotName = await bass.getAttribute('aria-label')
      await bass.focus(); await page.keyboard.press('Enter')
      const modal = page.getByRole('dialog')
      assert.equal(await modal.getByRole('button', { name: /Choose / }).count(), 0)
      assert.equal(await modal.getByLabel('Lesson service', { exact: true }).inputValue(), 'bass')
      assert.equal(await modal.getByLabel('Lesson service', { exact: true }).isDisabled(), true)
      assert.ok(await modal.getByLabel('Start time', { exact: true }).locator('option:disabled').count() > 0)
      const actions = modal.getByRole('button', { name: 'Continue enrollment', exact: true })
      const secondary = modal.getByRole('button', { name: 'Send enrollment request', exact: true })
      assert.ok(await actions.evaluate((element) => element.compareDocumentPosition(element.previousElementSibling) & Node.DOCUMENT_POSITION_PRECEDING))
      assert.equal(await secondary.count(), 1)
      assert.equal(await modal.getByLabel('Start time', { exact: true }).inputValue(), slotName.split(' at ')[1])
      await page.waitForTimeout(250)
      await page.screenshot({ path: `/tmp/odeon-context-bass-${width}.png` })
      await page.keyboard.press('Escape')
      await page.getByLabel('View by', { exact: true }).selectOption('teacher')
      const teacherSlot = page.locator('[data-resource-column="demo:teacher-1"] button[aria-label^="Book "]').first()
      await teacherSlot.focus(); await page.keyboard.press('Enter')
      await modal.getByRole('button', { name: 'Choose Lesson', exact: true }).click()
      assert.equal(await modal.getByLabel('Teacher', { exact: true }).inputValue(), 'demo:teacher-1')
      assert.equal(await modal.getByLabel('Teacher', { exact: true }).isDisabled(), false)
      const services = await modal.getByLabel('Lesson service', { exact: true }).locator('option').evaluateAll(items => items.map(item => item.value))
      assert.ok(!services.includes('bass'))
      await page.keyboard.press('Escape')
      await page.getByLabel('View by', { exact: true }).selectOption('room')
      const smallRoom = page.locator('[data-resource-column="Studio 1"] button[aria-label^="Book "]').first()
      await smallRoom.focus(); await page.keyboard.press('Enter')
      assert.equal(await modal.getByRole('button', { name: 'Choose Band rehearsal', exact: true }).count(), 0)
      assert.equal(await modal.getByRole('button', { name: 'Choose Event', exact: true }).count(), 0)
      await modal.getByRole('button', { name: 'Choose Lesson', exact: true }).click()
      const roomServices = await modal.getByLabel('Lesson service', { exact: true }).locator('option').evaluateAll(items => items.map(item => item.value))
      assert.ok(!roomServices.some(id => ['tiny', 'rockers', 'band'].includes(id)))
      assert.equal(await modal.getByLabel('Room', { exact: true }).inputValue(), 'Studio 1')
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: 'Add booking', exact: true }).click()
      await modal.getByRole('button', { name: 'Choose Event', exact: true }).click()
      await modal.getByLabel('Booking date').fill('2026-11-10')
      await modal.getByLabel('Start time').selectOption('09:00')
      await modal.getByLabel('Required event capacity').fill('9')
      assert.equal(await modal.getByLabel('Room', { exact: true }).locator('option').count(), 1)
      await modal.getByText('No suitable rooms available for this activity and time.').waitFor()
      assert.equal(await modal.locator('[aria-invalid=true]').count(), 0)
      await modal.getByLabel('Required event capacity').fill('8')
      assert.equal(await modal.getByLabel('Room', { exact: true }).inputValue(), 'Band room')
      await modal.getByRole('button', { name: 'Back', exact: true }).click()
      await modal.getByRole('button', { name: 'Choose Band rehearsal', exact: true }).click()
      assert.deepEqual(await modal.getByLabel('Room', { exact: true }).locator('option').evaluateAll(items => items.map(item => item.value)), ['', 'Band room'])
      assert.deepEqual(errors, [])
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
      console.log(`PASS context ${width}: Bass direct entry, teacher scope, small-room restrictions, event capacity, rehearsal suitability`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })