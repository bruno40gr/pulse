/* eslint-disable @typescript-eslint/no-require-imports -- Source integration contracts. */
const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve } = require('node:path')
const source = file => readFileSync(resolve(__dirname, '../..', file), 'utf8')
test('Communications uses the current contact panel, not the retired contact UI', () => {
  const panel = source('components/inbox/ConversationProfilePanel.tsx')
  assert.match(panel, /<LiveContactPanel/)
  assert.doesNotMatch(panel, /ContactSlidePanel|tenant-fields/)
  assert.match(panel, /X-Contacts-Can-Edit/)
  assert.match(panel, /contactProfileFamilies\(roster, tenantId/)
  assert.match(panel, /controller.signal.aborted/)
  assert.match(panel, /history.dismissPanel\(\(\) => onCompose\(channel\)\)/)
  assert.match(panel, /contact.id === person.profileId/)
})
test('View contact hands SMS back to the mounted thread without replacing its draft', () => {
  const inbox = source('components/inbox/Conversations.tsx')
  assert.match(inbox, />View contact<\/ControlButton>/)
  assert.doesNotMatch(inbox, /View lead|Open lead for/)
  assert.match(inbox, /if \(location.channel !== 'sms'\) navigate/)
  assert.match(inbox, /textarea\[aria-label="SMS message"\]/)
  const panel = source('components/contacts/LiveContactPanel.tsx')
  assert.match(panel, /if \(onCompose\) \{ onCompose\('sms'\); return \}/)
  assert.match(panel, /if \(onCompose\) \{ onCompose\('email'\); return \}/)
  assert.match(panel, /setVisitedChannels/)
})
test('Overview uses the permission-aware shared profile without resetting its active family member on edits', () => {
  const page = source('app/dashboard/page.tsx')
  assert.match(page, /<ConversationProfilePanel/)
  assert.doesNotMatch(page, /ContactSlidePanel|tenant-fields|tenantFields/)
  assert.match(page, /useMemo<ConversationPerson \| null>/)
  assert.match(page, /onClose=\{\(\) => setSelectedContact\(null\)\}/)
  assert.doesNotMatch(page, /useMobilePanelHistory/)
  assert.match(page, /conversationComposeHref\(getActiveTenantId\(\), profilePerson.id, channel\)/)
  assert.match(page, /onContactUpdated=\{/)
  const callback = page.slice(page.indexOf('onContactUpdated={'))
  assert.match(callback, /setContactDetailsMap/)
  assert.match(callback, /setContactPreviewMap/)
  assert.doesNotMatch(callback, /setSelectedContact/)
  const panel = source('components/inbox/ConversationProfilePanel.tsx')
  assert.match(panel, /onContactUpdated\?\.\(updated\)/)
})
test('Staff uses the shared profile with one history owner and keeps bulk messaging', () => {
  const page = source('app/dashboard/staff/page.tsx')
  assert.match(page, /<ConversationProfilePanel/)
  assert.doesNotMatch(page, /ContactSlidePanel|tenant-fields|useMobilePanelHistory/)
  assert.match(page, /onClose=\{\(\) => setProfileStaff\(null\)\}/)
  assert.match(page, /conversationComposeHref\(tenantId, profilePerson.id, channel\)/)
  assert.match(page, /onContactUpdated=\{/)
  assert.match(page, /filter\(member => member.is_active !== false\)/)
  assert.match(page, /onClick=\{openBulkCompose\}/)
  assert.match(page, /<ComposePanel/)
  const panel = source('components/contacts/LiveContactPanel.tsx')
  assert.match(panel, /if \(!isInstructor \|\| !person \|\| !capabilities.edit \|\| saving\) return/)
  assert.match(panel, /body: JSON.stringify\(\{ is_active: nextActive \}\)/)
  assert.match(panel, /saved.is_active !== nextActive/)
  assert.match(panel, /Active students/)
  assert.match(panel, /onOpenPerson\(student.person_id\)/)
  const host = source('components/inbox/ConversationProfilePanel.tsx')
  assert.match(host, /active_students: data.active_students/)
  assert.match(host, /data.tenant_id !== tenantId/)
  assert.match(host, /requestId !== navigationRequest.current/)
})