/* eslint-disable @typescript-eslint/no-require-imports -- Local calendar interaction regression. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:3231'
assert.match(base, /^http:\/\/127\.0\.0\.1:/)

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1100 } })
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.goto(`${base}/odeon-demo?screen=calendar`)
      const view = page.getByRole('group', { name: 'View by', exact: true })
      await view.waitFor()
      assert.equal(await view.getByRole('button', { name: 'Teacher', exact: true }).getAttribute('aria-pressed'), 'true')
      assert.ok(await page.locator('[data-resource-column]').count() > 1)
      await view.getByRole('button', { name: 'Service', exact: true }).click()
      const columns = await page.locator('[data-resource-column]').evaluateAll(items => items.map(item => item.dataset.resourceColumn))
      for (const service of ['Piano', 'Guitar', 'Voice & Vocals', 'Drums', 'Bass', 'Tiny Keys', 'Little Rockers', 'Band']) assert.ok(columns.includes(service))
      const ids = await page.locator('[data-booking-id]').evaluateAll(items => items.map(item => item.dataset.bookingId).sort())
      assert.ok(ids.length > 0)
      await view.getByRole('button', { name: 'Room', exact: true }).click()
      assert.deepEqual(await page.locator('[data-booking-id]').evaluateAll(items => items.map(item => item.dataset.bookingId).sort()), ids)
      await page.getByRole('button', { name: 'Week', exact: true }).click()
      assert.equal(await page.locator('[data-resource-column]').count(), 7)
      await page.getByLabel('Week room', { exact: true }).selectOption({ label: 'Studio 5' })
      await page.getByRole('button', { name: 'Day', exact: true }).click()
      await view.getByRole('button', { name: 'Service', exact: true }).click()
      const grid = page.getByRole('region', { name: 'Academy schedule', exact: true })
      await grid.evaluate(element => { element.scrollLeft = 180 })
      const first = page.locator('[data-booking-id]').first()
      const border = await first.evaluate(element => [getComputedStyle(element).borderLeftWidth, getComputedStyle(element).borderRightWidth])
      assert.equal(border[0], border[1])
      const movedTitle = await first.locator('strong').innerText()
      await first.click()
      const inspector = page.getByRole('dialog', { name: 'Booking details', exact: true })
      await inspector.waitFor()
      await page.keyboard.press('Escape')
      assert.equal(await inspector.count(), 0)
      await first.click()
      await inspector.getByRole('button', { name: 'Reschedule', exact: true }).click()
      await page.getByRole('region', { name: 'Available lesson times', exact: true }).waitFor()
      assert.equal(await page.getByRole('dialog', { name: /Family workspace/ }).count(), 0)
      await page.locator('button[class*="openSlot"]').first().click()
      const teachers = page.getByRole('group', { name: /Teachers at/ })
      if (await teachers.count()) await teachers.getByRole('button').first().click()
      const confirm = page.getByRole('button', { name: 'Reschedule lesson', exact: true })
      await confirm.focus()
      await page.keyboard.down('Space')
      await page.waitForTimeout(1700)
      await page.keyboard.up('Space')
      await view.waitFor()
      assert.equal(await view.getByRole('button', { name: 'Service', exact: true }).getAttribute('aria-pressed'), 'true')
      assert.ok((await page.locator('body').innerText()).includes(`Moved ${movedTitle}`))
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      await page.screenshot({ path: `/tmp/odeon-calendar-hub-${width}.png`, fullPage: true })
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: resources, service roster, week, inspector, shared blocks, rescheduling and return context`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })