/* eslint-disable @typescript-eslint/no-require-imports -- Isolated fictional review; all writes intercepted. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const contacts = require('./fixtures/contact-list-review.cjs')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const width of [1440, 900, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1100 } })
      const errors = [], writes = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/api/**', route => {
        const request = route.request(), path = new URL(request.url()).pathname
        if (path === '/api/inbox/reconcile') return route.fulfill({ json: { skipped: true } })
        if (request.method() !== 'GET') { writes.push(path); return route.abort() }
        return route.fulfill({ json: path === '/api/contacts' ? contacts : path === '/api/tenant-fields' ? [] : {} })
      })
      await page.goto('http://127.0.0.1:3218/dashboard/contacts')
      const table = page.getByRole('table', { name: 'Contacts', exact: true })
      const name = text => table.getByRole('button', { name: text, exact: true })
      const view = page.getByRole('group', { name: 'Contact view', exact: true })
      await name('Ethan Kim').waitFor()
      await name('Casey Rivera').first().waitFor()
      await name('Jules Bennett').waitFor()
      assert.equal(await table.getByRole('button', { name: /^(Jules Bennett|Drew Brooks|Robin Chen|Ethan Kim|Jamie Kim|Sam Kim|Sophie Kim|Avery Patel|Morgan Reed|Casey Rivera|Emma Smith|Jane Smith)$/ }).first().textContent(), 'Jules Bennett')
      assert.ok(await table.getByText('Instructor', { exact: true }).count() >= 3)
      assert.equal(await view.getByRole('switch').count(), 1)
      assert.equal(await table.getByText('—', { exact: true }).count(), 0)
      for (const person of contacts.filter(person => person.is_student)) {
        assert.ok(person.instructor?.name, 'Every fictional student has an instructor')
        await name(`${person.first_name} ${person.last_name}`).locator('xpath=ancestor::*[@role="row"][1]').getByText(person.instructor.name, { exact: true }).waitFor()
      }
      assert.equal(await name('Sam Kim').count(), 1)
      assert.equal(await table.getByRole('button', { name: /Expand|Collapse/ }).count(), 0)
      for (const person of ['Avery Patel', 'Morgan Reed', 'Robin Chen', 'Drew Brooks']) await name(person).waitFor()
      const parentX = await name('Sam Kim').evaluate(el => el.getBoundingClientRect().x)
      const childX = await name('Ethan Kim').evaluate(el => el.getBoundingClientRect().x)
      assert.ok(Math.abs(childX - parentX) < 2, 'Names have no family indentation')
      // Message targets only: a minor routes to their account holder, so they get no checkbox.
      for (const minor of ['Ethan Kim', 'Sophie Kim', 'Emma Smith']) assert.equal(await table.getByRole('checkbox', { name: `Select ${minor}`, exact: true }).count(), 0, `${minor} cannot receive, so no checkbox`)
      const samSelection = table.getByRole('checkbox', { name: 'Select Sam Kim', exact: true })
      const jamieSelection = table.getByRole('checkbox', { name: 'Select Jamie Kim', exact: true })
      // The family row selects the family's recipients; an individual row toggles only itself.
      await samSelection.check()
      assert.equal(await jamieSelection.isChecked(), true, 'The family row selects the family recipients')
      await page.screenshot({ path: `/private/tmp/pulse-family-person-selection-${width}.png` })
      await samSelection.uncheck()
      assert.equal(await jamieSelection.isChecked(), false)
      const counter = page.getByText('12 contacts', { exact: true })
      assert.ok(await counter.evaluate(el => !!(document.querySelector('[data-table-toolbar]').compareDocumentPosition(el) & Node.DOCUMENT_POSITION_FOLLOWING)))
      assert.ok(await counter.evaluate(el => !!(el.compareDocumentPosition(document.querySelector('[role="table"]')) & Node.DOCUMENT_POSITION_FOLLOWING)))
      const statusWidth = await table.getByRole('columnheader', { name: /Status/ }).evaluate(el => el.getBoundingClientRect().width)
      assert.ok(statusWidth < 110, 'Status column does not stretch away from names')
      await page.screenshot({ path: `/private/tmp/pulse-contact-group-family-${width}.png` })
      await view.getByRole('switch', { name: 'Families' }).uncheck()
      await page.getByText('12 contacts', { exact: true }).waitFor()
      assert.equal(await page.getByText('Showing 10 of 12', { exact: true }).count(), 0)
      assert.equal(await table.getByRole('button', { name: /^(Jules Bennett|Drew Brooks|Robin Chen|Ethan Kim|Jamie Kim|Sam Kim|Sophie Kim|Avery Patel|Morgan Reed|Casey Rivera|Emma Smith|Jane Smith)$/ }).first().textContent(), 'Jules Bennett')
      const pagination = page.getByRole('navigation', { name: 'Contacts pagination' })
      const selectAll = table.getByRole('checkbox', { name: 'Select all contacts', exact: true })
      const seen = new Set()
      for (const person of contacts) if (await name(`${person.first_name} ${person.last_name}`).count()) seen.add(person.id)
      assert.equal(await selectAll.count(), 1)
      assert.equal(await table.getByRole('checkbox').count() >= 1, true)
      await selectAll.check()
      const checkedLabels = await table.getByRole('checkbox', { checked: true }).evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')))
      assert.ok(checkedLabels.length > 1, 'Students view retains record selection independently of routing')
      const totalPages = await pagination.innerText()
      if (/Page 1 of 2/.test(totalPages)) {
        await pagination.getByRole('button', { name: 'Next', exact: true }).click()
        await pagination.getByText('Page 2 of 2', { exact: true }).waitFor()
      }
      for (const person of contacts) if (await name(`${person.first_name} ${person.last_name}`).count()) seen.add(person.id)
      assert.equal(seen.size, contacts.length)
      await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
      await table.getByRole('checkbox', { name: 'Select Jane Smith', exact: true }).check()
      await page.screenshot({ path: `/private/tmp/pulse-contact-group-none-${width}.png` })
      await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
      await view.getByRole('switch', { name: 'Families' }).check()
      assert.equal(await table.getByRole('checkbox', { checked: true }).count(), 0)
      assert.equal(await view.getByRole('switch', { name: 'Families' }).getAttribute('aria-checked'), 'true')
      assert.equal(await view.evaluate(el => el.nextElementSibling?.textContent.includes('Table Preferences')), true)
      assert.deepEqual(errors, [])
      assert.deepEqual(writes, [])
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      console.log(`PASS ${width}px: Students/Families toggle, instructors retained, tight status, no indentation, selection reset`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })