/* eslint-disable @typescript-eslint/no-require-imports -- Local browser regression. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.ODEON_DEMO_URL || 'http://127.0.0.1:3198'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local review only')
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH || undefined })
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 } })
      const page = await context.newPage(), errors = [], apis = []
      page.setDefaultTimeout(12000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) { apis.push(url.pathname); return route.abort() }
        return route.continue()
      })
      await page.goto(`${base}/odeon-demo`)
      await page.getByRole('heading', { name: 'Contacts', exact: true }).waitFor()
      assert.equal(await page.getByRole('heading', { name: 'Explore your sample school' }).count(), 0)
      await page.getByText('Emma Adams', { exact: true }).click()
      const dialog = page.getByRole('dialog', { name: 'Family workspace V3' })
      await dialog.getByText('Student profile', { exact: true }).waitFor()
      await dialog.getByRole('button', { name: 'Billing', exact: true }).click()
      await dialog.getByText('DEMO-2026-09-1', { exact: false }).first().waitFor()
      await page.screenshot({ path: `/tmp/odeon-real-ui-billing-${width}.png`, fullPage: true })
      await dialog.getByRole('button', { name: /Makeups/ }).click()
      await dialog.getByText('Piano', { exact: false }).first().waitFor()
      await page.screenshot({ path: `/tmp/odeon-real-ui-makeups-${width}.png`, fullPage: true })
      await dialog.getByRole('button', { name: 'Close', exact: true }).first().click()
      await page.getByRole('button', { name: 'View families', exact: true }).click()
      await page.getByText('Alex Adams', { exact: true }).first().waitFor()
      await page.screenshot({ path: `/tmp/odeon-real-ui-contacts-${width}.png`, fullPage: true })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
      await page.goto(`${base}/odeon-demo?screen=staff`)
      await page.getByRole('heading', { name: 'Staff', exact: true }).waitFor()
      await page.getByText('Maya Chen', { exact: true }).click()
      await page.getByRole('dialog').getByText('Emma Adams', { exact: true }).waitFor()
      await page.screenshot({ path: `/tmp/odeon-real-ui-teacher-${width}.png`, fullPage: true })
      await page.goto(`${base}/odeon-demo?view=parent&account=demo%3Afamily-13`)
      await page.getByText('Parent portal · Zoe Morgan', { exact: true }).waitFor()
      await page.getByText('Ruby Morgan', { exact: true }).first().waitFor()
      assert.equal(await page.getByText('Emma Adams', { exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Billing', exact: true }).click()
      await page.getByText('DEMO-2026-09-13', { exact: false }).first().waitFor()
      await page.screenshot({ path: `/tmp/odeon-real-ui-parent-${width}.png`, fullPage: true })
      await page.goto(`${base}/odeon-demo/school-setup?experience=configured`)
      await page.getByRole('heading', { name: 'School Setup', exact: true, level: 1 }).waitFor()
      await page.getByRole('navigation', { name: 'School setup sections' }).getByRole('button', { name: 'Plans & prices', exact: true }).click()
      await page.getByText('Staff discount', { exact: true }).waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
      assert.deepEqual(errors, [])
      assert.deepEqual(apis, [])
      console.log(`PASS ${width}px: actual Contacts table, V3 drawer billing/makeups, family view, actual Staff table/panel, actual ParentPortal, SchoolSetup; no API calls or runtime errors`)
      await context.close()
    }
    const context = await browser.newContext()
    for (const route of ['/dashboard/staff', '/content-studio-prototype/school-setup', '/odeon-demo/private']) {
      const response = await context.request.get(`${base}${route}`, { maxRedirects: 0 })
      assert.equal(response.status(), 307)
      assert.match(response.headers().location, /\/login/)
    }
    assert.equal((await context.request.get(`${base}/api/staff`, { maxRedirects: 0 })).status(), 401)
    console.log('PASS: production staff/prototype/API protections unchanged')
    await context.close()
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })