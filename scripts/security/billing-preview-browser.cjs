/* eslint-disable @typescript-eslint/no-require-imports -- Local-only fictional billing journeys. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const version of ['', 'v2', 'v3']) for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], apis = []
      page.setDefaultTimeout(10000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.hostname === 'res.cloudinary.com' && route.request().resourceType() === 'image') return route.continue()
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) {
          const shell = ['/api/account/identity', '/api/account/claim-reminder', '/api/notifications', '/api/leads', '/api/inbox', '/api/inbox/reconcile', '/api/tenant/sync-status']
          if (!shell.includes(url.pathname)) { apis.push(url.pathname); return route.abort() }
          return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        }
        return route.continue()
      })
      const params = new URLSearchParams({ view: 'staff', account: 'preview:kim', section: 'billing', ...(version ? { prototype: version } : {}) })
      await page.goto(`${base}?${params}`)
      await page.getByRole('heading', { name: '$400.00 due', exact: true }).waitFor()
      assert.equal(await page.getByRole('heading', { name: 'Open balance', exact: true }).count(), 0)
      assert.equal(await page.getByText(/overdue|outstanding|due Nov 15/, { exact: false }).count(), 0, 'Summary does not split the unpaid balance')
      const invoices = page.getByRole('region', { name: 'Invoices', exact: true })
      assert.equal(await invoices.getByRole('button', { name: 'Pay $200', exact: true }).count(), 2)
      assert.equal(await invoices.getByRole('button', { name: 'Create statement', exact: true }).count(), 0)
      assert.equal(await invoices.getByRole('button', { name: 'Create invoice', exact: true }).count(), 0)
      await invoices.getByRole('button', { name: 'Billing actions', exact: true }).click()
      await invoices.getByRole('menuitem', { name: 'Create statement', exact: true }).waitFor()
      await invoices.getByRole('menuitem', { name: 'Create invoice', exact: true }).waitFor()
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: 'Payment methods', exact: true }).click()
      const cardsDialog = page.getByRole('region', { name: 'Payment methods', exact: true })
      await cardsDialog.getByRole('textbox', { name: 'Name on card', exact: true }).fill('Taylor Kim')
      assert.equal(await cardsDialog.getByRole('combobox', { name: 'Save card for', exact: true }).inputValue(), 'preview:sam-kim')
      await cardsDialog.getByRole('checkbox', { name: 'I am authorized to use this card', exact: true }).check()
      await cardsDialog.getByRole('button', { name: 'Add card', exact: true }).click()
      await cardsDialog.getByText('Name on card: Taylor Kim', { exact: false }).waitFor()
      await page.screenshot({ path: `/tmp/odeon-cardholder-${version || 'v1'}-${width}.png`, fullPage: true })
      await cardsDialog.getByRole('button', { name: 'Back to billing', exact: true }).click()
      const firstCard = invoices.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).locator('..').locator('..')
      const overduePayColor = await firstCard.getByRole('button', { name: 'Pay $200', exact: true }).evaluate(el => getComputedStyle(el).backgroundColor)
      assert.notEqual(overduePayColor, 'rgba(0, 0, 0, 0)', 'Overdue invoice Pay uses the red variant')
      const currentCard = invoices.getByRole('button', { name: 'View invoice DEMO-1004', exact: true }).locator('..').locator('..')
      assert.equal(await currentCard.getByRole('button', { name: 'Pay $200', exact: true }).evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)', 'Non-overdue invoice Pay stays neutral')
      const title = await firstCard.getByRole('heading').boundingBox()
      const status = await firstCard.getByText('Overdue', { exact: true }).boundingBox()
      assert.ok(Math.abs(status.y - title.y) < 45, 'Status belongs with the invoice title')
      await page.screenshot({ path: `/tmp/odeon-billing-${version || 'v1'}-${width}.png`, fullPage: true })
      const viewSize = await invoices.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).boundingBox()
      const paySize = await invoices.getByRole('button', { name: 'Pay $200', exact: true }).first().boundingBox()
      assert.ok(Math.abs(viewSize.width - paySize.width) < 1 && Math.abs(viewSize.height - paySize.height) < 1, 'Card actions have equal sizes')
      const totalPay = invoices.getByRole('button', { name: 'Pay $400', exact: true })
      const totalSize = await totalPay.boundingBox()
      assert.equal(totalSize.width, paySize.width, 'Total and individual Pay widths match')
      assert.equal(totalSize.height, paySize.height, 'Total and individual Pay heights match')
      assert.equal(await totalPay.evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)', 'Payment is not styled as a destructive action')
      await invoices.getByRole('button', { name: 'Pay $200', exact: true }).first().click()
      const directPayment = page.getByRole('dialog', { name: 'Pay', exact: true })
      await directPayment.getByRole('combobox', { name: 'Paying as', exact: true }).waitFor()
      assert.equal(await directPayment.getByRole('combobox', { name: 'Sam Kim’s payment method', exact: true }).getByRole('option', { name: /Taylor Kim/ }).count(), 1, 'Cardholder name appears without adding a payer')
      assert.equal(await directPayment.getByRole('combobox', { name: 'Paying as', exact: true }).getByRole('option', { name: 'Taylor Kim', exact: true }).count(), 0)
      assert.equal(await page.getByRole('article', { name: 'Itemized invoice', exact: true }).count(), 0, 'Card Pay skips invoice viewing')
      await directPayment.getByRole('button', { name: 'Close', exact: true }).click()
      await invoices.waitFor()
      assert.equal(await invoices.getByRole('button', { name: /Download|PDF/ }).count(), 0, 'PDF download belongs only in invoice details')
      await invoices.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).click()
      const document = page.getByRole('article', { name: 'Itemized invoice', exact: true })
      await document.waitFor()
      await document.getByRole('columnheader', { name: 'Quantity', exact: true }).waitFor()
      const logo = document.getByRole('img', { name: 'Headliner Music Academy', exact: true })
      await logo.waitFor()
      await logo.evaluate(image => image.decode())
      assert.equal(await logo.evaluate(image => image.complete && image.naturalWidth > 0), true, 'Uploaded logo loads')
      assert.equal(await page.getByRole('dialog', { name: 'Pay', exact: true }).count(), 0, 'View invoice does not open payment')
      const download = page.getByRole('button', { name: 'Download invoice DEMO-1003', exact: true })
      const pay = page.getByRole('button', { name: 'Pay $200', exact: true })
      assert.equal(await pay.evaluate(el => getComputedStyle(el).backgroundColor), overduePayColor, 'Overdue Pay styling matches card and invoice detail')
      const screenTitle = page.getByRole('heading', { level: 2, name: 'Invoice DEMO-1003', exact: true })
      await screenTitle.waitFor()
      const titleBounds = await screenTitle.boundingBox()
      const backBounds = await page.getByRole('button', { name: 'Back to invoices', exact: true }).boundingBox()
      assert.ok(backBounds.x < titleBounds.x && Math.abs(backBounds.y - titleBounds.y) < 20, 'Back shares the invoice title row without indenting V3 titles')
      await pay.scrollIntoViewIfNeeded()
      const downloadBounds = await download.boundingBox(), payBounds = await pay.boundingBox()
      assert.equal(await page.locator('footer[aria-label="Invoice actions"]').evaluate(element => getComputedStyle(element).position), 'static', 'Invoice action row stays in normal flow, never sticky or floating')
      const previewBounds = await document.boundingBox()
      assert.ok(downloadBounds.y >= previewBounds.y + previewBounds.height && payBounds.y >= previewBounds.y + previewBounds.height, 'Actions sit below invoice preview')
      assert.ok(Math.abs(downloadBounds.width - payBounds.width) < 1 && Math.abs(downloadBounds.height - payBounds.height) < 1, 'Invoice actions have equal sizes')
      assert.ok(downloadBounds.height < 44, 'Invoice buttons use shared medium sizing, not a forced large target')

      assert.ok(payBounds.y >= downloadBounds.y && (payBounds.y > downloadBounds.y + 4 || payBounds.x > downloadBounds.x), 'Primary Pay follows Download PDF')
      const downloadEvent = page.waitForEvent('download')
      await download.click()
      assert.equal((await downloadEvent).suggestedFilename(), 'invoice-DEMO-1003.pdf')
      await page.screenshot({ path: `/tmp/odeon-invoice-${version || 'v1'}-${width}.png`, fullPage: true })
      await pay.click()
      const payment = page.getByRole('dialog', { name: 'Pay', exact: true })
      await payment.getByRole('combobox', { name: 'Paying as', exact: true }).waitFor()
      const payingAs = payment.getByRole('combobox', { name: 'Paying as', exact: true })
      await payingAs.selectOption('preview:riley-kim')
      const rileyCards = payment.getByRole('combobox', { name: 'Riley Kim’s payment method', exact: true })
      assert.equal(await rileyCards.getByRole('option', { name: /4242|4444/ }).count(), 0, 'Riley selection excludes Sam cards')
      await rileyCards.selectOption('preview:riley-mc')
      await payment.getByRole('button', { name: 'Close', exact: true }).click()
      await document.waitFor()
      await page.getByRole('button', { name: 'Customize invoice fields', exact: true }).click()
      await page.getByRole('button', { name: 'Add custom field', exact: true }).click()
      await page.getByRole('textbox', { name: 'Field 1 label', exact: true }).fill('Service Type')
      await page.getByRole('textbox', { name: 'Field 1 value', exact: true }).fill('Individual music instruction')
      await page.getByRole('textbox', { name: 'Invoice notes', exact: true }).fill('Funding reference: FAMILY-42\nWeekly piano lessons.')
      await page.getByRole('button', { name: 'Save details', exact: true }).click()
      await document.getByText('Service Type', { exact: true }).waitFor()
      await document.getByText('Individual music instruction', { exact: true }).waitFor()
      assert.ok((await document.innerText()).includes('FAMILY-42'))
      await page.getByRole('button', { name: 'Back to invoices', exact: true }).click()
      await invoices.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).click()
      await document.waitFor()
      await page.getByRole('button', { name: 'Back to invoices', exact: true }).click()
      await invoices.getByRole('button', { name: 'Pay $400', exact: true }).click()
      const all = page.getByRole('dialog', { name: 'Pay all invoices', exact: true })
      await all.getByText('DEMO-1003 · Sam Kim', { exact: true }).waitFor()
      await all.getByText('DEMO-1004 · Riley Kim', { exact: true }).waitFor()
      assert.equal(await all.getByText(/DEMO-1002/).count(), 0, 'Paid invoices excluded')
      await all.getByRole('combobox', { name: 'Paying as', exact: true }).selectOption('preview:sophie')
      assert.equal(await all.getByRole('button', { name: 'Pay', exact: true }).isDisabled(), true, 'No saved card prevents payment')
      await all.getByRole('combobox', { name: 'Paying as', exact: true }).selectOption('preview:sam-kim')
      await all.getByRole('combobox', { name: 'Sam Kim’s payment method', exact: true }).selectOption('preview:sam-mc')
      await all.getByRole('button', { name: 'Pay', exact: true }).click()
      await page.getByRole('heading', { name: '$0.00 due', exact: true }).waitFor()
      assert.equal(await invoices.getByRole('button', { name: 'Pay $200', exact: true }).count(), 0)
      assert.equal(await invoices.getByRole('button', { name: 'Pay $400', exact: true }).count(), 0)
      await invoices.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).click()
      await document.getByText('Paid', { exact: true }).first().waitFor()
      assert.equal(await page.getByRole('button', { name: /^Pay \$/ }).count(), 0)
      await document.getByText('Paid by Sam Kim', { exact: true }).waitFor()
      await document.getByText('Paid with Mastercard ···· 4444', { exact: true }).waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      params.set('student', 'preview:sophie')
      await page.goto(`${base}?${params}`)
      await page.getByRole('heading', { name: '$200.00 due', exact: true }).waitFor()
      assert.equal(await page.getByText('$200.00 due', { exact: true }).count(), 1, 'Due balance is not repeated')
      assert.equal(await page.getByText(/Next payment/).count(), 0)
      params.delete('student'); params.set('view', 'parent'); params.set('portal', 'billing')
      await page.goto(`${base}?${params}`)
      await page.getByRole('heading', { name: '$200.00 due', exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Pay $200', exact: true }).count(), 1, 'Parent can pay their own invoice')
      assert.equal(await page.getByRole('button', { name: 'View invoice DEMO-1004', exact: true }).count(), 0, 'Other payer invoice stays outside parent scope')
      assert.deepEqual(errors, []); assert.deepEqual(apis, [])
      console.log(`PASS billing ${version || 'v1'} ${width}px: balances, unified itemized invoice, uploaded logo, PDF, payment cancel, atomic Pay all and paid state`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })