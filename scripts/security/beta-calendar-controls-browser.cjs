/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional UI checks. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:3231'
assert.match(base, /^http:\/\/127\.0\.0\.1:/)

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1100 } })
      page.setDefaultTimeout(30000)
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.goto(`${base}/odeon-demo?screen=calendar`)
      await page.getByLabel('View by', { exact: true }).waitFor()
      const heading = await page.getByRole('heading', { name: 'Academy calendar', exact: true }).boundingBox()
      const addBooking = await page.getByRole('button', { name: 'Add booking', exact: true }).boundingBox()
      const viewBy = await page.getByRole('group', { name: 'View by', exact: true }).boundingBox()
      const staffFilter = await page.getByRole('button', { name: 'Staff: All', exact: true }).boundingBox()
      assert.ok(Math.abs(heading.y - addBooking.y) < 8, 'Add booking stays at page-header level')
      assert.ok(addBooking.x > heading.x + heading.width, 'Add booking is right of the title')
      assert.ok(Math.abs(viewBy.x - staffFilter.x) < 1 && Math.abs(heading.x - viewBy.x) < 1, 'Title, view selector and filters share the left edge')
      const date = page.getByLabel('Calendar date', { exact: true })
      assert.equal(await date.evaluate(element => element.parentElement.parentElement.parentElement.parentElement === Array.from(document.querySelectorAll('button')).find(button => button.textContent.trim() === 'Staff: All')?.parentElement?.parentElement), true, 'Date navigation lives in the filters row')
      if (width === 1440) {
        const dateBounds = await date.boundingBox()
        assert.ok(Math.abs(dateBounds.y + dateBounds.height / 2 - staffFilter.y - staffFilter.height / 2) < 2, 'Date and filters are centered on the same desktop row')
      }
      const checkbox = page.getByRole('checkbox', { name: 'Show unavailable time', exact: true })
      const alignment = await checkbox.evaluate(element => {
        const input = element.getBoundingClientRect(), text = element.nextElementSibling.getBoundingClientRect()
        return { inputCenter: input.y + input.height / 2, textCenter: text.y + text.height / 2, sameLine: input.right <= text.left }
      })
      assert.ok(alignment.sameLine && Math.abs(alignment.inputCenter - alignment.textCenter) < 1, 'Shared checkbox and label are horizontally centered')
      const selectedSegment = page.getByRole('group', { name: 'Calendar range', exact: true }).locator('button[aria-pressed="true"]')
      assert.deepEqual(await selectedSegment.evaluate(element => {
        const style = getComputedStyle(element)
        return [style.borderTopWidth, style.borderRightWidth, style.borderBottomWidth, style.borderLeftWidth]
      }), ['1px', '1px', '1px', '1px'], 'Selected segment has a complete border')
      assert.ok(await page.locator('[data-calendar-grid] strong').count() > 0)
      await page.getByRole('button', { name: 'Staff: All', exact: true }).click()
      const staff = page.getByRole('group', { name: 'Staff filters' })
      await staff.getByRole('checkbox').nth(1).check()
      await staff.getByRole('checkbox').nth(2).check()
      assert.equal(await page.locator('[data-resource-column]').count(), 2)
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: /^Staff:/ }).click()
      await staff.getByRole('checkbox').nth(1).uncheck()
      await staff.getByRole('checkbox').nth(2).uncheck()
      await page.keyboard.press('Escape')
      assert.equal(await page.getByRole('button', { name: 'Clear filters', exact: true }).count(), 0)
      const perspective = page.getByRole('group', { name: 'View by', exact: true })
      for (const name of ['Room', 'Service', 'Teacher']) {
        await perspective.getByRole('button', { name, exact: true }).click()
        assert.equal(await perspective.getByRole('button', { name, exact: true }).getAttribute('aria-pressed'), 'true')
        if (name === 'Room') {
          const rooms = await page.locator('[data-resource-column]').evaluateAll(elements => elements.map(element => element.getAttribute('data-resource-column')))
          assert.ok(rooms.includes('Carole King') && rooms.includes('Kids n Keys') && rooms.includes('Taylor Swift'), 'Supplied room names are calendar resources')
          assert.ok(!rooms.some(room => /^Studio \d+$/.test(room)), 'Placeholder studio names are removed')
          await page.screenshot({ path: `/tmp/odeon-rooms-${width}.png`, fullPage: true })
        }
      }
      const range = page.getByRole('group', { name: 'Calendar range', exact: true })
      await range.getByRole('button', { name: 'Week', exact: true }).click()
      await page.getByLabel('Week teacher', { exact: true }).waitFor()
      assert.equal(await page.getByLabel('Week teacher', { exact: true }).inputValue(), '', 'Week defaults to all teachers, not the first teacher')
      assert.equal(await page.locator('[data-resource-column]').count(), 7, 'All week retains seven day columns')
      assert.ok(await page.locator('[data-booking-id]').count() > 10, 'All week includes multiple teachers')
      assert.equal(await page.getByRole('button', { name: 'Group: All', exact: true }).count(), 0, 'Group is not a redundant service filter')
      await page.getByRole('button', { name: 'Service: All', exact: true }).click()
      const serviceFilter = page.getByRole('group', { name: 'Service filters', exact: true })
      await serviceFilter.getByRole('checkbox', { name: 'Band', exact: true }).check()
      await page.keyboard.press('Escape')
      assert.ok(await page.locator('[data-booking-id]').count() > 0, 'Band can be seen across the week without choosing a teacher')
      await page.screenshot({ path: `/tmp/odeon-week-band-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Service: Band', exact: true }).click()
      await serviceFilter.getByRole('checkbox', { name: 'All service', exact: true }).check()
      await page.keyboard.press('Escape')
      await page.screenshot({ path: `/tmp/odeon-week-all-${width}.png`, fullPage: true })
      await page.getByLabel('Week teacher', { exact: true }).selectOption({ index: 1 })
      assert.ok(await page.locator('[data-booking-id]').count() > 0, 'A single-resource week remains available')
      await range.getByRole('button', { name: 'Day', exact: true }).click()
      const blocks = await page.locator('[data-booking-id]').evaluateAll(elements => elements.map(element => ({ service: element.querySelector('strong')?.textContent, color: element.style.getPropertyValue('--calendar-student-surface') })))
      const guitar = blocks.filter(block => block.service === 'Guitar')
      assert.ok(guitar.length > 1, 'Multiple Guitar bookings are visible')
      assert.equal(new Set(guitar.map(block => block.color)).size, 1, 'Guitar has one consistent color')
      await page.locator('[data-booking-id]').first().click()
      await page.getByRole('button', { name: 'View profile', exact: true }).click()
      const profile = page.getByRole('dialog', { name: 'Family workspace V3', exact: true })
      await profile.waitFor()
      await profile.getByRole('button', { name: 'Close', exact: true }).click()
      await profile.waitFor({ state: 'hidden' })
      assert.equal(await profile.count(), 0)
      assert.ok(page.url().includes('screen=calendar'))
      await page.getByLabel('Calendar date', { exact: true }).fill('2026-11-05')
      await page.getByLabel('Calendar date', { exact: true }).fill('2026-11-04')
      await page.getByRole('button', { name: 'Add booking', exact: true }).click()
      const modal = page.getByRole('dialog', { name: 'Add booking', exact: true })
      await modal.waitFor()
      assert.equal(await modal.evaluate(element => element.parentElement.parentElement === document.body), true, 'Shared modal portals to body')
      const size = await modal.boundingBox()
      await modal.getByRole('button', { name: 'Choose Band rehearsal', exact: true }).click()
      await modal.getByLabel('Duration', { exact: true }).selectOption('90')
      assert.equal((await modal.boundingBox()).height, size.height)
      assert.equal(await modal.getByLabel('Student', { exact: true }).count(), 0)
      await page.keyboard.press('Escape')
      assert.equal(await modal.count(), 0)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      assert.deepEqual(errors, [])
      await page.screenshot({ path: `/tmp/odeon-calendar-controls-${width}.png`, fullPage: true })
      console.log(`PASS ${width}: multi-select, v3 profile, date picker, shared booking modal, variable band length, no overflow/errors`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })