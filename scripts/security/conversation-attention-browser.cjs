/* eslint-disable @typescript-eslint/no-require-imports -- Optional isolated browser validation. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const templateModule = { exports: {} }
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../../lib/headliner-email-templates.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module: templateModule, exports: templateModule.exports })

;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      const errors = []; const sends = []
      page.on('pageerror', error => errors.push(error.message))
      const people = ['Alex', 'Blair', 'Casey'].map((name, index) => ({ id: `person:${index}`, name, email: `${name.toLowerCase()}@example.com`, phone: `+1202555010${index}`, student: '', stage: '', profileType: 'contact', profileId: `${index}`, smsContactId: `${index}` }))
      let smsRead = false; let replied = false
      const email = () => ({ id: 'email:box:one:person:1', contactId: people[1].id, name: 'Blair', email: people[1].email, phone: people[1].phone, initials: 'B', student: '', stage: '', interest: '', nextAction: '', note: '', channel: 'email', subject: 'Lessons', mailboxId: 'box', providerThreadId: 'one', unread: true, messages: [{ id: 'email-one', channel: 'email', direction: 'inbound', unread: true, body: 'Can we start lessons?', time: 'Today', timestamp: '2026-10-19T12:00:00Z' }, ...(replied ? [{ id: 'sent', channel: 'email', direction: 'outbound', body: 'Yes', timestamp: '2026-10-19T13:00:00Z', time: 'Now' }] : [])] })
      await page.context().route('**/api/**', route => {
        const request = route.request(); const url = new URL(request.url())
        const fulfill = body => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) })
        if (url.pathname === '/api/conversations') return fulfill({ people })
        if (url.pathname === '/api/communications/senders') return fulfill({ senders: [{ id: 'office@example.com', email: 'office@example.com', name: 'Music Academy', mine: false }] })
        if (url.pathname === '/api/conversations/templates') return fulfill({ templates: templateModule.exports.headlinerEmailTemplates })
        if (url.pathname === '/api/conversations/signature') return fulfill({ company: 'Music Academy', phone: '+12025550199', logoUrl: 'https://assets.example.com/logo.png' })
        if (url.pathname === '/api/inbox') {
          if (request.method() === 'PATCH') { smsRead = true; return fulfill({ success: true }) }
          return fulfill([0, 2].map(index => ({ thread_key: `sms-${index}`, contact_id: `${index}`, other_phone: people[index].phone, display_name: people[index].name, profile_type: 'contact', profile_id: `${index}`, has_unread: index === 0 && !smsRead, messages: [{ id: `sms-${index}`, direction: 'inbound', body: 'Question', status: index === 0 && !smsRead ? 'received' : 'read', created_at: '2026-10-19T11:00:00Z' }] })))
        }
        if (url.pathname === '/api/conversations/email') {
          if (request.method() === 'POST') { sends.push(request.postDataJSON()); replied = true; return fulfill({ id: 'sent' }) }
          if (!url.searchParams.has('mailbox')) return fulfill({ mailboxes: [{ id: 'box', email: 'office@example.com', canSend: true }] })
          return fulfill({ threads: url.searchParams.has('summary') || url.searchParams.get('person') === people[1].id ? [email()] : [], nextCursor: null })
        }
        return fulfill([])
      })
      await page.goto(process.env.ATTENTION_REVIEW_URL || 'http://127.0.0.1:3111')
      const row = name => page.getByRole('row').filter({ has: page.getByRole('button', { name: `Open conversation with ${name}`, exact: true }) })
      const background = name => row(name).evaluate(node => getComputedStyle(node).backgroundColor)
      await row('Alex').getByRole('img', { name: 'Unread and unattended message', exact: true }).waitFor()
      await row('Blair').getByRole('img', { name: 'Unread and unattended message', exact: true }).waitFor()
      await row('Casey').getByRole('img', { name: 'Unattended message', exact: true }).waitFor()
      assert.equal(await background('Alex'), 'rgb(240, 248, 250)')
      assert.notEqual(await background('Casey'), 'rgb(240, 248, 250)')
      await page.screenshot({ path: `/tmp/pulse-attention-${width}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Open conversation with Alex', exact: true }).click()
      await page.getByRole('button', { name: 'Back to Conversations', exact: true }).click()
      await row('Alex').getByRole('img', { name: 'Unattended message', exact: true }).waitFor()
      assert.notEqual(await background('Alex'), 'rgb(240, 248, 250)')
      await page.getByRole('button', { name: 'Open conversation with Blair', exact: true }).click()
      await page.getByRole('button', { name: 'Email', exact: true }).click()
      await page.getByRole('region', { name: 'Email reader', exact: true }).getByText('Can we start lessons?', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Back to Conversations', exact: true }).click()
      await row('Blair').getByRole('img', { name: 'Unattended message', exact: true }).waitFor()
      assert.notEqual(await background('Blair'), 'rgb(240, 248, 250)')
      await page.getByRole('button', { name: 'Open conversation with Blair', exact: true }).click()
      await page.getByRole('button', { name: 'New email', exact: true }).click()
      const composer = page.getByRole('region', { name: 'Email composer', exact: true })
      const fields = composer.getByLabel('Email fields', { exact: true })
      const labels = fields.locator(':scope > span, :scope > label')
      const labelStyles = await labels.evaluateAll(nodes => nodes.map(node => { const s = getComputedStyle(node); return [s.fontSize, s.fontWeight, s.color, s.fontFamily].join('|') }))
      assert.equal(new Set(labelStyles).size, 1)
      const subjectField = await composer.getByRole('textbox', { name: 'Email subject', exact: true }).boundingBox()
      const subjectLabel = await fields.locator('label').boundingBox()
      assert.ok(subjectField.x > subjectLabel.x && Math.abs(subjectField.y + subjectField.height / 2 - subjectLabel.y - subjectLabel.height / 2) < 2)
      const body = composer.getByRole('textbox', { name: 'Email body', exact: true })
      assert.equal(await body.getAttribute('aria-placeholder'), 'Write your message…')
      const signatureBox = await composer.getByLabel('Your email signature', { exact: true }).boundingBox()
      const areaBox = await body.locator('..').boundingBox()
      assert.ok(Math.abs(signatureBox.y + signatureBox.height - areaBox.y - areaBox.height) < 2)
      assert.ok(await composer.evaluate(node => node.scrollWidth <= node.clientWidth))
      await page.screenshot({ path: `/tmp/pulse-composer-layout-${width}.png`, fullPage: true })
      await composer.getByRole('button', { name: 'Use template', exact: true }).click()
      const library = page.getByRole('dialog', { name: 'Email templates', exact: true })
      const gallery = library.getByRole('region', { name: 'Template gallery' })
      assert.equal(await gallery.getByRole('button').count(), 5)
      assert.equal(await library.getByText(/Shared workspace templates|Write from scratch/).count(), 0)
      const first = gallery.getByRole('button', { name: '2-Day Contact', exact: true })
      assert.equal(await first.getAttribute('aria-pressed'), 'true')
      assert.equal(await library.getByRole('button', { name: 'Use template', exact: true }).isEnabled(), true)
      assert.equal(await first.evaluate(node => getComputedStyle(node).backgroundColor), 'rgb(246, 248, 248)')
      const box = await library.boundingBox()
      const header = library.getByRole('heading', { name: 'Email templates', exact: true })
      assert.equal(await header.evaluate(node => getComputedStyle(node).fontSize), '24px')
      assert.ok(await header.evaluate(node => node.parentElement.parentElement.parentElement.getBoundingClientRect().height) <= 60)
      await gallery.getByRole('button', { name: '5-Day Contact', exact: true }).click()
      await library.getByRole('button', { name: 'Use template', exact: true }).click()
      const warning = composer.getByRole('alert')
      await warning.getByText(/Complete these placeholders/).waitFor()
      assert.equal(await warning.evaluate(node => getComputedStyle(node).backgroundColor), 'rgb(254, 247, 231)')
      assert.equal(await warning.evaluate(node => getComputedStyle(node).fontSize), '16px')
      assert.equal(await warning.evaluate(node => getComputedStyle(node).alignItems), 'center')
      assert.ok(await warning.evaluate(node => node.scrollWidth <= node.clientWidth))
      const dismissBox = await warning.getByRole('button', { name: 'Dismiss placeholder warning', exact: true }).boundingBox()
      assert.ok(dismissBox.width >= 44 && dismissBox.height >= 44)
      const warningIcon = await warning.locator(':scope > svg').boundingBox()
      assert.ok(Math.abs(warningIcon.y + warningIcon.height / 2 - dismissBox.y - dismissBox.height / 2) <= 1)
      await page.screenshot({ path: `/tmp/pulse-banner-${width}.png`, fullPage: true })
      assert.equal(await warning.evaluate(node => !!node.closest('[aria-label="Message input area"]')), false)
      const subjectBox = await composer.getByRole('textbox', { name: 'Email subject', exact: true }).boundingBox()
      const warningBox = await warning.boundingBox()
      const inputBox = await composer.getByLabel('Message input area', { exact: true }).boundingBox()
      assert.ok(subjectBox.y < warningBox.y && warningBox.y < inputBox.y)
      assert.equal(await composer.getByText(/applied\./).count(), 0)
      assert.equal(await composer.getByText(/Set up your public phone/).count(), 0)
      const undoBox = await composer.getByRole('button', { name: 'Undo template', exact: true }).boundingBox()
      const useBox = await composer.getByRole('button', { name: 'Use template', exact: true }).boundingBox()
      assert.ok(undoBox.x < useBox.x && Math.abs(undoBox.y - useBox.y) < 8)
      await warning.getByRole('button', { name: 'Dismiss placeholder warning', exact: true }).click()
      assert.equal(await composer.getByRole('alert').count(), 0)
      assert.equal(await composer.getByRole('button', { name: 'Send email', exact: true }).isDisabled(), true)
      await composer.getByRole('button', { name: 'Use template', exact: true }).click()
      await library.waitFor()
      await gallery.getByRole('button', { name: 'META Lead / Generic Email', exact: true }).click()
      await library.getByRole('button', { name: 'Use template', exact: true }).click()
      await library.getByRole('alert').getByText(/This will override your current email draft/).waitFor()
      assert.equal(await library.getByRole('button', { name: 'Insert instead', exact: true }).count(), 0)
      assert.equal((await library.boundingBox()).height, box.height)
      await library.getByRole('button', { name: 'Confirm replace', exact: true }).click()
      assert.doesNotMatch(await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText(), /\[INSTRUMENT\]/)
      await composer.getByRole('button', { name: 'Undo template', exact: true }).click()
      assert.match(await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText(), /\[INSTRUMENT\]/)
      await composer.getByRole('button', { name: 'Use template', exact: true }).click()
      await library.waitFor()
      for (const name of ['5-Day Contact', 'One Week Contact', 'META Lead / Generic Email', 'Create new template']) {
        const option = gallery.getByRole('button', { name, exact: true })
        await option.hover()
        assert.equal(await option.evaluate(node => getComputedStyle(node).backgroundColor), 'rgb(246, 248, 248)')
        await option.click()
        assert.equal(await option.getAttribute('aria-pressed'), 'true')
        assert.equal((await library.boundingBox()).height, box.height)
        assert.equal((await library.boundingBox()).width, box.width)
      }
      await library.getByRole('textbox', { name: 'Template name', exact: true }).fill('2-Day Contact')
      await library.getByRole('textbox', { name: 'Template subject', exact: true }).fill('A custom subject')
      await library.getByRole('textbox', { name: 'Template message', exact: true }).fill('A custom message')
      await library.getByRole('button', { name: 'Save template', exact: true }).click()
      await library.getByRole('alert').getByText('A template with this name already exists.').waitFor()
      assert.equal((await library.boundingBox()).height, box.height)
      await library.getByRole('textbox', { name: 'Template name', exact: true }).fill('Custom follow-up')
      await library.getByRole('button', { name: 'Save template', exact: true }).click()
      await gallery.getByRole('button', { name: 'Custom follow-up', exact: true }).waitFor()
      assert.equal((await library.boundingBox()).height, box.height)
      assert.equal(await gallery.getByRole('button', { name: 'Custom follow-up', exact: true }).getAttribute('aria-pressed'), 'true')
      assert.ok(await library.evaluate(node => node.scrollWidth <= node.clientWidth))
      await page.screenshot({ path: `/tmp/pulse-template-modal-${width}.png`, fullPage: true })
      await page.keyboard.press('Escape')
      await library.waitFor({ state: 'detached' })
      await composer.getByRole('button', { name: 'Use template', exact: true }).click()
      await library.waitFor()
      assert.equal(await first.getAttribute('aria-pressed'), 'true')
      await gallery.getByRole('button', { name: 'Custom follow-up', exact: true }).click()
      await library.getByRole('button', { name: 'Use template', exact: true }).click()
      await library.getByRole('button', { name: 'Confirm replace', exact: true }).click()
      const signature = composer.getByLabel('Your email signature', { exact: true })
      await signature.getByText('+12025550199', { exact: false }).waitFor()
      assert.equal(await signature.locator('img').getAttribute('src'), 'https://assets.example.com/logo.png')
      await composer.getByRole('button', { name: 'Send email', exact: true }).click()
      await page.getByText('Email sent.', { exact: true }).waitFor()
      assert.equal(sends.length, 1)
      assert.match(sends[0].html, /https:\/\/assets.example.com\/logo.png/)
      assert.match(sends[0].body, /Music Academy/)
      assert.match(sends[0].body, /\+12025550199/)
      await page.getByRole('button', { name: 'Back to Conversations', exact: true }).click()
      assert.equal(await row('Blair').getByRole('img', { name: /unattended message/i }).count(), 0, 'Outbound reply clears unattended state')
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}px: attention states; first template default; five options; hover/active colors; compact 24px title; fixed modal size; duplicate validation; create/apply; signed email`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })