/* eslint-disable @typescript-eslint/no-require-imports -- External local browser runner; no deliveries. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    for (const width of [1440, 900, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      const errors = [], requests = []
      page.on('pageerror', error => errors.push(error.message))
      page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) requests.push(request.url()) })
      await page.goto(`${process.env.FAMILY_LAB_URL || 'http://127.0.0.1:3198'}/lists`)
      const contacts = page.getByRole('table', { name: 'Contacts', exact: true })
      const leads = page.getByRole('table', { name: 'Leads', exact: true })
      await contacts.getByText('Emma Smith', { exact: true }).waitFor()
      await contacts.getByRole('checkbox', { name: 'Select Jane Smith', exact: true }).check()
      await page.getByRole('status').filter({ hasText: 'Selected: emma,noah / Opened:' }).waitFor()
      await contacts.getByRole('button', { name: 'Collapse Jane Smith' }).click()
      assert.equal(await contacts.getByText('Emma Smith', { exact: true }).count(), 0)
      await contacts.getByRole('button', { name: 'Expand Jane Smith' }).press('Enter')
      await contacts.getByRole('checkbox', { name: 'Select Emma Smith' }).uncheck()
      await contacts.getByRole('button', { name: 'Emma Smith', exact: true }).click()
      await page.getByRole('status').filter({ hasText: 'Selected: noah / Opened: emma' }).waitFor()
      await page.getByRole('textbox', { name: 'Filter' }).fill('Emma')
      assert.equal(await contacts.getByText('Noah Smith', { exact: true }).count(), 0)
      await contacts.getByRole('checkbox', { name: 'Select Jane Smith', exact: true }).check()
      await page.getByRole('status').filter({ hasText: 'Selected: emma,noah' }).waitFor()
      await contacts.getByRole('checkbox', { name: 'Select Jane Smith', exact: true }).uncheck()
      await page.getByRole('status').filter({ hasText: 'Selected: noah / Opened: emma' }).waitFor()
      await contacts.getByRole('checkbox', { name: 'Select Jane Smith', exact: true }).check()
      await page.getByRole('status').filter({ hasText: 'Selected: emma,noah' }).waitFor()
      assert.equal(await leads.getByRole('checkbox').count(), 4)
      assert.equal(await leads.getByRole('checkbox', { name: 'Select Emma Smith' }).isDisabled(), true)
      await leads.getByText('Drums', { exact: true }).waitFor()
      await leads.getByText('Noah Smith', { exact: true }).click()
      await page.getByRole('status').filter({ hasText: 'Opened: lead' }).waitFor()
      await leads.getByRole('button', { name: 'Collapse Jane Smith' }).click()
      assert.equal(await leads.getByText('Noah Smith', { exact: true }).count(), 0)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      assert.deepEqual(errors, [])
      assert.deepEqual(requests, [])
      await page.screenshot({ path: `/tmp/pulse-family-lists-${width}.png`, fullPage: true })
      console.log(`PASS: Contacts/Leads hierarchy, selection, filtering, keyboard disclosure, profile handoff, no API/page overflow at ${width}px`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })