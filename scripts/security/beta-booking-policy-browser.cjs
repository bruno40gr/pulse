/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional UI verification. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:3231'
assert.match(base, /^http:\/\/127\.0\.0\.1:/)
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } })
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.goto(`${base}/odeon-demo?screen=calendar`)
      const add = page.getByRole('button', { name: 'Add booking', exact: true })
      await add.click()
      const modal = page.getByRole('dialog')
      const initial = await modal.boundingBox()
      await modal.getByRole('button', { name: 'Choose Lesson', exact: true }).click()
      assert.deepEqual(await modal.getByLabel('Duration', { exact: true }).locator('option').evaluateAll(options => options.map(option => option.value)), ['30', '60'])
      assert.equal(await modal.getByLabel('Student', { exact: true }).count(), 1)
      await modal.getByRole('button', { name: 'Back', exact: true }).click()
      await modal.getByRole('button', { name: 'Choose Studio booking', exact: true }).click()
      assert.equal(await modal.getByLabel('Student', { exact: true }).count(), 0)
      const expanded = await modal.boundingBox()
      assert.equal(initial.height, expanded.height)
      assert.equal(initial.width, expanded.width)
      await modal.getByLabel('Booking name', { exact: true }).fill(`Room only ${width}`)
      await modal.getByLabel('Booking date', { exact: true }).fill('2026-11-04')
      await modal.getByLabel('Start time', { exact: true }).selectOption('09:00')
      await modal.getByLabel('Room', { exact: true }).selectOption({ label: 'Studio 1 · capacity 1' })
      await modal.getByRole('button', { name: 'Add booking', exact: true }).click()
      await modal.waitFor({ state: 'detached' })
      await add.click()
      await modal.getByRole('button', { name: 'Choose Block / unavailable', exact: true }).click()
      await modal.getByLabel('Block reason', { exact: true }).fill(`Blocked slot ${width}`)
      await modal.getByLabel('Booking date', { exact: true }).fill('2026-11-04')
      await modal.getByLabel('Start time', { exact: true }).selectOption('10:00')
      await modal.getByLabel('Room (optional)', { exact: true }).selectOption({ label: 'Studio 1 · capacity 1' })
      await modal.getByRole('button', { name: 'Save block', exact: true }).click()
      await modal.waitFor({ state: 'detached' })
      await page.getByLabel('View by', { exact: true }).selectOption('room')
      await page.getByLabel('Calendar date', { exact: true }).fill('2026-11-04')
      await page.getByLabel('Show unavailable time', { exact: true }).uncheck()
      const blocked = page.getByRole('button', { name: 'Unavailable Studio 1, 2026-11-04 at 10:00', exact: true })
      assert.equal(await blocked.isDisabled(), true)
      const target = page.getByRole('button', { name: 'Book Studio 1, 2026-11-04 at 11:00', exact: true })
      await target.focus(); await page.keyboard.press('Enter')
      await modal.getByRole('button', { name: 'Choose Studio booking', exact: true }).click()
      assert.equal(await modal.getByLabel('Booking date', { exact: true }).inputValue(), '2026-11-04')
      assert.equal(await modal.getByLabel('Start time', { exact: true }).inputValue(), '11:00')
      assert.equal(await modal.getByLabel('Room', { exact: true }).inputValue(), 'Studio 1')
      await page.screenshot({ path: `/tmp/odeon-booking-modal-${width}.png` })
      await page.keyboard.press('Escape')
      if (width === 1440) {
        const last = page.getByRole('button', { name: 'Book Studio 1, 2026-11-04 at 11:30', exact: true })
        await target.scrollIntoViewIfNeeded()
        const a = await target.boundingBox(), b = await last.boundingBox()
        await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
        await page.mouse.down(); await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 5 }); await page.mouse.up()
        await modal.getByRole('button', { name: 'Choose Studio booking', exact: true }).click()
        assert.equal(await modal.getByLabel('Duration', { exact: true }).inputValue(), '60')
        await page.keyboard.press('Escape')
      }
      await page.reload()
      await add.waitFor()
      const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('odeon-demo-workspace-v1') || 'null'))
      // Inspect the actual persistence key without depending on its version.
      const state = saved || await page.evaluate(() => Object.values(sessionStorage).map(value => { try { return JSON.parse(value) } catch { return null } }).find(value => value?.snapshot?.data?.demoSchool))
      assert.ok(state.snapshot.data.calendarBookings.some(item => item.title === `Room only ${width}`))
      assert.ok(state.setup.resourceBlocks.some(item => item.values.name === `Blocked slot ${width}`))
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}: stable dialog, optional participants, saved room/block, hidden enforcement, contextual slots, persistence, no overflow/errors`)
      await page.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })