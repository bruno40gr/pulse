/* eslint-disable @typescript-eslint/no-require-imports -- Optional standalone preview runner. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    for (const [width, height] of [[1440,900],[820,1180],[390,844],[320,568],[844,390]]) {
      const page = await browser.newPage({ viewport: { width, height } })
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      const button = (root, name) => root.getByRole('button', { name, exact: true })
      const action = name => button(page, name)
      const noOverflow = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`)
      await page.goto(process.env.WORKSPACE_REVIEW_URL || 'http://127.0.0.1:3101')
      assert.equal(await page.getByRole('navigation', { name: 'Workspace breadcrumbs' }).count(), 0)
      assert.equal(await page.getByText('Conversations prototype · sample people and messages only.', { exact: true }).count(), 0)
      await noOverflow()
      const search = page.getByRole('searchbox', { name: 'Search communications', exact: true })
      const filters = page.getByRole('region', { name: 'Conversation filters', exact: true })
      const filterBox = await filters.boundingBox()
      const tableBox = await page.getByRole('complementary', { name: 'Contacts', exact: true }).evaluate(node => {
        const panel = node.parentElement
        const bounds = panel.getBoundingClientRect()
        return { width: bounds.width, parentWidth: panel.parentElement.parentElement.clientWidth - parseFloat(getComputedStyle(panel.parentElement.parentElement).paddingLeft) - parseFloat(getComputedStyle(panel.parentElement.parentElement).paddingRight), top: bounds.top, containsFilters: panel.contains(document.querySelector('[aria-label="Conversation filters"]')) }
      })
      assert.ok(Math.abs(tableBox.width - tableBox.parentWidth) < 2, 'Conversation table must fill available width')
      assert.equal(tableBox.containsFilters, false, 'Filters must be outside the conversation table panel')
      assert.ok(filterBox.y + filterBox.height < tableBox.top, 'Filters must sit above the table with spacing')
      await search.fill('Jamie')
      assert.equal(await action('Open conversation with Morgan Rivera').count(), 0)
      await action('Open conversation with Alex Chen').waitFor()
      await search.fill('')
      await page.getByLabel('From date', { exact: true }).fill('2099-01-01')
      await page.getByRole('status').getByText('No conversations match your filters.', { exact: true }).waitFor()
      await action('Clear filters').click()
      await action('Open conversation with Alex Chen').click(); await action('Email').click()
      assert.equal(await page.getByRole('navigation', { name: 'Workspace breadcrumbs' }).count(), 0)
      const title = page.getByRole('heading', { name: 'Alex Chen', exact: true })
      const lead = page.getByRole('button', { name: 'Open lead for Alex Chen', exact: true })
      assert.ok(await title.evaluate((node) => node.parentElement.contains(document.querySelector('[aria-label="Open lead for Alex Chen"]'))))
      await lead.waitFor()
      await action('Read email: Piano lessons for Jamie').click(); await action('Reply').click()
      const composer = page.getByRole('region', { name: 'Email composer', exact: true })
      await composer.getByRole('textbox', { name: 'Email body', exact: true }).fill('Saved when switching to SMS')
      assert.equal(await page.getByRole('region', { name: 'Email reader', exact: true }).evaluate(panel => getComputedStyle(panel.querySelector('[aria-label="Email composer"]').parentElement.parentElement).borderTopWidth), '1px')
      await action('SMS').click()
      assert.equal(await action('Templates').count(), 0)
      assert.equal(await action('Use template').count(), 0)
      await page.getByRole('status').getByText('Email saved as draft.', { exact: true }).waitFor()
      await page.getByRole('textbox', { name: 'SMS message', exact: true }).fill('Phone preview text')
      const phone = page.getByRole('region', { name: 'SMS phone preview for Alex Chen', exact: true })
      await phone.getByText('Phone preview text', { exact: true }).waitFor()
      if (width >= 1000) {
        const pane = page.getByRole('complementary', { name: 'SMS preview pane', exact: true })
        const previewBox = await pane.boundingBox()
        const inputBox = await page.getByRole('textbox', { name: 'SMS message', exact: true }).boundingBox()
        assert.ok(previewBox.x >= inputBox.x + inputBox.width, 'Phone preview must be to the right of SMS input')
        assert.equal(await pane.evaluate(node => getComputedStyle(node).borderLeftWidth), '1px')
        const workspaceBox = await page.getByLabel('SMS workspace', { exact: true }).boundingBox()
        assert.ok(Math.abs(previewBox.width / workspaceBox.width - 0.7) < 0.005, 'SMS split must be 30/70')
      }
      await phone.scrollIntoViewIfNeeded(); await noOverflow()
      await action('Send').scrollIntoViewIfNeeded(); assert.ok(await action('Send').isVisible())
      await action('Email').click(); await action('Read email: Piano lessons for Jamie').click(); await action('Continue draft').click()
      assert.equal(await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText(), 'Saved when switching to SMS')
      await page.getByRole('button', { name: 'Back to Communications', exact: true }).click()
      await action('New message').click()
      const modal = page.getByRole('dialog', { name: 'New message', exact: true })
      await modal.getByRole('heading', { name: 'Send a new message', exact: true }).waitFor()
      const smsOption = await button(modal, 'SMS').boundingBox()
      const emailOption = await button(modal, 'Email').boundingBox()
      assert.equal(smsOption.y, emailOption.y)
      assert.ok(Math.abs(smsOption.width - emailOption.width) < 1)
      assert.equal(await modal.getByRole('button').count(), 3)
      await button(modal, 'SMS').click()
      for (const [query, name] of [['Alex', 'Alex Chen'], ['Morgan', 'Morgan Rivera']]) {
        await modal.getByRole('textbox', { name: 'Search SMS recipients', exact: true }).fill(query)
        await button(modal, `Add ${name} to SMS recipients`).click()
      }
      await button(modal, 'Write SMS (2)').click()
      await modal.waitFor({ state: 'detached' })
      await page.getByRole('heading', { name: 'Write a text message', exact: true }).waitFor()
      const newSms = page.getByRole('region', { name: 'New SMS composer', exact: true })
      assert.equal(await action('Email').count(), 0)
      const phones = newSms.getByRole('region', { name: /^SMS phone preview for / })
      assert.equal(await phones.count(), 1, 'Multi-recipient SMS must show exactly one smartphone')
      assert.ok(await phones.isVisible())
      assert.equal(await newSms.getByRole('button', { name: /^(Hide phone preview|Phone preview)$/ }).count(), 0)
      const messageActions = newSms.getByRole('group', { name: 'Text message actions', exact: true })
      assert.equal(await button(messageActions, 'Edit recipients').count(), 1)
      assert.equal(await button(messageActions, 'Discard text message').count(), 1)
      const actionsBox = await messageActions.boundingBox()
      const workspaceBox = await newSms.getByLabel('SMS workspace', { exact: true }).boundingBox()
      assert.ok(actionsBox.y + actionsBox.height <= workspaceBox.y, 'Discard and edit must be above the SMS workspace')
      await page.screenshot({ path: `/tmp/pulse-single-sms-${width}.png`, fullPage: true })
      const newSmsInput = newSms.getByRole('textbox', { name: 'SMS message', exact: true })
      await newSmsInput.fill('A separate message for each person')
      await action('Back to Communications').click()
      const leaveSms = page.getByRole('dialog', { name: 'Discard message and go back', exact: true })
      await leaveSms.getByText('Going back to conversations will discard the current message', { exact: true }).waitFor()
      await noOverflow()
      await button(leaveSms, 'Cancel').click()
      assert.equal(await newSmsInput.inputValue(), 'A separate message for each person')
      await action('Back to Communications').click()
      await page.keyboard.press('Escape')
      assert.equal(await newSmsInput.inputValue(), 'A separate message for each person')

      await noOverflow()
      await newSms.getByRole('button', { name: 'Send', exact: true }).scrollIntoViewIfNeeded()
      assert.ok(await newSms.getByRole('button', { name: 'Send', exact: true }).isEnabled())
      await newSms.getByRole('button', { name: 'Edit recipients', exact: true }).click()
      const editSms = page.getByRole('dialog', { name: 'Edit SMS recipients', exact: true })
      await button(editSms, 'Remove Alex Chen from SMS recipients').click()
      await button(editSms, 'Remove Morgan Rivera from SMS recipients').click()
      await button(editSms, 'Done').click()
      assert.equal(await phones.count(), 1, 'Keep one smartphone even with no recipients selected')
      assert.ok(await phones.isVisible())
      assert.ok(await newSms.getByRole('button', { name: 'Send', exact: true }).isDisabled())
      assert.equal(await newSmsInput.inputValue(), 'A separate message for each person')
      await noOverflow()
      await page.screenshot({ path: `/tmp/pulse-new-sms-${width}.png`, fullPage: true })
      await button(newSms, 'Discard text message').click()
      const discardSms = page.getByRole('dialog', { name: 'Discard text message', exact: true })
      await button(discardSms, 'Keep message').click()
      assert.equal(await newSmsInput.inputValue(), 'A separate message for each person')
      await button(newSms, 'Discard text message').click()
      await button(discardSms, 'Discard message').click()
      await page.getByRole('heading', { name: 'Communications', exact: true }).waitFor()
      await page.goBack()
      assert.equal(await page.getByRole('region', { name: 'New SMS composer', exact: true }).count(), 0)
      await action('Back to Communications').click()
      for (const body of ['', '   ', 'Hello']) {
        await action('New message').click()
        await button(modal, 'SMS').click()
        await modal.getByRole('textbox', { name: 'Search SMS recipients', exact: true }).fill('Alex')
        await button(modal, 'Add Alex Chen to SMS recipients').click()
        await modal.getByRole('textbox', { name: 'Search SMS recipients', exact: true }).fill('Morgan')
        await button(modal, 'Add Morgan Rivera to SMS recipients').click()
        await button(modal, 'Write SMS (2)').click()
        await newSmsInput.fill(body)
        await action('Back to Communications').click()
        if (body.trim()) {
          await leaveSms.waitFor()
          await button(leaveSms, 'Continue').click()
        }
        await page.getByRole('heading', { name: 'Communications', exact: true }).waitFor()
        assert.equal(await leaveSms.count(), 0)
        await page.goForward()
        assert.equal(await newSms.count(), 0, 'Leaving discards SMS rather than restoring it through history')
        await action('Back to Communications').click()
      }
      await action('New message').click()
      await button(modal, 'SMS').click()
      await modal.getByRole('textbox', { name: 'Search SMS recipients', exact: true }).fill('Alex')
      await button(modal, 'Add Alex Chen to SMS recipients').click()
      await button(modal, 'Write SMS (1)').click()
      await page.getByRole('heading', { name: 'Alex Chen', exact: true }).waitFor()
      assert.equal(await newSms.count(), 0)
      assert.equal(await action('Edit recipients').count(), 0)
      assert.equal(await action('Discard text message').count(), 0)
      const alexHistory = page.getByRole('region', { name: 'SMS history', exact: true })
      assert.equal(await alexHistory.getByText('Thanks for the email! Tuesdays or Thursdays after 3 would be great. You can text me here too.', { exact: true }).count(), 1)
      assert.equal(await alexHistory.getByText(/Is texting a good way to reach you/).count(), 1)
      assert.ok(await alexHistory.evaluate(node => node.scrollHeight > node.clientHeight))
      await alexHistory.evaluate(node => { node.scrollTop = 0 })
      await noOverflow()
      assert.equal(await page.getByRole('region', { name: /^SMS phone preview for / }).count(), 1)
      await page.screenshot({ path: `/tmp/pulse-personal-sms-${width}.png`, fullPage: true })
      const personalInput = page.getByRole('textbox', { name: 'SMS message', exact: true })
      await personalInput.fill('Following up on our conversation')
      await action('Back to Communications').click()
      assert.equal(await leaveSms.count(), 0, 'Personal conversations retain drafts rather than using bulk discard warning')
      await action('New message').click(); await button(modal, 'SMS').click()
      await modal.getByRole('textbox', { name: 'Search SMS recipients', exact: true }).fill('Alex')
      await button(modal, 'Add Alex Chen to SMS recipients').click()
      await button(modal, 'Write SMS (1)').click()
      assert.equal(await personalInput.inputValue(), 'Following up on our conversation')
      await action('Back to Communications').click()
      await action('New message').click(); await button(modal, 'SMS').click()
      await modal.getByRole('textbox', { name: 'Search SMS recipients', exact: true }).fill('Taylor')
      await button(modal, 'Add Taylor Patel to SMS recipients').click()
      await button(modal, 'Write SMS (1)').click()
      await page.getByRole('heading', { name: 'Taylor Patel', exact: true }).waitFor()
      await page.getByText('No text messages yet. Write one below.', { exact: true }).waitFor()
      assert.equal(await newSms.count(), 0)
      await noOverflow()
      await action('Back to Communications').click()
      await action('New message').click()
      await button(modal, 'Email').click()
      for (const [query, name] of [['Alex', 'Alex Chen'], ['Morgan', 'Morgan Rivera']]) {
        await modal.getByRole('textbox', { name: 'Search To', exact: true }).fill(query)
        await button(modal, `Add ${name} to To`).click()
      }
      await button(modal, 'Write email').click(); await composer.waitFor()
      await page.getByRole('heading', { name: 'New message', exact: true }).waitFor()
      for (const label of ['Email conversations', 'Email reader', 'Previous email context']) assert.equal(await page.getByLabel(label, { exact: true }).count(), 0)
      assert.equal(await action('SMS').count(), 0)
      assert.equal(await page.getByRole('heading', { name: 'Alex Chen', exact: true }).count(), 0)
      await composer.getByRole('textbox', { name: 'Email subject', exact: true }).fill('Class update')
      await composer.getByRole('textbox', { name: 'Email body', exact: true }).fill('Hello everyone')
      await noOverflow()
      await action('Save as draft').click(); await action('Continue draft').click()
      await page.getByRole('heading', { name: 'New message', exact: true }).waitFor()
      assert.equal(await composer.getByRole('textbox', { name: 'Email body', exact: true }).innerText(), 'Hello everyone')
      await action('Send email').scrollIntoViewIfNeeded(); assert.ok(await action('Send email').isVisible())
      await page.screenshot({ path: `/tmp/pulse-v0-clean-compose-${width}.png`, fullPage: true })
      assert.deepEqual(errors, [])
      await page.close()
      console.log(`PASS: ${width}x${height}: responsive rows/search/dates, email-to-SMS draft retention, phone preview, divider, clean multi-recipient compose/resume`)
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })