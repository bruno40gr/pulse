/* eslint-disable @typescript-eslint/no-require-imports -- Local fictional school browser regression. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:3231'
assert.match(base, /^http:\/\/127\.0\.0\.1:/)
;(async()=>{
 const browser=await chromium.launch({channel:'chrome'})
 try { for(const width of [1440,390]) {
  console.log(`START ${width}`)
  const context=await browser.newContext({viewport:{width,height:1000}})
  let page=await context.newPage(); const errors=[]; page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`${base}/odeon-demo?screen=setup&section=teachers`)
  await page.getByRole('button',{name:'Edit Maya Chen',exact:true}).click()
  await page.getByRole('checkbox',{name:'Can cover front desk',exact:true}).check()
  await page.getByRole('checkbox',{name:/^Can perform admin duties/}).check()
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  await page.goto(`${base}/odeon-demo?screen=calendar`)
  console.log('Teacher capabilities saved')
  for(const [path,time] of [['Front desk','14:00'],['Admin','14:30']]) {
   await page.getByRole('button',{name:'Add booking',exact:true}).click()
   const modal=page.getByRole('dialog',{name:'Add booking',exact:true})
   await modal.getByRole('button',{name:`Choose ${path}`,exact:true}).click()
   const dialog=page.getByRole('dialog',{name:'Add booking',exact:true})
   await dialog.getByLabel('Duty location',{exact:true}).selectOption({index:1})
   await dialog.getByLabel('Start time',{exact:true}).selectOption(time)
   await dialog.getByLabel('Duration',{exact:true}).selectOption('30')
   await dialog.getByLabel('Assigned staff',{exact:true}).selectOption({label:'Maya Chen'})
   await dialog.getByLabel('Duty notes',{exact:true}).fill('Coverage and office work')
   await dialog.getByLabel('Repeat',{exact:true}).selectOption('weekly')
   await dialog.getByLabel('Repeat through',{exact:true}).fill('2026-11-18')
   assert.equal(await dialog.getByLabel('Room (optional)',{exact:true}).inputValue(),'')
   console.log(`Saving ${path}`)
   await dialog.getByRole('button',{name:'Save duty',exact:true}).click()
   await dialog.waitFor({state:'hidden'})
  }
  await page.getByRole('checkbox',{name:'Show unavailable time',exact:true}).uncheck()
  assert.match(await page.getByLabel('Staff duty coverage',{exact:true}).innerText(),/Front desk.*Maya Chen/s)
  await page.getByLabel('Calendar date',{exact:true}).fill('2026-11-11')
  const front=page.locator('[data-booking-id]').filter({hasText:'Front desk'}).first()
  await front.click()
  await page.getByRole('button',{name:'Edit duty series',exact:true}).click()
  const edit=page.getByRole('dialog',{name:'Add booking',exact:true})
  await edit.getByLabel('Duty notes',{exact:true}).fill('Updated handover')
  await edit.getByRole('button',{name:'Save duty',exact:true}).click()
  await edit.waitFor({state:'hidden'})
  const persistent=await context.storageState()
  await context.close()
  const fresh=await browser.newContext({viewport:{width,height:1000},storageState:persistent})
  page=await fresh.newPage(); page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`${base}/odeon-demo?screen=calendar`)
  await page.getByLabel('Calendar date',{exact:true}).fill('2026-11-11')
  await page.locator('[data-booking-id]').filter({hasText:'Front desk'}).first().click()
  await page.getByText('Updated handover',{exact:false}).waitFor()
  await page.getByRole('button',{name:'Cancel duty series',exact:true}).click()
  assert.equal(await page.locator('[data-booking-id]').filter({hasText:'Front desk'}).count(),0)
  await page.reload()
  await page.getByLabel('Calendar date',{exact:true}).fill('2026-11-11')
  assert.equal(await page.locator('[data-booking-id]').filter({hasText:'Front desk'}).count(),0)
  assert.ok(await page.locator('[data-booking-id]').filter({hasText:'Admin'}).count()>0)
  await page.screenshot({path:`/tmp/odeon-staff-duties-${width}.png`,fullPage:true})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
  assert.deepEqual(errors,[])
  await fresh.close(); console.log(`PASS ${width}: teacher capability, recurring duties, no room required, visible coverage, series edit/cancel, persistence in fresh browser session`)
 }} finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
