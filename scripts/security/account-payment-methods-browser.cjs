/* eslint-disable @typescript-eslint/no-require-imports -- Local-only fictional billing journeys. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STUDENT_REVIEW_URL || 'http://127.0.0.1:3197/students'
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Local lab required')
;(async () => {
  const browser = await chromium.launch()
  try {
    for (const version of ['', 'v2', 'v3']) for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], apis = []
      page.setDefaultTimeout(10000)
      page.on('pageerror', error => errors.push(error.message))
      await context.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.hostname === 'res.cloudinary.com' && route.request().resourceType() === 'image') return route.continue()
        if (url.origin !== new URL(base).origin) return route.abort()
        if (url.pathname.startsWith('/api/')) {
          const shell = ['/api/account/identity', '/api/account/claim-reminder', '/api/notifications', '/api/leads', '/api/inbox', '/api/inbox/reconcile', '/api/tenant/sync-status']
          if (!shell.includes(url.pathname)) { apis.push(url.pathname); return route.abort() }
          return route.fulfill({ json: url.pathname === '/api/account/identity' ? { fullName: 'Preview staff', firstName: 'Preview', isDemo: true } : { count: 0, notifications: [], unread_count: 0, show: false } })
        }
        return route.continue()
      })
      const params = new URLSearchParams({ prototype: version || 'v1', view: version === 'v3' ? 'quick' : 'staff', account: 'preview:kim', student: 'preview:sophie', section: 'billing' })
      await page.goto(`${base}?${params}`)
      const summary = page.locator('header[aria-label="Billing summary"]')
      await page.getByRole('heading', { name: 'Sophie Kim', exact: true }).waitFor()
      assert.equal(await summary.getByRole('button').count(), 0, 'Child summary has no account link or card management')
      assert.equal(await summary.locator('[data-task-subtitle]').count(), 0, 'No permanent billing handoff message')
      assert.equal(await page.getByRole('button', { name: 'Billing actions', exact: true }).count(), 0)
      assert.equal(await page.getByRole('button', { name: 'View invoice DEMO-1004', exact: true }).count(), 0)
      const payment = page.getByRole('dialog', { name: 'Pay', exact: true })
      await page.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).click()
      await page.getByRole('article', { name: 'Itemized invoice', exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Customize invoice fields', exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Pay $200', exact: true }).click()
      await payment.getByText('For Sophie Kim', { exact: true }).waitFor()
      assert.equal(await payment.getByRole('combobox', { name: 'Paying as', exact: true }).inputValue(), 'preview:sam-kim')
      await payment.getByRole('combobox', { name: 'Sam Kim’s payment method', exact: true }).waitFor()
      assert.equal(await payment.getByRole('textbox', { name: 'Name on card', exact: true }).count(), 0)
      await payment.getByRole('combobox', { name: 'Paying as', exact: true }).selectOption('preview:sophie')
      await payment.getByText('No saved payment method for Sophie Kim. Payment methods are managed on the payer’s account.', { exact: true }).waitFor()
      assert.equal(await payment.getByRole('button', { name: 'Pay' }).isDisabled(), true)
      assert.equal(await payment.getByRole('button', { name: 'Open Sam Kim’s account', exact: true }).count(), 0, 'Do not send another payer to Sam')
      await payment.getByRole('button', { name: 'Close', exact: true }).click()
      await page.getByRole('button', { name: 'Back to invoices', exact: true }).click()
      await page.getByRole('button', { name: 'Pay $200', exact: true }).click()
      await payment.getByRole('button', { name: 'Pay' }).click()
      await page.getByRole('button', { name: 'View invoice DEMO-1003', exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: /^Pay / }).count(), 0, 'Pay disappears after payment')
      assert.equal(new URL(page.url()).searchParams.get('student'), 'preview:sophie', 'Payment keeps Sophie context')
      await page.screenshot({ path: `/tmp/odeon-child-billing-${version || 'v1'}-${width}.png`, fullPage: true })
      // Sam has the payment-method action; no special student return path.
      await page.goto(`${base}?${new URLSearchParams({ prototype: version || 'v1', view: 'staff', account: 'preview:kim', section: 'billing' })}`)
      await summary.getByRole('button', { name: 'Payment methods', exact: true }).click()
      const methods = page.getByRole('region', { name: 'Payment methods', exact: true })
      await methods.getByRole('textbox', { name: 'Name on card', exact: true }).fill('Taylor Kim')
      await methods.getByRole('checkbox', { name: 'I am authorized to use this card', exact: true }).check()
      await methods.getByRole('button', { name: 'Add card', exact: true }).click()
      await methods.getByText('Name on card: Taylor Kim', { exact: false }).waitFor()
      await methods.getByRole('button', { name: 'Remove Visa ···· 4242', exact: true }).first().click()
      await page.getByRole('button', { name: 'Confirm remove card', exact: true }).click()
      await page.getByRole('dialog', { name: 'Remove saved card', exact: true }).waitFor({ state: 'hidden' })
      await methods.getByRole('button', { name: 'Remove Visa ···· 4242', exact: true }).click()
      await page.getByRole('button', { name: 'Confirm remove card', exact: true }).click()
      await page.getByRole('dialog', { name: 'Remove saved card', exact: true }).waitFor({ state: 'hidden' })
      await methods.getByRole('button', { name: 'Remove Mastercard ···· 4444', exact: true }).click()
      await page.getByRole('button', { name: 'Confirm remove card', exact: true }).click()
      await page.getByRole('dialog', { name: 'Remove saved card', exact: true }).waitFor({ state: 'hidden' })
      await methods.getByRole('button', { name: 'Back to billing', exact: true }).click()
      await page.getByRole('button', { name: 'Pay $200', exact: true }).first().click()
      await payment.getByRole('button', { name: 'Open Sam Kim’s account', exact: true }).waitFor()
      assert.equal(await payment.getByRole('button', { name: 'Pay' }).isDisabled(), true)
      await payment.getByRole('button', { name: 'Open Sam Kim’s account', exact: true }).click()
      await methods.waitFor()
      assert.equal(await page.getByRole('dialog', { name: 'Pay', exact: true }).count(), 0, 'Missing-card action closes payment before navigation')
      await methods.getByRole('button', { name: 'Back to billing', exact: true }).click()
      await page.getByRole('heading', { name: 'Sam Kim', exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Back to Sophie Kim', exact: true }).count(), 0)
      assert.deepEqual(errors, [])
      assert.deepEqual(apis, [])
      console.log(`PASS ${version || 'v1'} ${width}px: child invoice payments, explicit payer, account-only methods and missing-card guidance`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
